def load(name, fixture_dir=FIXTURE_DIR):
    text = (Path(fixture_dir) / name).read_text()
    return json.loads(text), text


def inputs(tag, fixture_dir=FIXTURE_DIR):
    inventory, inventory_text = load(f"inventory-{tag}.json", fixture_dir)
    o10, _ = load(f"o10-overlay-{tag}.json", fixture_dir)
    m3, _ = load("claims/m3.json", fixture_dir)
    return inventory, inventory_text, o10, m3


def generated_overlay(tag, src=CHAIN_SRC, mutate=MUTATE_RS, fixture_dir=FIXTURE_DIR):
    inventory, _, o10, m3 = inputs(tag, fixture_dir)
    return overlay(inventory, o10, m3, source_rows(src), gated_kind_admitted("spork", src), SEEDS,
                   bank_names(mutate))


def overlay_path(tag, fixture_dir=FIXTURE_DIR):
    return Path(fixture_dir) / f"o2b4-overlay-{tag}.json"


def load_history(path=HISTORY):
    try:
        return json.loads(Path(path).read_text())
    except FileNotFoundError:
        return {"floors": {}, "bank": []}


def generated_floors(tag, overlay_text, fixture_dir=FIXTURE_DIR, registry_path=REGISTRY):
    _, inventory_text, _, _ = inputs(tag, fixture_dir)
    rows = registry(registry_path)
    planted = {t for t, p in rows.items() if p}
    return floors(json.loads(overlay_text), inventory_text, overlay_text, set(rows) - planted)


def o2b4_overlay(args):
    text = dumps(generated_overlay(args.tag))
    if args.write:
        overlay_path(args.tag).write_text(text)
        print(f"l3-census: wrote {overlay_path(args.tag)}")
    else:
        print(text, end="")
    return 0


def o2b4_floors(args):
    overlay_text = overlay_path(args.tag).read_text()
    fl = generated_floors(args.tag, overlay_text)
    history = load_history()
    if problems := history_problems(history["floors"], fl):
        # A body change at a recorded version: refused until its floor_version is bumped.
        recorded = [p for p in problems if "changed at" in p]
        if recorded:
            print("l3-census: o2b4-floors refused:", *recorded, sep="\n  ", file=sys_stderr())
            return 1
    if not args.write:
        for target, f in sorted(fl.items()):
            print(f"== {target}\n{dumps(f)}", end="")
        return 0
    CENSUS_DIR.mkdir(parents=True, exist_ok=True)
    for target, f in sorted(fl.items()):
        (CENSUS_DIR / f"{target}.floor.json").write_text(dumps(f))
        print(f"l3-census: wrote node-l1/census/{target}.floor.json")
    bank = json.loads(overlay_text)["bank"]
    if bank[:len(history["bank"])] != history["bank"]:
        print("l3-census: o2b4-floors refused: BANK does not extend the recorded bank", file=sys_stderr())
        return 1
    HISTORY.write_text(dumps({"floors": history_with(history["floors"], fl), "bank": bank}))
    print("l3-census: wrote node-l1/census/floor-versions.json")
    return 0


def sys_stderr():
    import sys
    return sys.stderr


def head_sha(root=ROOT):
    import subprocess
    return subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True,
                          check=True).stdout.strip()


def check_problems(tag, reach=None, head=None, *, root=ROOT):
    """Every o2b4-check problem (§1.4), the overlay and floors regenerated from this tree."""
    problems = []
    inventory, inventory_text, o10, m3 = inputs(tag)
    path = overlay_path(tag)
    if not path.exists():
        return [f"{path.name} does not exist"]
    overlay_text = path.read_text()
    ov = json.loads(overlay_text)
    if overlay_text != dumps(generated_overlay(tag)):
        problems.append(f"{path.name} does not regenerate from the rules and the inventory")
    src = source_rows()
    problems += overlay_problems(ov, inventory, m3, o10, src_rows=src, root=root)
    rows = registry()
    fl = generated_floors(tag, overlay_text)
    on_disk = {p.name[:-len(".floor.json")]: p for p in CENSUS_DIR.glob("*.floor.json")} if CENSUS_DIR.is_dir() else {}
    for target in sorted(set(on_disk) - set(fl)):
        why = "a planted target" if rows.get(target) else "a target no profile's floor is generated for"
        problems.append(f"node-l1/census/{target}.floor.json: a floor for {why}")
    for target, f in sorted(fl.items()):
        p = on_disk.get(target)
        if p is None:
            problems.append(f"node-l1/census/{target}.floor.json: missing")
        elif p.read_text() != dumps(f):
            problems.append(f"node-l1/census/{target}.floor.json does not regenerate byte for byte")
    on_disk_floors = {t: json.loads(p.read_text()) for t, p in on_disk.items()}
    problems += floor_problems(on_disk_floors, ov, inventory, rows)
    history = load_history()
    problems += history_problems(history["floors"], fl)
    tree_bank = bank_names()
    problems += bank_problems(ov["bank"], tree_bank, history["bank"])
    if reach is not None:
        problems += reach_problems(reach, ov, head or head_sha(root), tree_bank)
    return problems


def o2b4_check(args):
    reach = json.loads(Path(args.reach).read_text()) if args.reach else None
    problems = check_problems(args.tag, reach, args.head)
    path = overlay_path(args.tag)
    ov = json.loads(path.read_text()) if path.exists() else None
    if ov is not None:
        print(f"l3-census: o2b4 encoding gaps (report-only, never counted as reached; DEC-1514, DEC-1524, DEC-1526, DEC-1530, "
              f"DEC-1567, "
              f"{ENCODING_GAP_BL}):")
        if reach is None:
            for k, p, bl, home in encoding_gaps(ov):
                print(f"  {k} on {p}: {bl}, home {home}")
        else:
            counts, gaps = reach_summary(reach, ov)
            for k, p, bl, credited in gaps:
                print(f"  {k} on {p}: {bl}, {len(credited)} seeds credit it" + (f" ({', '.join(credited)})" if credited else ""))
            for p, (hit, total) in counts.items():
                print(f"l3-census: o2b4 {p}: {hit} of {total} required inventory cells reached")
        print(f"l3-census: o2b4 coverage gaps (report-only, never counted as reached; {COVERAGE_GAP_DEC}):")
        if reach is None:
            for k, p, dec in coverage_gaps(ov):
                print(f"  {k} on {p}: {dec}")
        else:
            for k, p, dec, credited in coverage_gap_credit(reach, ov):
                print(f"  {k} on {p}: {dec}, {len(credited)} seeds credit it" + (f" ({', '.join(credited)})" if credited else ""))
    if problems:
        print(f"l3-census: o2b4-check fails ({len(problems)}):", *problems, sep="\n  ", file=sys_stderr())
        return 1
    for p in PROFILE_NAMES:
        n = sum(e[p]["status"] == "required" for s in ("rows", "script_errors") for e in ov[s])
        print(f"l3-census: o2b4 {p}: {n} inventory keys required")
    print("l3-census: o2b4-check passed" + (" (with the reach report)" if reach else " (no --reach)"))
    return 0


