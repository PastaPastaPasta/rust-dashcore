# --- Reading the tree ----------------------------------------------------------------------------

def function_of(key):
    """The function a row key names: `validation.cpp:CheckBlock#4:...` -> CheckBlock;
    `tx_verify.cpp:Consensus::CheckTxInputs#1:...` -> Consensus::CheckTxInputs."""
    body = key.split(":", 1)[1]
    return re.split(r"#|@", body, maxsplit=1)[0]


def edge_callee(key):
    """An E row's callee: `validation.cpp:CheckBlock@E:CheckBlockHeader` -> CheckBlockHeader."""
    return key.split("@", 1)[1].split(":", 1)[1]


# 4c's leg-B stats keys: `legb_` literals that are no census row.
LEGB_STATS_KEYS = frozenset({"legb_refused_open", "legb_seeds", "legb_share", "legb_step_share"})


def source_rows(src=CHAIN_SRC):
    """The named census rows in node-l1's chain source: `.row("x")` literals, the `&str` row
    constants (4c's `LEGB_*`) and every other `legb_` literal but the stats keys (legb.rs's rows,
    run.rs's `row(match ...)` arms)."""
    names = set()
    for p in sorted(Path(src).rglob("*.rs")):
        text = p.read_text()
        names |= set(re.findall(r'\.row\(\s*"([a-z0-9_]+)"\s*\)', text))
        names |= set(re.findall(r'pub const LEGB_[A-Z_]+: &str = "([a-z0-9_]+)";', text))
        names |= set(re.findall(r'"(legb_[a-z0-9_]+)"', text)) - LEGB_STATS_KEYS
    return names


def gated_kind_admitted(kind, src=CHAIN_SRC):
    file, pattern = GATED_KINDS[kind]
    return bool(pattern.search((Path(src) / file).read_text()))


def bank_names(path=MUTATE_RS):
    """`BANK`'s operator names in slot order (node-l1 chain/mutate/bank.rs: each entry an
    `Operator { name: "...", ... }` or a `script_error!("...", ...)`)."""
    text = Path(path).read_text()
    m = re.search(r"pub const BANK: &\[Operator\] = &\[(.*?)\n\];", text, re.S)
    if m is None:
        raise ValueError(f"{path} has no BANK")
    return [a or b for a, b in re.findall(r'Operator \{\s*name: "([a-z0-9_]+)"|script_error!\(\s*"([a-z0-9_]+)"',
                                          m.group(1))]


def registry(path=REGISTRY):
    """targets.toml's chain-v2 targets: name -> planted (bool)."""
    with open(path, "rb") as f:
        raw = tomllib.load(f)
    return {t["name"]: "planted" in t.get("features", []) for t in raw.get("target", [])
            if t.get("encoding") == ENCODING}


