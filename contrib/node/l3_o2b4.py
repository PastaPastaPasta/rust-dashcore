# --- Self-tests (S1-S13) -------------------------------------------------------------------------

def selftest():
    """The o2b4 self-tests: each fixture fails as it must, and the real overlay passes. Returns
    the names of the cases that did not behave."""
    import copy
    import tempfile
    failures = []
    inventory, inventory_text, o10, m3 = inputs("v24.0.0")
    src = source_rows() | {"spork_on_then_cl_record"} - {"spork_on_then_cl_record"}
    # S15: run.rs's mirror-restart rows are rows; leg B's stats keys are not.
    if not {"legb_kill_after_mirror", "legb_clean_after_mirror"} <= src or src & LEGB_STATS_KEYS:
        failures.append("S15 leg B's rows in source_rows")
    with tempfile.TemporaryDirectory() as tmp:
        seeds = {}
        base = overlay(inventory, o10, m3, src, False, seeds, ["x_a", "x_b"])
        for section, name in (("rows", "key"), ("script_errors", "error"), ("named_rows", "row"), ("ops", "op"),
                              ("rejects", "reject")):
            for e in base[section]:
                for p in PROFILE_NAMES:
                    if e[p]["status"] == "required" and "basis" not in e[p]:
                        e[p]["seed"] = "s.prog"
        Path(tmp, "s.prog").write_text("")

        def problems(ov, rows=src):
            return overlay_problems(ov, inventory, m3, o10, src_rows=rows, seed_dir=tmp)

        def expect(name, ov, text, rows=src):
            got = problems(ov, rows)
            if not any(text in g for g in got):
                failures.append(f"{name} (got {got[:3]})")

        if p0 := problems(base):
            failures.append(f"baseline overlay fails: {p0[:5]}")

        def edited(f):
            ov = copy.deepcopy(base)
            f(ov)
            return ov
        req_row = next(e for e in base["rows"] if e["key"] == "validation.cpp:CheckBlock#4:bad-blk-sigops")
        idx = base["rows"].index(req_row)
        expect("S1 a dropped inventory row", edited(lambda ov: ov["rows"].pop(idx)), "the overlay leaves out")
        expect("S2 a dropped script error", edited(lambda ov: ov["script_errors"].pop(1)), "left out")
        expect("S3 a required row flipped out (M3)", edited(lambda ov: ov["rows"][idx].update(
            S0={"status": "out_of_profile", "code": "par_gt", "home": "profile:S1"})), "never narrow")
        expect("S3b a free-text reason", edited(lambda ov: ov["rows"][idx].update(
            S0={"status": "out_of_profile", "code": "too slow", "home": "profile:S1"})), "without a reason code")
        cis = next(i for i, e in enumerate(base["rows"]) if e["key"] == SCRIPT_ROW)
        expect("S4 a code whose fact doesn't hold", edited(lambda ov: ov["rows"][cis].update(
            S0={"status": "out_of_profile", "code": "par_gt", "home": "profile:S1"})), "never narrow")
        f_idx = next(i for i, e in enumerate(base["rows"]) if e["key"] == "validation.cpp:AcceptBlock@F4850")
        expect("S5 a test home with no fn", edited(lambda ov: ov["rows"][f_idx]["S0"].update(
            home="test:dashd-chainstate/src/chain/tests/blocks.rs::no_such_test")), "names no test fn")
        x_idx = next(i for i, e in enumerate(base["rows"]) if e["key"] == "validation.cpp:ConnectBlock#10:bad-cb-payee")
        expect("S5b an m3 home borrowing another key", edited(lambda ov: ov["rows"][x_idx]["S0"].update(
            home="m3:validation.cpp:ConnectBlock#1:bad-chainlock")), "borrows")
        expect("S5c a profile home not required there", edited(lambda ov: ov["rows"][cis]["S1"].update(
            home="profile:S2")), "not required there")
        e_idx = next(i for i, e in enumerate(base["rows"]) if e["key"] == "validation.cpp:CheckBlock@E:CheckBlockHeader")
        expect("S5d a callee home not required", edited(lambda ov: ov["rows"][e_idx]["S0"].update(
            home="callee:validation.cpp:CheckBlock#2:bad-cb-missing,validation.cpp:ConnectBlock#7:block-validation-failed")),
            "is not required on S0")
        expect("S6 an unknown inventory key", edited(lambda ov: ov["rows"].append(
            {**copy.deepcopy(base["rows"][idx]), "key": "validation.cpp:CheckBlock#99:bad-nothing"})),
            "not an inventory key")
        expect("S6b an unknown named row", edited(lambda ov: ov["named_rows"].append(
            {**copy.deepcopy(base["named_rows"][0]), "row": "no_such_row"})), "not in node-l1's chain source")
        expect("S6c an unknown op", edited(lambda ov: ov["ops"].append(
            {**copy.deepcopy(base["ops"][0]), "op": "block:maybe"})), "not a <kind>:<class>")
        expect("S6d a source row the overlay leaves out", base, "in the source, not in the overlay",
               rows=src | {"a_new_row"})
        expect("S10 a required cell without its seed file", edited(lambda ov: ov["rows"][idx]["S0"].update(
            seed="missing.prog")), "does not exist")
        # S16 (OD-L3-165): the basis "run" is exactly the 12 leg-B rows on diff_chain_prodflush.
        run_cells = sorted((e["row"], p) for e in base["named_rows"] for p in PROFILE_NAMES
                           if e[p].get("basis") == "run")
        want_run = sorted((r, p) for r in RUN_BASIS_ROWS for p in PROFILE_NAMES
                          if PROFILES[p]["target"] == "diff_chain_prodflush")
        if len(RUN_BASIS_ROWS) != 12 or run_cells != want_run or {p for _, p in run_cells} != {"S0p"}:
            failures.append(f"S16 the run basis cells: {run_cells}")
        n_idx = {e["row"]: i for i, e in enumerate(base["named_rows"])}
        expect("S16b the run basis on an S0 row", edited(lambda ov: ov["named_rows"][n_idx["reorg_3"]].update(
            S0={"status": "required", "basis": "run"})), "only for RUN_BASIS_ROWS")
        expect("S16c the run basis on a leg-B row of another target", edited(
            lambda ov: ov["named_rows"][n_idx["legb_steps"]].update(S0={"status": "required", "basis": "run"})),
            "only for RUN_BASIS_ROWS")
        expect("S16d the run basis on S0p's S0 row", edited(lambda ov: ov["named_rows"][n_idx["reorg_3"]].update(
            S0p={"status": "required", "basis": "run"})), "only for RUN_BASIS_ROWS")
        expect("S16e another basis", edited(lambda ov: ov["named_rows"][n_idx["legb_steps"]].update(
            S0p={"status": "required", "basis": "smoke"})), "only for RUN_BASIS_ROWS")
        # S17 (DEC-1625): S2's row:kill_with_unflushed_entries is the one coverage gap, report-only in
        # the overlay and the floor; S0, S1 and S0p keep the row required, named kill_unflushed.prog.
        kill = "kill_with_unflushed_entries"
        if coverage_gaps(base) != [(f"row:{kill}", "S2", COVERAGE_GAP_DEC)]:
            failures.append(f"S17 the baseline's coverage gaps: {coverage_gaps(base)}")
        if any(seed_of(f"row:{kill}", p, SEEDS) != "kill_unflushed.prog" or base["named_rows"][n_idx[kill]][p]["status"]
               != "required" for p in ("S0", "S1", "S0p")):
            failures.append("S17 the row is not required on S0, S1 and S0p with kill_unflushed.prog")
        s2_floor, s0_floor = floor_body(base, "S2"), floor_body(base, "S0")
        if kill not in s2_floor["report_only"] or kill in s2_floor["require"]["rows"] \
                or kill not in s0_floor["require"]["rows"] or kill in s0_floor["report_only"]:
            failures.append("S17 S2's floor does not report the gap only, or S0's does not require the row")
        expect("S17b the coverage gap turned required (dropped)", edited(lambda ov: ov["named_rows"][n_idx[kill]].update(
            S2={"status": "required", "seed": "s.prog"})), f"row:{kill} on S2: DEC-1625's coverage gap is not marked")
        expect("S17c the coverage gap without its DEC", edited(lambda ov: ov["named_rows"][n_idx[kill]]["S2"].pop("dec")),
               f"row:{kill} on S2: DEC-1625's coverage gap is not marked")
        expect("S17d a coverage gap on another cell", edited(lambda ov: ov["named_rows"][n_idx[kill]].update(
            S0=coverage_gap())), f"row:{kill} on S0: a coverage gap DEC-1625 does not declare")
        expect("S17f a coverage gap on another row", edited(lambda ov: ov["named_rows"][n_idx["reorg_3"]].update(
            S2=coverage_gap())), "row:reorg_3 on S2: a coverage gap DEC-1625 does not declare")
        restart_ok = next(i for i, e in enumerate(base["ops"]) if e["op"] == "restart:ok")
        expect("S17g a coverage gap on an op cell", edited(lambda ov: ov["ops"][restart_ok].update(
            S2=coverage_gap())), "op:restart:ok on S2: a coverage gap DEC-1625 does not declare")
        # The encoding gaps (DEC-1514, DEC-1524, DEC-1526, DEC-1530, DEC-1567; BL-835): only these 16 cells, each with its
        # BL id, none dropped.
        listed = {(k, p) for k, p, _, _ in encoding_gaps(base)}
        if listed != {(k, p) for k, (g, _, _) in ENCODING_GAP.items() for p in g} or len(listed) != 16:
            failures.append(f"S14 the baseline's encoding gaps: {encoding_gaps(base)}")
        # DEC-1567: block:duplicate is reachable by a raw image-block resubmit, and its gap says so.
        if {e[p].get("cite") for e in base["ops"] if e["op"] == "block:duplicate" for p in PROFILE_NAMES} != {
                "DEC-1526, DEC-1530, DEC-1567: no send-again intent; a raw image-block resubmit reaches it but is "
                "pinned to the image"}:
            failures.append("S14l block:duplicate's gaps do not carry DEC-1567's reason")
        gap_key = "validation.cpp:AcceptBlockHeader#1:duplicate"
        gap = next(i for i, e in enumerate(base["rows"]) if e["key"] == gap_key)
        expect("S14b an encoding gap turned required (dropped)", edited(lambda ov: ov["rows"][gap].update(
            S0={"status": "required", "seed": "s.prog"})), "encoding gap is not marked")
        expect("S14c an encoding gap without its BL id", edited(lambda ov: ov["rows"][gap]["S0"].pop("bl")),
               "without its BL id")
        expect("S14d an encoding gap on another cell", edited(lambda ov: ov["rows"][idx].update(
            S0=encoding_gap(gap_key))), "never narrow")
        op_gap = next(i for i, e in enumerate(base["ops"]) if e["op"] == "block:duplicate")
        rej_gap = next(i for i, e in enumerate(base["rejects"]) if e["reject"] == "duplicate")
        expect("S14f an op gap turned required (dropped)", edited(lambda ov: ov["ops"][op_gap].update(
            S1={"status": "required", "seed": "s.prog"})), "op:block:duplicate on S1: DEC-1514's encoding gap is not marked")
        expect("S14g a reject gap without its BL id", edited(lambda ov: ov["rejects"][rej_gap]["S2"].pop("bl", None)),
               "reject:duplicate on S2: an encoding gap without its BL id")
        other_rej = next(i for i, e in enumerate(base["rejects"]) if e["reject"] == "duplicate-invalid")
        expect("S14h a gap cell on a reject not in the list", edited(lambda ov: ov["rejects"][other_rej].update(
            S0={**out("encoding_gap", _HEADER_HOME), "bl": ENCODING_GAP_BL})),
               "reject:duplicate-invalid on S0: out of profile but not an encoding gap")
        expect("S14i an op out of profile with another code", edited(lambda ov: ov["ops"][0].update(
            S0=out("edge", "profile:S1"))), "out of profile but not an encoding gap")
        expect("S14j an op gap whose home names no test fn", edited(lambda ov: ov["ops"][op_gap]["S0"].update(
            home="test:dashd-node/src/sut.rs::no_such_fn")), "names no test fn")
        # Floors.
        fl = floors(base, inventory_text, dumps(base), {"diff_chain_s0", "diff_chain_par", "diff_chain_av"})
        if fp := floor_problems(fl, base, inventory, {}):
            failures.append(f"baseline floors fail: {fp[:3]}")
        s0 = fl["diff_chain_s0"]
        if not s0["require"]["ops"] or s0["bounds"]["legb_share_min"] is not None:
            failures.append("baseline S0 floor: ops or legb_share_min")
        bad = copy.deepcopy(fl)
        bad["diff_chain_s0"]["require"]["inventory"].append("validation.cpp:Nope#1:x")
        bad["diff_chain_s0"]["require"]["ops"] = []
        got = floor_problems(bad, base, inventory, {"diff_chain_par_p3a": True})
        if not any("not an inventory key" in g for g in got):
            failures.append("S6e a floor requiring an unknown key")
        if not any("requires no op" in g for g in got):
            failures.append("S11 an empty require.ops")
        planted = floor_problems({**fl, "diff_chain_par_p3a": fl["diff_chain_s0"]}, base, inventory,
                                 {"diff_chain_par_p3a": True})
        if not any("planted target" in g for g in planted):
            failures.append("S12 a floor for a planted target")
        if not any("no profile names" in g for g in planted):
            failures.append("S12b a floor for a target no profile names")
        hist = history_with({}, fl)
        if history_problems(hist, fl):
            failures.append("baseline history")
        changed = copy.deepcopy(fl)
        changed["diff_chain_s0"]["require"]["rows"] = changed["diff_chain_s0"]["require"]["rows"][1:]
        if not any("changed at floor_version" in g for g in history_problems(hist, changed)):
            failures.append("S8 a body change at a recorded floor_version")
        if not any("not in floor-versions" in g for g in history_problems({}, fl)):
            failures.append("S8b an unrecorded floor_version")
        # S8c (OD-L3-174 N3): a v1 floor, written before declared_gaps, stands by its recorded
        # three-key body, and a change to it is still caught.
        v1 = {t: {**{k: v for k, v in f.items() if k != "declared_gaps"}, "floor_version": 1} for t, f in fl.items()}
        try:
            v1_hist = history_with({}, v1)
            v1_ok, v1_bad = history_problems(v1_hist, v1), history_problems(v1_hist, {
                "diff_chain_s0": {**v1["diff_chain_s0"], "report_only": ["x"]}})
        except KeyError as e:
            v1_ok, v1_bad = [f"KeyError {e}"], []
        if v1_ok or not any("changed at floor_version 1" in g for g in v1_bad):
            failures.append(f"S8c a v1 floor without declared_gaps: {v1_ok[:1]}")
        # A recorded-fixture home whose section lacks the error (OD-L3-132 item 2).
        if fixture_problems(base):
            failures.append(f"baseline fixture coverage: {fixture_problems(base)[:2]}")
        wrong = copy.deepcopy(base)
        for e in wrong["script_errors"]:
            for p in PROFILE_NAMES:
                if e[p].get("home") == POLICY_HOME:
                    e[p]["home"] = f"test:{SCRIPT_TESTS}::verify_script_results"
        if not any("has no record of code" in g for g in fixture_problems(wrong)):
            failures.append("S13 a script error's test home whose section lacks it")
        # Bank.
        if bank_problems(["x_a", "x_b"], ["x_a", "x_b"], ["x_a"]):
            failures.append("baseline bank")
        if not any("append-only" in g for g in bank_problems(["x_b", "x_a"], ["x_b", "x_a"], ["x_a", "x_b"])):
            failures.append("S9 a reordered bank")
        if not any("append-only" in g for g in bank_problems(["x_a"], ["x_a"], ["x_a", "x_b"])):
            failures.append("S9b a truncated bank")
        if not any("not mutate.rs" in g for g in bank_problems(["x_a"], ["x_a", "x_b"], [])):
            failures.append("S9c the overlay's bank differs from mutate.rs's")
        # Reach: the baseline runs every profile's target, each seed done.
        targets = [base["profiles"][p]["target"] for p in PROFILE_NAMES]
        runs = {}
        for p in PROFILE_NAMES:
            census = {"inventory": {}, "rows": {}, "ops": {}, "rejects": {}, "end": "Done"}
            for section, name, m in (("rows", "key", "inventory"), ("script_errors", "error", "inventory"),
                                     ("named_rows", "row", "rows"), ("ops", "op", "ops"),
                                     ("rejects", "reject", "rejects")):
                for e in base[section]:
                    if e[p]["status"] == "required":
                        census[m][f"script:{e[name]}" if section == "script_errors" else e[name]] = 1
            runs[p] = {"s.prog": census}
        reach = {"schema": REACH_SCHEMA, "head": "h" * 40, "bank": ["x_a", "x_b"], "g_enc4": "pass",
                 "targets": targets, "profiles": runs}
        fake_seeds = lambda target: {"s.prog"}
        if rp := reach_problems(reach, base, "h" * 40, ["x_a", "x_b"], fake_seeds):
            failures.append(f"baseline reach: {rp[:3]}")
        # S10f-S10i (OD-L3-171 (2)): an empty report, an omitted target, an omitted profile and a
        # seed that does not end done each fail; none passes by skipping a profile.
        empty = {**reach, "targets": [], "profiles": {}}
        if len([g for g in reach_problems(empty, base, "h" * 40, ["x_a", "x_b"], fake_seeds)
                if "does not run" in g or "has no" in g]) != 2 * len(PROFILE_NAMES):
            failures.append("S10f an empty reach report")
        no_target = {**reach, "targets": [t for t in targets if t != base["profiles"]["S1"]["target"]]}
        if not any("does not run S1's target" in g for g in reach_problems(no_target, base, "h" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10g a reach report omitting a target")
        no_profile = copy.deepcopy(reach)
        del no_profile["profiles"]["S2"]
        if not any("has no S2 run" in g for g in reach_problems(no_profile, base, "h" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10h a reach report omitting a profile")
        not_done = copy.deepcopy(reach)
        not_done["profiles"]["S0p"]["s.prog"]["end"] = "Unexpected(\"block\")"
        if not any("s.prog on S0p ends" in g for g in reach_problems(not_done, base, "h" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10i a reach seed that does not end done")
        # S10j (OD-L3-174 N2): a profile's seeds must be the tree's for its target, so a
        # truncated report (or one with a seed the tree lacks) fails.
        truncated = lambda target: {"s.prog", "t.prog"} if target == base["profiles"]["S2"]["target"] else {"s.prog"}
        if not any("S2 seeds are not the tree's" in g and "1 missing ['t.prog']" in g
                   for g in reach_problems(reach, base, "h" * 40, ["x_a", "x_b"], truncated)):
            failures.append("S10j a reach report missing a tree seed")
        extra = copy.deepcopy(reach)
        extra["profiles"]["S1"]["u.prog"] = extra["profiles"]["S1"]["s.prog"]
        if not any("S1 seeds are not the tree's" in g and "1 not in the tree ['u.prog']" in g
                   for g in reach_problems(extra, base, "h" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10j a reach report with a seed the tree lacks")
        missing = copy.deepcopy(reach)
        del missing["profiles"]["S0"]["s.prog"]["inventory"]["validation.cpp:CheckBlock#4:bad-blk-sigops"]
        if not any("did not reach" in g for g in reach_problems(missing, base, "h" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10b a reach report missing a required cell")
        if not any("not h" in g or "for head" in g for g in reach_problems(reach, base, "g" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10c a stale head")
        if not any("BANK" in g for g in reach_problems(reach, base, "h" * 40, ["x_a"], fake_seeds)):
            failures.append("S10d a stale bank")
        if not any("G-ENC-4" in g for g in reach_problems({**reach, "g_enc4": "fail"}, base, "h" * 40, ["x_a", "x_b"], fake_seeds)):
            failures.append("S10e G-ENC-4 failed")
        # S14e: a seed crediting an encoding gap counts nothing as reached, and the gap is still listed.
        credited = copy.deepcopy(reach)
        credited["profiles"]["S0"]["s.prog"]["inventory"][gap_key] = 1
        before, _ = reach_summary(reach, base)
        after, gaps = reach_summary(credited, base)
        if after != before:
            failures.append("S14e a credited encoding gap changed what counts as reached")
        # S14m (DEC-1567): the credit is a reach problem, reached-while-declared with its seeds.
        if reach_problems(credited, base, "h" * 40, ["x_a", "x_b"], fake_seeds) != [
                f"{gap_key} on S0: reached-while-declared, a {ENCODING_GAP_BL} encoding gap its seeds s.prog credit"]:
            failures.append("S14m a credited encoding gap is not reached-while-declared")
        if (gap_key, "S0", ENCODING_GAP_BL, ["s.prog"]) not in gaps or len(gaps) != 16:
            failures.append(f"S14e the credited gap is not listed: {gaps}")
        # S17e (DEC-1625): the coverage gap is never a required cell: a report whose seeds credit
        # the row on neither S0 nor S2 misses S0's cell alone; a seed crediting the gap is
        # reached-while-declared.
        uncredited = copy.deepcopy(reach)
        for p in ("S0", "S2"):
            uncredited["profiles"][p]["s.prog"]["rows"].pop("kill_with_unflushed_entries", None)
        if [g for g in reach_problems(uncredited, base, "h" * 40, ["x_a", "x_b"], fake_seeds)
                if "kill_with_unflushed_entries" in g] != [
                "kill_with_unflushed_entries on S0: its seed s.prog did not reach it in Core's session"]:
            failures.append("S17e the coverage gap counts as a required cell")
        cov = copy.deepcopy(reach)
        cov["profiles"]["S2"]["s.prog"]["rows"]["kill_with_unflushed_entries"] = 1
        if reach_problems(cov, base, "h" * 40, ["x_a", "x_b"], fake_seeds) != [
                "row:kill_with_unflushed_entries on S2: reached-while-declared, a DEC-1625 coverage gap its seeds "
                "s.prog credit"]:
            failures.append("S17e a credited coverage gap is not reached-while-declared")
        if coverage_gap_credit(cov, base) != [("row:kill_with_unflushed_entries", "S2", COVERAGE_GAP_DEC, ["s.prog"])] \
                or coverage_gap_credit(reach, base) != [("row:kill_with_unflushed_entries", "S2", COVERAGE_GAP_DEC, [])]:
            failures.append("S17e the coverage gap's credit is not listed")
        # S14k: an op or reject gap's credit reads its own census map.
        credited["profiles"]["S0"]["s.prog"]["ops"]["block:duplicate"] = 1
        credited["profiles"]["S0"]["s.prog"]["rejects"]["duplicate"] = 1
        after, gaps = reach_summary(credited, base)
        if after != before:
            failures.append("S14k a credited op or reject gap changed what counts as reached")
        declared = [g.split(" on ")[0] for g in reach_problems(credited, base, "h" * 40, ["x_a", "x_b"], fake_seeds)
                    if "reached-while-declared" in g]
        if sorted(declared) != sorted([gap_key, "op:block:duplicate", "reject:duplicate"]):
            failures.append(f"S14m credited op and reject gaps are not each reached-while-declared: {declared}")
        for k in ("op:block:duplicate", "reject:duplicate"):
            if (k, "S0", ENCODING_GAP_BL, ["s.prog"]) not in gaps or (k, "S1", ENCODING_GAP_BL, []) not in gaps:
                failures.append(f"S14k {k}'s credit is not listed: {gaps}")
    return failures
