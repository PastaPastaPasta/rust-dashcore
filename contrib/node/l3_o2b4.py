def code_holds(code, row, profile, profiles, overlay_rows):
    """Whether the inventory fact `code` needs holds for `row` on `profile` (§1.1's code table)."""
    guards, par = row.get("guards") or {}, profiles[profile]["par"]
    key = row["key"]
    if code == "par_gt":
        return "par_gt" in guards and par <= guards["par_gt"]
    if code == "par":
        return "par" in guards and par != guards["par"]
    if code == "dip1_active":
        return guards.get("measured") in DIP1_GUARDS
    if code == "budget_outputs":
        return any("@BO" in c for c in row.get("covered_by") or [])
    if code in ("network", "checkpoint", "dip3", "mnsync"):
        return code in guards
    if code == "islock":
        return key == ISLOCK_KEY
    if code == "evo":
        return row.get("decision") == "X-evo" or row.get("wrapper") == "e-evo" or row.get("kind") == "E-evo"
    if code == "unreachable":
        return row.get("decision") == "X-unr"
    if code == "fault":
        return row.get("kind") == "F"
    if code == "edge":
        return row.get("kind") == "E"
    if code == "encoding_gap":
        return profile in gap_profiles(key)
    if code == "no_callee":
        return row.get("kind") == "W" and not any(
            overlay_rows[k][profile]["status"] == "required" for k in overlay_rows
            if function_of(k) == row.get("callee") and k != key and "@" not in k)
    return False


def test_home_exists(home, root=ROOT):
    path, _, fn = home[len("test:"):].partition("::")
    p = Path(root) / path
    return p.is_file() and re.search(rf"\bfn {re.escape(fn)}\b", p.read_text()) is not None


SCRIPT_TESTS = "dash-consensus/tests/script_core_recorded.rs"
SCRIPT_FIXTURE = "dash-consensus/tests/data/script_recorded.json"


def fixture_problems(ov, root=ROOT):
    """A script error whose home is a recorded-fixture test fn: the error's code must have a record
    in the section that fn runs (`run_verify("<section>", ..)`), so a home in the wrong section is
    caught beyond the fn's existence."""
    problems, cache = [], {}

    def section_of(fn):
        if fn not in cache:
            m = re.search(rf'\bfn {re.escape(fn)}\(\)\s*\{{\s*run_\w+\(\s*"(\w+)"',
                          (Path(root) / SCRIPT_TESTS).read_text())
            cache[fn] = m.group(1) if m else None
        return cache[fn]

    fixture = json.loads((Path(root) / SCRIPT_FIXTURE).read_text())
    codes = {e["text"]: e["code"] for e in fixture["error_strings"]}
    for e in ov.get("script_errors", []):
        for p in PROFILE_NAMES:
            home = str(e.get(p, {}).get("home", ""))
            if not home.startswith(f"test:{SCRIPT_TESTS}::"):
                continue
            fn = home.split("::", 1)[1]
            section, code = section_of(fn), codes.get(e["error"])
            if section is None:
                problems.append(f"script error {e['error']!r} on {p}: {fn} runs no recorded section")
            elif code is None:
                problems.append(f"script error {e['error']!r}: not in the fixture's error_strings")
            elif not any(rec.get("error") == code for rec in fixture.get(section, [])):
                problems.append(f"script error {e['error']!r} on {p}: {fn}'s section {section} "
                                f"has no record of code {code}")
    return sorted(set(problems))


def home_problem(home, where, profile, ov_index, m3_keys, o10_keys, root=ROOT):
    """Why `home` doesn't resolve (None when it does)."""
    if not isinstance(home, str) or ":" not in home:
        return f"{where}: no home"
    kind, _, rest = home.partition(":")
    if kind == "profile":
        cell = ov_index.get(where, {}).get(rest)
        if rest not in PROFILE_NAMES or cell is None or cell["status"] != "required":
            return f"{where} on {profile}: home {home} is not required there"
    elif kind == "m3":
        if rest not in m3_keys:
            return f"{where} on {profile}: home {home} has no m3.json entry"
        if rest != where:
            return f"{where} on {profile}: home {home} borrows another key's entry"
    elif kind == "o10":
        if rest not in o10_keys or rest != where:
            return f"{where} on {profile}: home {home} is not this key's o10 overlay entry"
    elif kind == "test":
        if not test_home_exists(home, root):
            return f"{where} on {profile}: home {home} names no test fn"
    elif kind == "callee":
        keys = [k for k in rest.split(",") if k]
        if not keys:
            return f"{where} on {profile}: home {home} names no callee row"
        for k in keys:
            if ov_index.get(k, {}).get(profile, {}).get("status") != "required":
                return f"{where} on {profile}: callee {k} is not required on {profile}"
    else:
        return f"{where} on {profile}: unknown home kind {kind!r}"
    return None


