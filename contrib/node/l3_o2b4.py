def overlay_problems(ov, inventory, m3, o10, *, src_rows, seed_dir=SEED_DIR, root=ROOT):
    """Why `ov` does not stand over a10's `inventory` (§1.4 checks 1-5), whatever wrote it."""
    problems = []
    if ov.get("schema") != OVERLAY_SCHEMA:
        problems.append(f"the overlay's schema is not {OVERLAY_SCHEMA}")
    if ov.get("provenance", {}).get("commit") != inventory["provenance"]["commit"]:
        problems.append("the overlay's commit is not the inventory's")
    profiles = ov.get("profiles") or {}
    if tuple(profiles) != PROFILE_NAMES:
        problems.append(f"the overlay's profiles are not {list(PROFILE_NAMES)}")
        return problems
    inv = {r["key"]: r for r in inventory["rows"]}
    m3_keys = {r["key"] for r in m3["rows"]} | {d["key"] for d in m3["deferred"] if "key" in d}
    o10_keys = {r["key"] for r in o10["rows"]}
    # 1. Coverage: every key once, every profile cell.
    keys = [e.get("key") for e in ov.get("rows", [])]
    for k in sorted(set(inv) - set(keys)):
        problems.append(f"{k}: an inventory row the overlay leaves out")
    for k in sorted({k for k in keys if keys.count(k) > 1}):
        problems.append(f"{k}: twice in the overlay")
    for k in sorted(set(keys) - set(inv)):
        problems.append(f"{k}: not an inventory key")
    errors = [e.get("error") for e in ov.get("script_errors", [])]
    for e in sorted(set(inventory["script_errors"]) - set(errors)):
        problems.append(f"script error {e!r}: left out")
    for e in sorted(set(errors) - set(inventory["script_errors"])):
        problems.append(f"script error {e!r}: not an inventory script error")
    for e in sorted({e for e in errors if errors.count(e) > 1}):
        problems.append(f"script error {e!r}: twice in the overlay")
    index = {e["key"]: e for e in ov.get("rows", []) if e.get("key") in inv}
    index.update({f"script:{e['error']}": e for e in ov.get("script_errors", [])})
    for section, name in (("rows", "key"), ("script_errors", "error"), ("named_rows", "row"), ("ops", "op"),
                          ("rejects", "reject")):
        for e in ov.get(section, []):
            for p in PROFILE_NAMES:
                cell = e.get(p)
                if not isinstance(cell, dict) or cell.get("status") not in ("required", "out_of_profile",
                                                                             "report_only"):
                    problems.append(f"{e.get(name)}: no {p} cell")
                elif cell["status"] == "report_only" and section in ("rows", "script_errors", "rejects"):
                    problems.append(f"{e.get(name)} on {p}: report_only is for named rows and ops")
    for e in ov.get("rows", []):
        k = e.get("key")
        if k in inv and e.get("a10_decision") != inv[k].get("decision", "-"):
            problems.append(f"{k}: the overlay read a10 decision {e.get('a10_decision')!r}, "
                            f"a10 has {inv[k].get('decision', '-')!r}")
    if problems:
        return problems
    # 2. Never narrow, 3. homes.
    for k, e in index.items():
        row = inv.get(k)
        for p in PROFILE_NAMES:
            cell = e[p]
            if cell["status"] != "out_of_profile":
                continue
            code = cell.get("code")
            if code not in CODES:
                problems.append(f"{k} on {p}: out of profile without a reason code ({code!r})")
                continue
            if row is not None and not code_holds(code, row, p, profiles, index):
                problems.append(f"{k} on {p}: {code} does not hold for the row (never narrow, §4.3)")
            if row is None:
                error = k[len("script:"):]
                fact = {"policy_flag": error in POLICY_ONLY, "par4_hides": profiles[p]["par"] > 1}.get(code, False)
                if not fact:
                    problems.append(f"{k} on {p}: {code} does not hold for the script error")
            if code == "encoding_gap" and cell.get("bl") != ENCODING_GAP_BL:
                problems.append(f"{k} on {p}: an encoding gap without its BL id ({ENCODING_GAP_BL})")
            if why := home_problem(cell.get("home"), k, p, index, m3_keys, o10_keys, root):
                problems.append(why)
        if row is not None and starting_rule(row) and all(e[p]["status"] == "out_of_profile" for p in PROFILE_NAMES) \
                and all(str(e[p].get("home", "")).startswith("profile:") for p in PROFILE_NAMES):
            problems.append(f"{k}: out on every profile with only profile homes")
    # An op or reject cell is out of profile only as one of the encoding gaps.
    for section, name in (("ops", "op"), ("rejects", "reject")):
        for e in ov.get(section, []):
            k = f"{name}:{e[name]}"
            index[k] = e
            for p in PROFILE_NAMES:
                cell = e[p]
                if cell["status"] != "out_of_profile":
                    continue
                if cell.get("code") != "encoding_gap" or p not in gap_profiles(k):
                    problems.append(f"{k} on {p}: out of profile but not an encoding gap (never narrow, §4.3)")
                    continue
                if cell.get("bl") != ENCODING_GAP_BL:
                    problems.append(f"{k} on {p}: an encoding gap without its BL id ({ENCODING_GAP_BL})")
                if why := home_problem(cell.get("home"), k, p, index, m3_keys, o10_keys, root):
                    problems.append(why)
    for k, (gap, _, _) in ENCODING_GAP.items():
        for p in gap:
            if index.get(k, {}).get(p, {}).get("code") != "encoding_gap":
                problems.append(f"{k} on {p}: DEC-1514's encoding gap is not marked ({ENCODING_GAP_BL})")
    for section, name, prefix in (("rows", "key", ""), ("script_errors", "error", "script:"),
                                  ("named_rows", "row", "row:"), ("ops", "op", "op:"), ("rejects", "reject", "reject:")):
        for e in ov.get(section, []):
            for p in PROFILE_NAMES:
                declared = section == "named_rows" and p in COVERAGE_GAP_ROWS.get(e[name], ())
                if declared and e[p] != coverage_gap():
                    problems.append(f"{prefix}{e[name]} on {p}: {COVERAGE_GAP_DEC}'s coverage gap is not marked")
                elif not declared and e[p].get("code") == "coverage_gap":
                    problems.append(f"{prefix}{e[name]} on {p}: a coverage gap {COVERAGE_GAP_DEC} does not declare")
    problems += fixture_problems(ov, root)
    # 4. Keys exist.
    for e in ov.get("named_rows", []):
        if e["row"] not in src_rows:
            problems.append(f"named row {e['row']!r} is not in node-l1's chain source")
    for e in ov.get("ops", []):
        kind, _, cls = e["op"].partition(":")
        if kind not in OP_KINDS or cls not in REPLY_CLASSES:
            problems.append(f"op {e['op']!r}: not a <kind>:<class> of step.rs and run.rs")
    for name in sorted(src_rows - {e["row"] for e in ov.get("named_rows", [])}):
        problems.append(f"named row {name!r}: in the source, not in the overlay")
    # 5. Seeds.
    for section, name in (("rows", "key"), ("script_errors", "error"), ("named_rows", "row"), ("ops", "op"),
                          ("rejects", "reject")):
        for e in ov.get(section, []):
            for p in PROFILE_NAMES:
                cell = e[p]
                if cell["status"] == "required" and "basis" in cell:
                    if cell != {"status": "required", "basis": "run"} or not run_basis(section, e[name], p):
                        problems.append(f"{e[name]} on {p}: the basis \"run\" is only for RUN_BASIS_ROWS on "
                                        f"{RUN_BASIS_TARGET} (OD-L3-165)")
                elif cell["status"] == "required":
                    seed = cell.get("seed")
                    if not seed:
                        problems.append(f"{e[name]} on {p}: required without a seed")
                    elif not (Path(seed_dir) / seed).is_file():
                        problems.append(f"{e[name]} on {p}: seed {seed} does not exist")
    return problems


OP_KINDS = ("block", "header", "proposal", "invalidate", "precious", "reconsider", "restart", "flush", "settime",
            "activate", "cl_record", "cl_enforce", "spork")
REPLY_CLASSES = ("ok", "duplicate", "inconclusive", "reject", "down")


def floor_problems(fl, ov, inventory, registry_rows):
    """Floors whose keys don't exist, or a floor for a planted or unknown target (§1.4 checks 4, 6)."""
    problems = []
    inv_keys = {r["key"] for r in inventory["rows"]} | {f"script:{e}" for e in inventory["script_errors"]}
    targets = {prof["target"] for prof in ov["profiles"].values()}
    named = {e["row"] for e in ov["named_rows"]}
    for target, f in sorted(fl.items()):
        if registry_rows.get(target):
            problems.append(f"{target}: a floor for a planted target")
        if target not in targets:
            problems.append(f"{target}: a floor for a target no profile names")
        req_ = f.get("require", {})
        for k in req_.get("inventory", []):
            if k not in inv_keys:
                problems.append(f"{target}: requires {k!r}, not an inventory key or script error")
        for k in req_.get("rows", []):
            if k not in named:
                problems.append(f"{target}: requires row {k!r}, not a named row")
        for k in req_.get("ops", []):
            kind, _, cls = k.partition(":")
            if kind not in OP_KINDS or cls not in REPLY_CLASSES:
                problems.append(f"{target}: requires op {k!r}, not a <kind>:<class>")
        if not req_.get("ops"):
            problems.append(f"{target}: requires no op (C-4e2-fm2)")
    return problems


def bank_problems(ov_bank, tree_bank, history_bank):
    """The overlay's bank is mutate.rs's, in order, and extends the recorded one (append-only)."""
    problems = []
    if list(ov_bank) != list(tree_bank):
        problems.append(f"the overlay's bank {list(ov_bank)} is not mutate.rs's BANK {list(tree_bank)}")
    if list(tree_bank[:len(history_bank)]) != list(history_bank):
        problems.append("BANK does not extend the recorded bank (append-only: no slot moves or goes)")
    return problems


def tree_seeds(target, seed_dir=SEED_DIR):
    """The seed programs chain_reach runs for `target`: tests/chain_seeds/*.prog, chain-v2/*.prog
    and <target>/*.prog, named by their path below the seed directory."""
    return {str(f.relative_to(seed_dir)) for d in (seed_dir, seed_dir / "chain-v2", seed_dir / target)
            for f in d.glob("*.prog")}


def reach_problems(reach, ov, head, tree_bank, seeds_of=tree_seeds):
    """Every required cell's seed credited its key on its profile in Core's session (§5.3), at
    this head and bank, and G-ENC-4 held on the grown bank. The report must run every profile's
    target the overlay names (OD-L3-171 (2)): an omitted target or profile, or an empty report,
    is a problem, never a profile skipped, and so is a profile whose seeds are not the tree's for
    its target (`seeds_of`, OD-L3-174 N2). A seed that does not end done credits nothing (its
    census would be discarded or counted unexpected in a run) and is a problem itself. A seed
    crediting an encoding gap is one too, named reached-while-declared with its seeds (DEC-1567:
    the gap is declared, never silently reached)."""
    problems = []
    if reach.get("schema") != REACH_SCHEMA:
        return [f"the reach report's schema is not {REACH_SCHEMA}"]
    if reach.get("head") != head:
        problems.append(f"the reach report is for head {reach.get('head')!r}, not {head}")
    if reach.get("bank") != list(tree_bank):
        problems.append("the reach report's bank is not mutate.rs's BANK")
    if reach.get("g_enc4") != "pass":
        problems.append(f"G-ENC-4 on the grown bank: {reach.get('g_enc4')!r}")
    runs = reach.get("profiles") or {}
    sections = (("rows", "key", "inventory"), ("script_errors", "error", "inventory"),
                ("named_rows", "row", "rows"), ("ops", "op", "ops"), ("rejects", "reject", "rejects"))
    for p, prof in ov["profiles"].items():
        if prof["target"] not in (reach.get("targets") or []):
            problems.append(f"the reach report does not run {p}'s target {prof['target']}")
        seeds = runs.get(p)
        if not isinstance(seeds, dict) or not seeds:
            problems.append(f"the reach report has no {p} run")
            continue
        tree = seeds_of(prof["target"])
        if set(seeds) != tree:
            lost, extra = sorted(tree - set(seeds)), sorted(set(seeds) - tree)
            problems.append(f"the reach report's {p} seeds are not the tree's for {prof['target']}: "
                            f"{len(lost)} missing {lost[:3]}, {len(extra)} not in the tree {extra[:3]}")
        for name, census in seeds.items():
            if (census or {}).get("end") != "Done":
                problems.append(f"{name} on {p} ends {(census or {}).get('end', 'without an end')!r}, "
                                "not done: it credits nothing")
        for section, name, census_map in sections:
            for e in ov[section]:
                cell = e[p]
                if cell["status"] != "required" or cell.get("basis") == "run":
                    continue
                k = f"script:{e[name]}" if section == "script_errors" else e[name]
                census = seeds.get(cell["seed"])
                count = ((census or {}).get(census_map) or {}).get(k, 0)
                if not (isinstance(count, int) and count >= 1):
                    problems.append(f"{k} on {p}: its seed {cell['seed']} did not reach it in Core's session")
    for k, p, bl, _ in encoding_gaps(ov):
        seeds = runs.get(p)
        if credited := sorted(s for s, c in seeds.items() if gap_credit(c, k)) if isinstance(seeds, dict) else []:
            problems.append(f"{k} on {p}: reached-while-declared, a {bl} encoding gap its seeds "
                            f"{', '.join(credited)} credit")
    for k, p, dec, credited in coverage_gap_credit(reach, ov):
        if credited:
            problems.append(f"{k} on {p}: reached-while-declared, a {dec} coverage gap its seeds "
                            f"{', '.join(credited)} credit")
    return problems


def coverage_gaps(ov):
    """The overlay's coverage-gap cells, (`row:<name>`, profile, DEC), in overlay order."""
    return [(f"row:{e['row']}", p, e[p].get("dec")) for e in ov["named_rows"] for p in PROFILE_NAMES
            if e[p].get("code") == "coverage_gap"]


def coverage_gap_credit(reach, ov):
    """Each coverage gap with the seeds whose census holds its row on its profile."""
    runs = reach.get("profiles") or {}

    def credits(census, row):
        count = ((census if isinstance(census, dict) else {}).get("rows") or {}).get(row, 0)
        return isinstance(count, int) and count >= 1
    return [(k, p, dec, sorted(s for s, c in (runs.get(p) or {}).items() if credits(c, k[len("row:"):])))
            for k, p, dec in coverage_gaps(ov)]


GAP_SECTIONS = (("rows", "key", "", "inventory"), ("ops", "op", "op:", "ops"), ("rejects", "reject", "reject:", "rejects"))


def encoding_gaps(ov):
    """The overlay's encoding-gap cells, (key, profile, BL id, home), in overlay order; an op's key
    is `op:<kind>:<class>` and a reject's `reject:<text>`."""
    return [(prefix + e[name], p, e[p].get("bl"), e[p].get("home"))
            for section, name, prefix, _ in GAP_SECTIONS for e in ov[section] for p in PROFILE_NAMES
            if e[p].get("code") == "encoding_gap"]


def gap_credit(census, key):
    """`key`'s count in a seed's census: an op or reject gap reads its own census map."""
    for _, _, prefix, m in GAP_SECTIONS[1:]:
        if key.startswith(prefix):
            return ((census or {}).get(m) or {}).get(key[len(prefix):], 0)
    return ((census or {}).get("inventory") or {}).get(key, 0)


def reach_summary(reach, ov):
    """{profile: (required cells reached, required cells)} over the inventory sections, and each
    encoding gap's credit in the reach report (the seeds whose census holds its key). A gap cell is
    never a required cell, so its credit never counts as reached (DEC-1514)."""
    runs = reach.get("profiles") or {}
    counts = {}
    for p in PROFILE_NAMES:
        seeds, hit, total = runs.get(p) or {}, 0, 0
        for section, name in (("rows", "key"), ("script_errors", "error")):
            for e in ov[section]:
                if e[p]["status"] != "required":
                    continue
                k = f"script:{e[name]}" if section == "script_errors" else e[name]
                total += 1
                hit += ((seeds.get(e[p]["seed"]) or {}).get("inventory") or {}).get(k, 0) >= 1
        counts[p] = (hit, total)
    gaps = [(k, p, bl, sorted(s for s, c in ((runs.get(p) or {}).items()) if gap_credit(c, k)))
            for k, p, bl, _ in encoding_gaps(ov)]
    return counts, gaps


