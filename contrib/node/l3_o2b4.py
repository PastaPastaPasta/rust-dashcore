def out(code, home, cite=None):
    cell = {"status": "out_of_profile", "code": code, "home": home}
    if cite:
        cell["cite"] = cite
    return cell


def encoding_gap(key):
    _, home, cite = ENCODING_GAP[key]
    return {**out("encoding_gap", home, cite), "bl": ENCODING_GAP_BL}


def gap_or_req(key, profile, seeds):
    return encoding_gap(key) if profile in gap_profiles(key) else req(key, profile, seeds)


def seed_of(key, profile, seeds):
    s = seeds.get(key)
    if isinstance(s, dict):
        s = s.get(profile)
    return s


def req(key, profile, seeds):
    return {"status": "required", "seed": seed_of(key, profile, seeds)}


def evo_home(key, o10, m3_keys):
    return f"o10:{key}" if key in o10 else f"m3:{key}"


def row_cells(row, inventory, o10, m3_keys, seeds, decided=None):
    """{profile: cell} for one inventory row (the §1.2 rule table)."""
    key, kind, decision = row["key"], row.get("kind"), row.get("decision")
    guards, covered = row.get("guards") or {}, row.get("covered_by") or []
    cells = {}
    for p, prof in PROFILES.items():
        par = prof["par"]
        if p in gap_profiles(key):
            cells[p] = encoding_gap(key)
        elif kind in ("E", "E-evo"):
            if decision == "X-unr":
                cells[p] = out("unreachable", f"m3:{key}")
            elif kind == "E-evo":
                cells[p] = out("evo", f"m3:{key}")
            else:
                cells[p] = out("edge", "callee:" + ",".join(edge_homes(key, inventory, p, decided)))
        elif kind == "F":
            cells[p] = out("fault", F_HOMES[key])
        elif decision == "X-unr" and key in DIP3_GATED_UNR:
            cells[p] = out("dip3", evo_home(key, o10, m3_keys), DIP3_GATED_UNR[key])
        elif decision == "X-unr":
            cells[p] = out("unreachable", f"m3:{key}")
        elif decision == "X-evo" or (kind == "W" and row.get("wrapper") == "e-evo"):
            cells[p] = out("evo", evo_home(key, o10, m3_keys))
        elif decision == "X-reg":
            code = next(XREG_CODES[g] for g in guards if g in XREG_CODES)
            cells[p] = out(code, evo_home(key, o10, m3_keys))
        elif decision == "X-cl":
            cells[p] = out("islock", ISLOCK_HOME, "PLAN §4.5 M3 exclusion ISLOCK") if key == ISLOCK_KEY \
                else req(key, p, seeds)
        elif kind == "W":
            callees = [k for k in w_callee_rows(row, inventory) if decided and decided[k][p]["status"] == "required"]
            if callees:
                cells[p] = req(key, p, seeds)
            else:
                first = next(q for q in PROFILES if any(decided[k][q]["status"] == "required"
                                                         for k in w_callee_rows(row, inventory)))
                cells[p] = out("no_callee", f"profile:{first}", NO_CALLEE_CITES.get(key))
        elif decision == "C":
            if "par_gt" in guards and par <= guards["par_gt"]:
                cells[p] = out("par_gt", f"profile:{PAR4[0]}")
            elif "par" in guards and par != guards["par"]:
                cells[p] = out("par", f"profile:{PAR1[0]}")
            elif guards.get("measured") in DIP1_GUARDS:
                cells[p] = out("dip1_active", f"m3:{key}", "DIP0001 at height 1 on regtest")
            elif any("@BO" in c for c in covered):
                cells[p] = out("budget_outputs", f"m3:{key}",
                               "node-l1/src/chain/mutate.rs:156-158 BO_BASE (the budget window's MAX_MONEY mints)")
            else:
                cells[p] = req(key, p, seeds)
        else:
            raise ValueError(f"{key}: no rule for kind {kind!r}, decision {decision!r}")
    return cells


def w_callee_rows(w_row, inventory):
    """The R rows a W row wraps: those of its callee function."""
    return [r["key"] for r in inventory["rows"] if r.get("kind") == "R" and function_of(r["key"]) == w_row["callee"]]


def edge_homes(key, inventory, profile, decided, seen=None):
    """The rows required on `profile` under an E row's callee: its R and W rows, and through its
    own E rows, theirs."""
    callee = edge_callee(key)
    seen = set() if seen is None else seen
    if callee in seen:
        return []
    seen.add(callee)
    out_keys = []
    for r in inventory["rows"]:
        k = r["key"]
        if r.get("kind") in ("R", "W") and function_of(k) == callee and decided[k][profile]["status"] == "required":
            out_keys.append(k)
        elif r.get("kind") == "E" and function_of(k) == callee and r.get("decision") != "X-unr":
            out_keys += edge_homes(k, inventory, profile, decided, seen)
    return sorted(set(out_keys))


def script_cells(error, seeds):
    if error in POLICY_ONLY:
        return {p: out("policy_flag", POLICY_HOME, POLICY_ONLY[error]) for p in PROFILES}
    key = f"script:{error}"
    return {p: req(key, p, seeds) if PROFILES[p]["par"] == 1 else out("par4_hides", f"profile:{PAR1[0]}")
            for p in PROFILES}


def overlay(inventory, o10, m3, src_rows, spork_admitted, seeds=SEEDS, bank=()):
    """The overlay over a10's `inventory` (§1.1)."""
    m3_keys = {r["key"] for r in m3["rows"]} | {d["key"] for d in m3["deferred"] if "key" in d}
    o10_keys = {r["key"] for r in o10["rows"]}
    decided = {}
    rows = inventory["rows"]
    # R and X rows first: W rows and E rows read their callees' cells.
    for r in rows:
        if r.get("kind") not in ("W", "E", "E-evo"):
            decided[r["key"]] = row_cells(r, inventory, o10_keys, m3_keys, seeds)
    for r in rows:
        if r.get("kind") == "W":
            decided[r["key"]] = row_cells(r, inventory, o10_keys, m3_keys, seeds, decided)
    for r in rows:
        if r.get("kind") in ("E", "E-evo"):
            decided[r["key"]] = row_cells(r, inventory, o10_keys, m3_keys, seeds, decided)
    unknown = sorted(src_rows - set(NAMED_ROWS) - set(REPORT_ONLY_ROWS))
    if unknown:
        raise ValueError(f"named rows the rule table does not decide: {unknown}")
    named = []
    for name in sorted(src_rows):
        cells = {}
        for p in PROFILES:
            if p in COVERAGE_GAP_ROWS.get(name, ()):
                cells[p] = coverage_gap()
            elif p in NAMED_ROWS.get(name, ()) and run_basis("named_rows", name, p):
                cells[p] = {"status": "required", "basis": "run"}
            elif p in NAMED_ROWS.get(name, ()):
                cells[p] = req(f"row:{name}", p, seeds)
            elif p in REPORT_ONLY_ROWS.get(name, ()):
                cells[p] = {"status": "report_only"}
            else:
                cells[p] = {"status": "out_of_profile"}
        named.append({"row": name, **cells})
    ops = []
    for kind, (required, reported) in OPS.items():
        if kind in GATED_KINDS and not spork_admitted:
            continue
        for cls in required:
            ops.append({"op": f"{kind}:{cls}", **{p: gap_or_req(f"op:{kind}:{cls}", p, seeds) for p in PROFILES}})
        for cls in reported:
            ops.append({"op": f"{kind}:{cls}", **{p: {"status": "report_only"} for p in PROFILES}})
    return {
        "schema": OVERLAY_SCHEMA,
        "provenance": {"tag": inventory["provenance"]["tag"], "commit": inventory["provenance"]["commit"],
                       "inventory": f"inventory-{inventory['provenance']['tag']}.json", "note": PROVENANCE_NOTE},
        "profiles": PROFILES,
        "rows": [{"key": r["key"], "a10_decision": r.get("decision", "-"), **decided[r["key"]]} for r in rows],
        "script_errors": [{"error": e, **script_cells(e, seeds)} for e in inventory["script_errors"]],
        "named_rows": named,
        "ops": ops,
        "rejects": [{"reject": t, **{p: gap_or_req(f"reject:{t}", p, seeds) for p in PROFILES}} for t in REJECTS],
        "bank": list(bank),
    }


# --- Floors --------------------------------------------------------------------------------------

def floor_body(ov, profile):
    """A floor's require, bounds and report_only for `profile` (§3.1)."""
    def required(entries, name):
        return sorted(e[name] for e in entries if e[profile]["status"] == "required")

    def reported(entries, name):
        return sorted(e[name] for e in entries if e[profile]["status"] == "report_only")
    inventory = required(ov["rows"], "key") + sorted(
        f"script:{e['error']}" for e in ov["script_errors"] if e[profile]["status"] == "required")
    return {
        "require": {"inventory": inventory, "ops": required(ov["ops"], "op"),
                    "rejects": required(ov["rejects"], "reject"), "rows": required(ov["named_rows"], "row")},
        "bounds": {**BOUNDS, "legb_share_min": LEGB_SHARE_MIN.get(profile)},
        # census_floor sums a report-only key over ops by class suffix, so op cells stay in the
        # overlay; the floor reports the named rows no profile requires and the profile's
        # coverage gaps (DEC-1625).
        "report_only": reported(ov["named_rows"], "row"),
        # The profile's encoding gaps, each keyed exactly in its census map, so a census that
        # reaches one reports it reached-while-declared (DEC-1567).
        "declared_gaps": {m: sorted(e[name] for e in ov[section] if e[profile].get("code") == "encoding_gap")
                          for section, name, _, m in GAP_SECTIONS},
    }


FLOOR_BODY = ("require", "bounds", "report_only", "declared_gaps")


def floor_record(f):
    """The body floor-versions.json hashes: a floor written before floor_version 2 has no
    declared_gaps, and its recorded body is the other three keys."""
    return {k: f[k] for k in FLOOR_BODY if k in f}


def body_sha(body):
    return sha256_text(dumps(body))


def floor(ov, profile, inventory_text, overlay_text):
    prof = ov["profiles"][profile]
    body = floor_body(ov, profile)
    return {"schema": FLOOR_SCHEMA, "floor_version": prof["floor_version"], "target": prof["target"],
            "profile": profile, "encoding": ENCODING, "inventory_sha256": sha256_text(inventory_text),
            "overlay_sha256": sha256_text(overlay_text), **body}


def floors(ov, inventory_text, overlay_text, targets):
    """target -> floor, for each profile whose target is a chain-v2 target in the registry."""
    return {prof["target"]: floor(ov, p, inventory_text, overlay_text)
            for p, prof in ov["profiles"].items() if prof["target"] in targets}


def history_problems(history, fl):
    """Why the floors don't stand with floor-versions.json: a (target, version) whose recorded
    body differs, or one not recorded."""
    problems = []
    for target, f in sorted(fl.items()):
        body = floor_record(f)
        got = history.get(target, {}).get(str(f["floor_version"]))
        if got is None:
            problems.append(f"{target}: floor_version {f['floor_version']} is not in floor-versions.json")
        elif got != body_sha(body):
            problems.append(f"{target}: the floor changed at floor_version {f['floor_version']} (bump it)")
    return problems


def history_with(history, fl):
    """floor-versions.json with each floor's (target, version) recorded if it is new."""
    out_h = {t: dict(v) for t, v in history.items()}
    for target, f in sorted(fl.items()):
        body = floor_record(f)
        out_h.setdefault(target, {}).setdefault(str(f["floor_version"]), body_sha(body))
    return {t: dict(sorted(v.items(), key=lambda kv: int(kv[0]))) for t, v in sorted(out_h.items())}


