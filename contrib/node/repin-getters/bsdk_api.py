"""Read base-sdk's struct shapes from its source: fields, getters, setters, constructors.

Everything comes from the source the workspace actually builds (the cargo git checkout of
the pinned rev), never from a hand-kept table, so a re-run after a re-pin sees the new shape.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field

from rustlex import OPEN, Tok, lex, split_top

# Macros whose block form declares the struct and a `new(<every field in order>)`.
CTOR_MACROS = {"impl_new", "codec_base", "codec_type", "codec_payload", "codec_p2p"}

# Packages of base-sdk, by crate name as rustc prints it.
BSDK_PACKAGES = ("dash-num", "dash-p2p-core", "dash-params", "dash-pkc", "dash-pow", "dash-primitives",
                 "dash-types", "dash-script")


@dataclass
class Field:
    name: str
    ty: str
    public: bool
    getter: str | None = None  # "get" (returns &T), "get_copy" (returns T), "method" (hand-written)
    setter: bool = False
    serde_rename: str | None = None
    getter_body: str | None = None  # for hand-written getters
    getter_ret: str | None = None
    getter_name: str | None = None  # when the getter is not named after the field (tuple fields)


@dataclass
class Ctor:
    name: str
    params: list[tuple[str, str]]  # (name, type text)
    # field name -> param name, when the body is a plain `Self { .. }` of the params; else None
    field_map: dict[str, str] | None
    body: str
    # A `Self { .. }` body storing every parameter unchanged and setting the other fields to an
    # expression (`sig: CollateralSig::default()`): field -> param, and field -> that expression.
    partial_map: dict[str, str] | None = None
    reset: dict[str, str] = field(default_factory=dict)


@dataclass
class Struct:
    name: str
    crate: str
    file: str
    line: int
    tuple: bool
    fields: list[Field]
    macro: str | None
    macro_new: bool  # `new` generated by a CTOR_MACROS block form
    ctors: list[Ctor] = field(default_factory=list)
    methods: dict[str, dict] = field(default_factory=dict)

    @property
    def private(self) -> list[Field]:
        return [f for f in self.fields if not f.public]

    def field(self, name: str) -> Field | None:
        for f in self.fields:
            if f.name == name:
                return f
        return None

    def plain_ctor(self) -> Ctor | None:
        """A constructor taking every field, in any order, and storing it unchanged."""
        names = {f.name for f in self.fields}
        best = None
        for c in self.ctors:
            if c.field_map is not None and set(c.field_map) == names and len(c.params) == len(names):
                if c.name == "new":
                    return c
                best = best or c
        return best

    def reset_ctor(self) -> Ctor | None:
        """A constructor storing every field but `reset` ones unchanged, which it sets to an
        expression of its own (the ProTx `new`s reset `sig`). Only for a rebuild whose reset fields are put back (`[[restore]]`)."""
        names = {f.name for f in self.fields}
        for c in self.ctors:
            if c.partial_map is not None and set(c.partial_map) | set(c.reset) == names \
                    and len(c.params) == len(c.partial_map):
                return c
        return None


def _attr_args(toks: list[Tok], src: str, i: int) -> tuple[str, int]:
    """`toks[i]` is `#`; return (attribute body text, index after it)."""
    j = i + 1
    if toks[j].text == "!":
        j += 1
    assert toks[j].text == "["
    end = toks[j].match
    return src[toks[j].start + 1:toks[end].start], end + 1


_GETSET = re.compile(r"getset\s*\((.*)\)", re.S)


def _parse_fields(toks: list[Tok], src: str, lo: int, hi: int, tuple_struct: bool) -> list[Field]:
    out = []
    for n, (a, b) in enumerate(split_top(toks, lo, hi)):
        i = a
        getter = None
        setter = False
        rename = None
        while i < b and toks[i].text == "#":
            body, i = _attr_args(toks, src, i)
            m = _GETSET.search(body)
            if m:
                args = m.group(1)
                if re.search(r"\bget_copy\s*=", args):
                    getter = "get_copy"
                elif re.search(r"\bget\s*=", args):
                    getter = "get"
                if re.search(r"\bset\s*=\s*\"pub", args):
                    setter = True
            m = re.search(r"serde\s*\(\s*rename\s*=\s*\"([^\"]+)\"", body)
            if m:
                rename = m.group(1)
        if i >= b:
            continue
        public = False
        if toks[i].text == "pub":
            public = True
            i += 1
            if i < b and toks[i].text == "(":
                # pub(crate) / pub(super): not public to us
                public = False
                i = toks[i].match + 1
        if tuple_struct:
            out.append(Field(str(n), src[toks[i].start:toks[b - 1].end], public, getter, setter, rename))
        else:
            name = toks[i].text
            ty = src[toks[i + 2].start:toks[b - 1].end]
            out.append(Field(name, ty, public, getter, setter, rename))
    return out


def _enclosing_macro(toks: list[Tok], idx: int) -> tuple[str | None, bool]:
    """Innermost macro invocation group containing token idx: (macro name, has @no_new)."""
    for j in range(idx - 1, -1, -1):
        t = toks[j]
        if t.kind == "punct" and t.text in OPEN and t.match > idx:
            if j >= 2 and toks[j - 1].text == "!" and toks[j - 2].kind == "ident":
                no_new = toks[j + 1].text == "@" and toks[j + 2].text == "no_new"
                return toks[j - 2].text, no_new
            return None, False
    return None, False


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def _parse_impls(toks: list[Tok], src: str, structs: dict[str, Struct]) -> None:
    i = 0
    n = len(toks)
    while i < n:
        t = toks[i]
        if t.kind == "ident" and t.text == "impl" and (i == 0 or toks[i - 1].text not in ("->", "dyn")):
            j = i + 1
            if j < n and toks[j].text == "<":
                depth = 0
                while j < n:
                    if toks[j].text == "<":
                        depth += 1
                    elif toks[j].text == ">":
                        depth -= 1
                        if depth == 0:
                            break
                    elif toks[j].text == ">>":
                        depth -= 2
                        if depth <= 0:
                            break
                    j += 1
                j += 1
            # find the `{` of the impl body
            k = j
            is_trait = False
            while k < n and toks[k].text != "{" and toks[k].text != ";":
                if toks[k].text == "for":
                    is_trait = True
                k += 1
            if k >= n or toks[k].text != "{":
                i = k + 1
                continue
            # self type: last ident at depth 0 before `{` (skipping generics)
            name = None
            depth = 0
            for m in range(j, k):
                tx = toks[m].text
                if tx == "<":
                    depth += 1
                elif tx == ">":
                    depth -= 1
                elif tx == ">>":
                    depth -= 2
                elif tx == "where":
                    break
                elif depth == 0 and toks[m].kind == "ident" and tx not in ("for", "dyn"):
                    name = tx
            if name in structs and not is_trait:
                _parse_impl_body(toks, src, k, structs[name])
            i = toks[k].match + 1
            continue
        i += 1


def _parse_impl_body(toks: list[Tok], src: str, brace: int, st: Struct) -> None:
    i = brace + 1
    end = toks[brace].match
    while i < end:
        t = toks[i]
        if t.text in OPEN and t.match > i and t.text != "(":
            # nested braces at impl level only occur as fn bodies (handled below) or consts
            i = t.match + 1
            continue
        if t.kind == "ident" and t.text == "fn":
            is_pub = any(toks[m].text == "pub" for m in range(max(brace + 1, i - 4), i))
            name = toks[i + 1].text
            p = i + 2
            if toks[p].text == "<":
                while toks[p].text != "(":
                    p += 1
            pe = toks[p].match
            params_toks = split_top(toks, p + 1, pe)
            q = pe + 1
            ret = None
            if toks[q].text == "->":
                r = q + 1
                while toks[r].text not in ("{", "where", ";"):
                    # skip `[u8; 16]` and `(A, B)`: their `;` is not the end of a declaration
                    r = toks[r].match + 1 if toks[r].text in ("[", "(") and toks[r].match > r else r + 1
                ret = _norm(src[toks[q + 1].start:toks[r - 1].end])
                q = r
            while toks[q].text not in ("{", ";"):
                q += 1
            if toks[q].text == ";":
                i = q + 1
                continue
            body_lo, body_hi = q + 1, toks[q].match
            body = src[toks[q].start:toks[body_hi].end]
            params = []
            has_self = False
            for a, b in params_toks:
                txt = _norm(src[toks[a].start:toks[b - 1].end])
                if "self" in [toks[m].text for m in range(a, b)] and b - a <= 4:
                    has_self = True
                    continue
                if b - a >= 3 and toks[a + 1].text == ":":
                    params.append((toks[a].text, _norm(src[toks[a + 2].start:toks[b - 1].end])))
                else:
                    params.append((txt, ""))
            if is_pub:
                st.methods[name] = {"ret": ret, "self": has_self, "body": _norm(body), "nparams": len(params)}
            if is_pub and not has_self and ret in ("Self", st.name):
                fmap = _plain_body(toks, body_lo, body_hi, {param for param, _ in params}, st.name)
                ctor = Ctor(name, params, fmap, _norm(body))
                if fmap is None:
                    part = _reset_body(toks, src, body_lo, body_hi, {param for param, _ in params}, st.name)
                    if part is not None:
                        ctor.partial_map, ctor.reset = part
                st.ctors.append(ctor)
            i = body_hi + 1
            continue
        i += 1


def _plain_body(toks: list[Tok], lo: int, hi: int, params: set[str], name: str) -> dict[str, str] | None:
    """`{ Self { a, b: c } }` (or `{ Self(a, b) }`) with every value a parameter name -> {field: param}."""
    if hi - lo >= 3 and toks[lo].text in ("Self", name) and toks[lo + 1].text == "(" and toks[lo + 1].match == hi - 1:
        parts = split_top(toks, lo + 2, hi - 1)
        if all(b - a == 1 and toks[a].text in params for a, b in parts) and len(parts) == len(params):
            return {str(i): toks[a].text for i, (a, _b) in enumerate(parts)}
        return None
    if hi - lo < 3 or toks[lo].text not in ("Self", name) or toks[lo + 1].text != "{":
        return None
    if toks[lo + 1].match != hi - 1:
        return None
    out = {}
    for a, b in split_top(toks, lo + 2, hi - 1):
        if b - a == 1 and toks[a].text in params:
            out[toks[a].text] = toks[a].text
        elif b - a == 3 and toks[a + 1].text == ":" and toks[a + 2].text in params:
            out[toks[a].text] = toks[a + 2].text
        else:
            return None
    if sorted(out.values()) != sorted(params):
        return None
    return out


def _reset_body(toks: list[Tok], src: str, lo: int, hi: int, params: set[str],
                name: str) -> tuple[dict[str, str], dict[str, str]] | None:
    """`{ Self { a, b: c, d: <expr> } }`: each parameter stored once, unchanged, and at least one
    field set to an expression -> ({field: param}, {field: expr})."""
    if hi - lo < 3 or toks[lo].text not in ("Self", name) or toks[lo + 1].text != "{" \
            or toks[lo + 1].match != hi - 1:
        return None
    out, reset = {}, {}
    for a, b in split_top(toks, lo + 2, hi - 1):
        if b - a == 1 and toks[a].text in params:
            out[toks[a].text] = toks[a].text
        elif b - a == 3 and toks[a + 1].text == ":" and toks[a + 2].text in params:
            out[toks[a].text] = toks[a + 2].text
        elif b - a >= 3 and toks[a].kind == "ident" and toks[a + 1].text == ":":
            reset[toks[a].text] = _norm(src[toks[a + 2].start:toks[b - 1].end])
        else:
            return None
    if not reset or sorted(out.values()) != sorted(params):
        return None
    return out, reset


def parse_package(crate: str, src_dir: str) -> list[Struct]:
    out = []
    files_srcs = {}
    for root, _dirs, files in os.walk(src_dir):
        for fn in sorted(files):
            if fn.endswith(".rs"):
                path = os.path.join(root, fn)
                with open(path, "rb") as fh:
                    files_srcs[path] = fh.read().decode("latin-1")
    by_name: dict[str, Struct] = {}
    lexed = {}
    for path, src in sorted(files_srcs.items()):
        toks = lex(src)
        lexed[path] = toks
        for i, t in enumerate(toks):
            if t.kind != "ident" or t.text != "struct" or i + 2 >= len(toks):
                continue
            if toks[i + 1].kind != "ident":
                continue
            # skip `$name` macro templates
            if i >= 1 and toks[i - 1].text == "$":
                continue
            j = i + 2
            if toks[j].text == "<":
                depth = 0
                while j < len(toks):
                    if toks[j].text == "<":
                        depth += 1
                    elif toks[j].text == ">":
                        depth -= 1
                        if depth == 0:
                            break
                    j += 1
                j += 1
            if j >= len(toks) or toks[j].text not in ("{", "("):
                continue
            if toks[j - 1].text == "$" or toks[i + 1].text.startswith("$"):
                continue
            tuple_struct = toks[j].text == "("
            fields = _parse_fields(toks, src, j + 1, toks[j].match, tuple_struct)
            if not fields:
                continue
            macro, no_new = _enclosing_macro(toks, i)
            macro_new = macro in CTOR_MACROS and not no_new and not tuple_struct
            line = src.count("\n", 0, t.start) + 1
            rel = os.path.relpath(path, os.path.dirname(src_dir))
            st = Struct(toks[i + 1].text, crate, rel, line, tuple_struct, fields, macro, macro_new)
            by_name.setdefault(st.name, st)
            out.append(st)
    for path, toks in lexed.items():
        _parse_impls(toks, files_srcs[path], by_name)
    for st in out:
        if st.macro_new and not any(c.name == "new" for c in st.ctors):
            st.ctors.insert(0, Ctor("new", [(f.name, f.ty) for f in st.fields],
                                    {f.name: f.name for f in st.fields}, "<macro>"))
        for f in st.fields:
            if st.tuple and not f.public and f.getter is None:
                # `pub fn service(&self) -> &ServiceV1 { &self.0 }` and the like
                for m, info in sorted(st.methods.items()):
                    if not info["self"] or info["nparams"] != 0:
                        continue
                    if info["body"] == f"{{ &self.{f.name} }}":
                        f.getter, f.getter_name, f.getter_ret, f.getter_body = "get", m, info["ret"], info["body"]
                        break
                    if info["body"] == f"{{ self.{f.name} }}":
                        f.getter, f.getter_name, f.getter_ret, f.getter_body = "get_copy", m, info["ret"], info["body"]
                        break
                continue
            if not f.public and f.getter is None and f.name in st.methods and st.methods[f.name]["self"] \
                    and st.methods[f.name]["nparams"] == 0:
                f.getter = "method"
                f.getter_body = st.methods[f.name]["body"]
                f.getter_ret = st.methods[f.name]["ret"]
    return out


def bsdk_sources(metadata: dict) -> dict[str, str]:
    """crate name (underscored) -> src dir, for base-sdk packages in `cargo metadata` output."""
    out = {}
    for p in metadata["packages"]:
        src = p.get("source") or ""
        if "base-sdk" in src and p["name"] in BSDK_PACKAGES:
            out[p["name"].replace("-", "_")] = os.path.join(os.path.dirname(p["manifest_path"]), "src")
    return out


_MAKE_NUM = re.compile(r"\bmake_num!\s*\{(?:\s*(?:///[^\n]*|#\[[^\]]*\]))*\s*([A-Z][A-Za-z0-9_]*)\s*,\s*([a-z0-9]+)\s*,")


def num_types(src_dirs: list[str]) -> dict[str, str]:
    """`make_num!` newtypes: private inner integer, `new(v) -> Self(v)` and `get(self) -> self.0`."""
    out = {}
    for d in src_dirs:
        for root, _dirs, files in os.walk(d):
            for fn in files:
                if fn.endswith(".rs"):
                    with open(os.path.join(root, fn), encoding="utf-8", errors="replace") as fh:
                        for m in _MAKE_NUM.finditer(fh.read()):
                            out[m.group(1)] = m.group(2)
    return out


class Api:
    def __init__(self, structs: list[Struct], renames: dict[tuple[str, str], str], nums: dict[str, str] | None = None):
        self.nums = nums or {}
        self.structs = structs
        self.by_name: dict[str, list[Struct]] = {}
        for s in structs:
            self.by_name.setdefault(s.name, []).append(s)
        self.renames = renames  # (struct, old field) -> new field

    def lookup(self, qualified: str, field: str | None = None) -> Struct | None:
        """`dash_primitives::Transaction`, `&OutPoint`, `TxOut` -> Struct."""
        q = qualified.strip().lstrip("&").strip()
        q = re.sub(r"^mut\s+", "", q)
        q = re.sub(r"<.*>$", "", q)
        parts = q.split("::")
        name = parts[-1]
        cands = self.by_name.get(name, [])
        if len(parts) > 1:
            narrowed = [c for c in cands if c.crate == parts[0]] or cands
            cands = narrowed
        if field is not None and len(cands) > 1:
            cands = [c for c in cands if c.field(field) or (c.name, field) in self.renames] or cands
        return cands[0] if len(cands) == 1 else None

    def to_json(self) -> list[dict]:
        out = []
        for s in self.structs:
            if not s.private:
                continue
            out.append({
                "name": s.name, "crate": s.crate, "file": f"{s.file}:{s.line}", "tuple": s.tuple,
                "macro": s.macro, "macro_new": s.macro_new,
                "fields": [{"name": f.name, "ty": f.ty, "public": f.public, "getter": f.getter,
                            "setter": f.setter, "serde_rename": f.serde_rename,
                            **({"getter_ret": f.getter_ret, "getter_body": f.getter_body} if f.getter == "method" else {})}
                           for f in s.fields],
                "ctors": [{"name": c.name, "params": c.params, "plain": c.field_map is not None, "reset": c.reset,
                           "body": c.body if c.body != "<macro>" else "<macro>"} for c in s.ctors],
            })
        return out


def load_api(srcs: dict[str, str], renames: dict[tuple[str, str], str]) -> Api:
    structs = []
    for crate, d in sorted(srcs.items()):
        structs.extend(parse_package(crate, d))
    return Api(structs, renames, num_types(list(srcs.values())))


if __name__ == "__main__":
    import sys

    srcs = json.loads(sys.argv[1]) if len(sys.argv) > 1 else {}
    api = load_api(srcs, {})
    print(json.dumps(api.to_json(), indent=1))
