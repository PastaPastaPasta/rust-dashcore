_E0616 = re.compile(r"field `([^`]+)` of struct `([^`]+)` is private")
_E0609 = re.compile(r"no field `([^`]+)` on type `([^`]+)`")
_E0615 = re.compile(r"attempted to take value of method `([^`]+)` on type `([^`]+)`")
_E0451 = re.compile(r"fields? (.+) of struct `([^`]+)` (?:is|are) private")
_E0560 = re.compile(r"struct `([^`]+)` has no field named `([^`]+)`")
_E0026 = re.compile(r"struct `([^`]+)` does not have a field named `([^`]+)`")
_E0063 = re.compile(r"missing fields? .* in initializer of `([^`]+)`")


def receiver_start(toks, dot: int) -> int:
    """Token index where the receiver expression of the `.` at `dot` starts (best effort)."""
    i = dot - 1
    while i >= 0:
        t = toks[i]
        if t.text in (")", "]") and t.match >= 0:
            i = t.match - 1
            # a call or index: keep going through the callee
            if i >= 0 and (toks[i].kind == "ident" or toks[i].text in (")", "]", ">", "?")):
                continue
            # parenthesised expression `(expr).f`
            return i + 1
        if t.kind in ("ident", "lit") or t.text == "?":
            if t.kind == "ident" and t.text in ("return", "let", "in", "if", "match", "while", "mut", "move",
                                                 "else", "break", "ref"):
                return i + 1
            if i >= 1 and toks[i - 1].text in (".", "::"):
                i -= 2
                continue
            return i
        if t.text == ">" and i >= 1:
            # turbofish `::<T>` before a call
            depth = 0
            j = i
            while j >= 0:
                if toks[j].text == ">":
                    depth += 1
                elif toks[j].text == "<":
                    depth -= 1
                    if depth == 0:
                        break
                j -= 1
            if j >= 1 and toks[j - 1].text == "::":
                i = j - 2
                continue
            return i + 1
        return i + 1
    return 0


def access_context(src: Source, start: int, end: int) -> str:
    """read | write | mutborrow for a field ident spanning [start, end)."""
    toks = src.toks
    fi = tok_at(toks, start)
    if fi >= len(toks) or toks[fi].start != start:
        return "read"
    nxt = toks[fi + 1] if fi + 1 < len(toks) else None
    if nxt is not None and nxt.text in ASSIGN_OPS:
        return "write"
    # x.f[i] = ..., x.f.0 = ..., x.f.g = ...
    j = fi + 1
    while j < len(toks):
        t = toks[j]
        if t.text == "[" and t.match > j:
            j = t.match + 1
            continue
        if t.text == "." and j + 1 < len(toks) and toks[j + 1].kind in ("ident", "lit"):
            if toks[j + 1].kind == "ident" and j + 2 < len(toks) and toks[j + 2].text in ("(", "::"):
                if is_mut_method(toks[j + 1].text):
                    return "write"
                break
            j += 2
            continue
        if t.text in ASSIGN_OPS:
            return "write"
        break
    dot = fi - 1
    if dot >= 0 and toks[dot].text == ".":
        rs = receiver_start(toks, dot)
        if rs >= 2 and toks[rs - 1].text == "mut" and toks[rs - 2].text == "&":
            return "mutborrow"
    return "read"


def suggestion_edits(d: Diag) -> list[tuple[str, int, int, str, str]]:
    """(message, start, end, replacement, applicability) of the diag's suggestions."""
    out = []
    for ch in d.children:
        for sp in ch.get("spans", []):
            if sp.get("suggested_replacement") is not None:
                out.append((ch["message"], sp["byte_start"], sp["byte_end"], sp["suggested_replacement"],
                            sp.get("suggestion_applicability")))
    return out


def plan_access(d: Diag, src: Source, api: bsdk_api.Api, st: CrateStats) -> list[Edit]:
    """E0616 / E0609 on a field read."""
    if d.code == "E0616":
        m = _E0616.search(d.message)
        fname, sname = m.group(1), m.group(2)
    else:
        m = _E0609.search(d.message) or _E0615.search(d.message)
        if not m:
            return []
        fname, sname = m.group(1), m.group(2)
        if d.code == "E0615" and not any((x.name, fname) in api.renames for x in
                                         api.by_name.get(re.sub(r"<.*>$", "", sname.lstrip("&").split("::")[-1]), [])):
            return []  # a real method read as a field: not ours
    short = re.sub(r"<.*>$", "", sname.lstrip("&").split("::")[-1])
    if fname == "0" and short in api.nums:
        if access_context(src, d.start, d.end) != "read":
            st.hand_sites.append((d.file, d.line, d.code, d.message, f"write of {short}.0 (make_num!: rebuild with new)"))
            return []
        return [Edit(d.start, d.end, "get()", "num-get", short)]
    s = api.lookup(sname, fname)
    if s is None:
        st.hand_sites.append((d.file, d.line, d.code, d.message, "type not in base-sdk's private-field table"))
        return []
    new = api.renames.get((s.name, fname), fname)
    f = s.field(new)
    if f is None or f.public:
        if d.code == "E0609":
            return []  # not ours
        st.hand_sites.append((d.file, d.line, d.code, d.message, "no such field in base-sdk's source"))
        return []
    ctx = access_context(src, d.start, d.end)
    if ctx != "read":
        if ctx in ("write", "mutborrow"):
            e = plan_write(d, src, s, new, sname)
            if e:
                return [e]
        st.hand_sites.append((d.file, d.line, d.code, d.message,
                              f"{ctx} of {s.name}.{new} ({'setter exists' if f.setter else 'no setter: rebuild'})"))
        return []
    if f.getter is None:
        why = (f"{s.name}::{new}() does not return the field ({f.getter_body})" if f.getter_body
               else f"{s.name}.{new} has no getter")
        st.hand_sites.append((d.file, d.line, d.code, d.message, why))
        return []
    if f.getter_name:
        # a tuple field read through a getter of another name: `v1.0` -> `v1.service()`
        edits = [Edit(d.start, d.end, f"{f.getter_name}()", "tuple-getter", f"{s.name}.{new}->{f.getter_name}")]
    elif d.code == "E0616":
        sugg = [x for x in suggestion_edits(d) if x[0].startswith(f"a method `{new}` also exists")]
        if not sugg:
            st.hand_sites.append((d.file, d.line, d.code, d.message, "no method suggestion"))
            return []
        _msg, a, b, rep, _app = sugg[0]
        kind = "getter"
        edits = [Edit(a, b, rep, kind, f"{s.name}.{new}:{f.getter}")]
    else:
        # renamed field: `.hash` -> `.txid()`
        edits = [Edit(d.start, d.end, f"{new}()", "rename", f"{s.name}.{fname}->{new}:{f.getter}")]
    if f.getter == "get":
        e = redundant_borrow(src, d.start)
        if e:
            edits.append(e)
        elif value_position(src, d.start):
            old = src.text[_line_start(src.text, d.start):src.text.find("\n", d.end)].strip()
            edits[0].nonequiv = {"kind": "ref-getter", "old": old, "fn": enclosing_fn(src, d.start),
                                 "new": f"... {new}() ...",
                                 "why": f"`{s.name}::{new}()` returns `&{f.ty}` where the field read was a "
                                        f"`{f.ty}` place (a move or copy in value position)"}
    for msg, a, b, rep, app in suggestion_edits(d):
        if app == "MachineApplicable" and not msg.startswith("a method"):
            edits.append(Edit(a, b, rep, "machine", msg))
    return edits


def _line_start(text: str, off: int) -> int:
    return text.rfind("\n", 0, off) + 1


def enclosing_fn(src: Source, off: int) -> str:
    """Name of the innermost `fn` whose body contains `off` (or the closest item name)."""
    toks = src.toks
    idx = tok_at(toks, off)
    for j in range(idx - 1, 0, -1):
        if toks[j].text == "fn" and j + 1 < len(toks) and toks[j + 1].kind == "ident":
            k = j + 2
            while k < len(toks) and toks[k].text not in ("{", ";"):
                if toks[k].text in OPEN and toks[k].match > k and toks[k].text != "{":
                    k = toks[k].match
                k += 1
            if k < len(toks) and toks[k].text == "{" and toks[k].match >= idx:
                return toks[j + 1].text
    return "<module>"


def value_position(src: Source, start: int) -> bool:
    """False when the field read is a method receiver, a field base or indexed (auto-deref)."""
    toks = src.toks
    fi = tok_at(toks, start)
    nxt = toks[fi + 1] if fi + 1 < len(toks) else None
    return not (nxt is not None and nxt.text in (".", "[", "?"))


EXPR_END_KW = {"self", "Self", "true", "false", "crate", "super"}
EXPR_START_KW = {"return", "in", "if", "match", "while", "else", "break", "let", "move", "yield"}


def redundant_borrow(src: Source, start: int) -> Edit | None:
    """`&recv.f` read through a `get` getter becomes `&recv.f()`, a `&&T`: drop the `&`, which
    gives back the original expression's type, `&T`, borrowed from the same place."""
    toks = src.toks
    fi = tok_at(toks, start)
    if fi < 1 or toks[fi - 1].text != ".":
        return None
    nxt = toks[fi + 1] if fi + 1 < len(toks) else None
    if nxt is not None and (nxt.text in (".", "[", "(", "?", "::") or nxt.text == "as"):
        return None  # `&` applies to a longer chain
    rs = receiver_start(toks, fi - 1)
    if rs < 1 or toks[rs - 1].text != "&":
        return None
    if rs >= 2:
        p = toks[rs - 2]
        if (p.kind in ("ident", "lit") and p.text not in EXPR_START_KW and p.text not in ("mut",)) \
                or p.text in (")", "]", "?") or (p.kind == "ident" and p.text in EXPR_END_KW):
            return None  # binary `a & b`
        if p.text == "&" or p.text == "&&":
            return None  # `&&recv.f`: leave it to clippy
    return Edit(toks[rs - 1].start, toks[rs - 1].end, "", "borrow", "redundant & before a get getter")


def _expr_end(toks, j: int) -> int:
    """Index of the token ending the expression starting at `j` (a depth-0 `,` `;` or closer)."""
    while j < len(toks) and toks[j].text not in (";", ",", "}", ")", "]", "=>"):
        if toks[j].text in OPEN and toks[j].match > j:
            j = toks[j].match + 1
        else:
            j += 1
    return j


def _simple_place(toks, lo: int, hi: int) -> bool:
    """idents, `.`, literal tuple indices and `[ident-or-literal]` only: safe to evaluate twice."""
    i = lo
    while i < hi:
        t = toks[i]
        if t.text == "[" and t.match > i:
            if not all(x.kind in ("ident", "lit") or x.text in (".", "::") for x in toks[i + 1:t.match]):
                return False
            i = t.match + 1
            continue
        if not (t.kind in ("ident", "lit") or t.text in (".",)):
            return False
        i += 1
    return True


def plan_write(d: Diag, src: Source, s: "bsdk_api.Struct", fname: str, sname: str) -> Edit | None:
    """`place.f = v` / `place.f op= v`: the field's setter in a statement, else a rebuild through
    the plain constructor when every field reads by copy (so the rebuild clones nothing)."""
    toks = src.toks
    fi = tok_at(toks, d.start)
    if fi >= 1 and toks[fi - 1].text == "." and fi + 1 < len(toks) and toks[fi + 1].text not in ASSIGN_OPS:
        return plan_mutate(d, src, s, fname, sname)
    if fi < 1 or toks[fi - 1].text != "." or fi + 1 >= len(toks) or toks[fi + 1].text not in ASSIGN_OPS:
        return None
    rs = receiver_start(toks, fi - 1)
    if rs >= fi - 1 or not _simple_place(toks, rs, fi - 1):
        return None
    place = src.text[toks[rs].start:toks[fi - 1].start]
    op = toks[fi + 1].text
    j = _expr_end(toks, fi + 2)
    if j >= len(toks) or j == fi + 2:
        return None
    expr = src.text[toks[fi + 2].start:toks[j - 1].end]
    f = s.field(fname)
    if op == "=":
        value = expr
    else:
        rhs = expr if j - (fi + 2) == 1 else f"({expr})"
        value = f"{place}.{fname}() {op[:-1]} {rhs}"
    stmt = toks[j].text == ";" and (rs == 0 or toks[rs - 1].text in (";", "{", "}"))
    if f.setter and stmt:
        return Edit(toks[rs].start, toks[j - 1].end, f"{place}.set_{fname}({value})", "setter", fname)
    test = is_test_code(src, d.file, d.start)
    more: dict[str, str] = {}
    if s.plain_ctor() is None and stmt and test and op == "=":
        # a run of writes to `place` is one rebuild: a reset field is put back once, on the final
        # value, which is a payload that encodes even where the steps between do not
        j = write_run(src, toks, j, place, s, fname, more)
    # the restoring rebuild is a block, of type `()` like the assignment, so any position takes it
    built = rebuild_expr(s, sname, place, fname, value, allow_reset=test, more=more)
    if built is None:
        return None
    new, cloned = built
    if cloned and not test:
        return None  # a rebuild that clones, outside tests: a hand edit
    target = place_target(src, toks, rs, place, d.start)
    if target is None:
        return None
    text = f"{target} = {new}"
    dead = None
    if s.plain_ctor() is None:
        dead = stmt and reset_dead(src, toks, j, place, s)
        if not dead:
            ls = src.text.rfind("\n", 0, toks[rs].start) + 1
            text = restore_text(s, place, new, target, re.match(r"[ \t]*", src.text[ls:]).group(0), d.package_id)
            if text is None:
                return None
    e = Edit(toks[rs].start, toks[j - 1].end, text, "rebuild", f"{s.name}.{fname}")
    e.nonequiv = _rebuild_note(src, d.start, s, fname, src.text[toks[rs].start:toks[j - 1].end], place, cloned,
                               dead)
    if more:
        e.nonequiv["why"] += (f"; the writes of {', '.join([fname, *more])} in a row are one rebuild, "
                              f"each value read before any of them is stored, as the old code read them")
    return e


def write_run(src: Source, toks, j: int, place: str, s, fname: str, more: dict[str, str]) -> int:
    """Extend the write `place.fname = ..;` ending at `toks[j]` (`;`) with the plain writes
    `place.g = v;` that follow it in the block, into `more` (field -> value). A write joins when
    `g` is a field of `s` not reset by its constructor and not written yet in the run, no comment
    sits between it and the one before, and `v` reads `place` only as `place.h` for an `h` not
    written yet in the run (so it reads the value the old code read). Returns the index of the last
    joined write's `;`."""
    reset = set(s.reset_ctor().reset) if s.reset_ctor() else set()
    p = re.escape(place.strip())
    written = {fname}
    i = j + 1
    while i < len(toks) and toks[i].text != "}":
        k = i
        while k < len(toks) and toks[k].text not in (";", "}"):
            k = toks[k].match + 1 if toks[k].text in OPEN and toks[k].match > k else k + 1
        if k >= len(toks) or toks[k].text != ";":
            break
        gap = src.text[toks[i - 1].end:toks[i].start]
        if "//" in gap or "/*" in gap:
            break
        m = re.fullmatch(rf"{p} ?\. ?(\w+) ?= ?(?!=)(.*);", " ".join(src.text[toks[i].start:toks[k].end].split()))
        if m is None:
            break
        g = API_RENAMES.get((s.name, m.group(1)), m.group(1))
        if s.field(g) is None or g in written or g in reset:
            break
        reads = re.findall(rf"(?<![\w.]){p}\b ?(\. ?(\w+) ?(\()?)?", m.group(2))
        if any(not r[0] or r[2] or API_RENAMES.get((s.name, r[1]), r[1]) in written | reset for r in reads):
            break
        # the value, as written in the source (whitespace kept)
        eq = next(t for t in range(i, k) if toks[t].text == "=")
        more[g] = src.text[toks[eq + 1].start:toks[k - 1].end]
        written.add(g)
        j = k
        i = k + 1
    return j


def reset_dead(src: Source, toks, end: int, place: str, s) -> str | None:
    """`reset_is_dead` for every field `s`'s reset constructor resets (with their old names)."""
    found = None
    for f in s.reset_ctor().reset:
        aliases = {old for (st, old), new in API_RENAMES.items() if st == s.name and new == f}
        found = reset_is_dead(src, toks, end, place, f, aliases)
        if found is None:
            return None
    return found


def rebuild_expr(s: "bsdk_api.Struct", sname: str, place: str, fname: str, value: str,
                 allow_reset: bool = False, more: dict[str, str] | None = None) -> tuple[str, list[str]] | None:
    """`Path::ctor(..)` of `place` with `fname` set to `value`; the other fields read through their
    getters, cloned where the getter returns a reference. None without a plain constructor or when a
    field has no getter. With `allow_reset`, a constructor that resets some fields (`reset_ctor`) also
    serves, unless `fname` is one of them; the caller must then put them back (`restore_text`)."""
    ctor = s.plain_ctor()
    if ctor is None and allow_reset:
        ctor = s.reset_ctor()
        if ctor is not None and fname in ctor.reset:
            ctor = None
    if ctor is None or any(not g.public and g.getter not in ("get", "get_copy") for g in s.fields):
        return None
    inv = {p: fld for fld, p in (ctor.field_map or ctor.partial_map).items()}
    args, cloned = [], []
    for p, _ty in ctor.params:
        g = s.field(inv[p])
        if g.name == fname:
            args.append(value)
        elif more and g.name in more:
            args.append(more[g.name])
        elif g.public:
            args.append(f"{place}.{g.name}.clone()")
            cloned.append(g.name)
        elif g.getter == "get":
            args.append(f"{place}.{g.getter_name or g.name}().clone()")
            cloned.append(g.name)
        else:
            args.append(f"{place}.{g.getter_name or g.name}()")
    q = re.sub(r"^(?:&\s*(?:mut\s+)?)+", "", sname.strip()).strip()  # `&mut T` from "on type `&mut T`"
    path = q if "::" in q else f"{s.crate}::{s.name}"
    path = re.sub(r"<.*>$", "", path)
    return f"{path}::{ctor.name}({', '.join(args)})", cloned


def rebuild_ctor(s) -> "bsdk_api.Ctor":
    return s.plain_ctor() or s.reset_ctor()


def restore_text(s, place: str, new: str, target: str, indent: str, package_id: str) -> str | None:
    """The rebuild through a constructor that resets a field (`reset_ctor`): build, then put the
    old value back through the crate's `[[restore]]` helper. None when the crate reaches no helper
    for this type: the site goes to the hand list."""
    got = RESTORE.get(package_id, {}).get(s.name)
    if got is None or set(s.reset_ctor().reset) != {got[0]}:
        return None
    field, path = got
    g = s.field(field).getter_name or field
    return (f"{{\n{indent}    let rebuilt = {new};\n"
            f"{indent}    {target} = {path}(&rebuilt, {place}.{g}().clone());\n{indent}}}")


def reset_is_dead(src: Source, toks, end: int, place: str, field: str, aliases: set[str]) -> str | None:
    """Whether the value a reset constructor gives `field` is never read: the statements after the
    one ending at `end` (a `;`), in the same block, write `place`'s `field` (`place.field = v` with
    no `place` in `v`, or `place.reset_signature()`) before anything reads it. Only writes to
    other fields of `place` whose value reads `place`'s other fields by name may come first. The
    rebuild then needs no restore: returns that statement, for the note, else None."""
    names = {field} | aliases
    p = re.escape(place.strip())
    i = end + 1
    while i < len(toks) and toks[i].text not in ("}",):
        j = i
        while j < len(toks) and toks[j].text not in (";", "}"):
            j = toks[j].match + 1 if toks[j].text in OPEN and toks[j].match > j else j + 1
        if j >= len(toks) or toks[j].text != ";":
            return None
        stmt = " ".join(src.text[toks[i].start:toks[j].end].split())
        m = re.fullmatch(rf"{p} ?\. ?(\w+) ?= ?(.*);", stmt)
        if re.fullmatch(rf"{p} ?\. ?reset_signature ?\( ?\) ?;", stmt):
            return stmt
        if m is None:
            return None
        rhs = m.group(2)
        reads = re.findall(rf"(?<![\w.]){p}\b ?(\. ?(\w+) ?(\()?)?", rhs)
        if m.group(1) in names:
            return stmt if not reads else None
        if any(not r[0] or r[2] or r[1] in names for r in reads):
            return None
        i = j + 1
    return None


RESTORE_NOTE = ("the helper re-encodes the rebuilt payload with the old value's bytes and decodes it, "
                "asserting the round trip, so a payload that does not round-trip panics there")


def _reset_why(ctor, dead: str | None) -> str:
    fields = ", ".join(f"`{f}`" for f in sorted(ctor.reset))
    if dead:
        return (f"`{ctor.name}` resets {fields}, left reset: the block writes it before reading it "
                f"(`{dead[:80]}`)")
    return f"`{ctor.name}` resets {fields}, which is put back from the old value ({RESTORE_NOTE})"


def _rebuild_note(src: Source, off: int, s, fname: str, old: str, place: str, cloned: list[str],
                  dead: str | None = None) -> dict:
    ctor = rebuild_ctor(s)
    why = f"rebuilt through `{s.name}::{ctor.name}` instead of writing `{fname}` in place"
    if ctor.field_map is None:
        why += "; " + _reset_why(ctor, dead)
    if cloned:
        why += f"; clones the other fields ({', '.join(cloned)}) where the old code left them in place"
    else:
        why += f"; every {s.name} field reads by copy, so the value is the same"
    kind = "rebuild" + (("-reset-dead" if dead else "-restore") if ctor.field_map is None else "") \
        + ("+clone" if cloned else "")
    return {"kind": kind, "fn": enclosing_fn(src, off),
            "old": " ".join(old.split())[:160], "new": f"{place} = {s.name}::{ctor.name}(..)", "why": why}


def is_test_code(src: Source, file: str, off: int) -> bool:
    """Under tests/, benches/ or examples/, in a `tests.rs`/`*_tests.rs`, or inside a
    `#[cfg(test)]` module or a `#[test]` function."""
    parts = file.split("/")
    if any(p in ("tests", "benches", "examples") for p in parts[:-1]) or parts[-1] == "tests.rs" \
            or parts[-1].endswith("_tests.rs"):
        return True
    toks = src.toks
    idx = tok_at(toks, off)
    for j in range(idx - 1, -1, -1):
        t = toks[j]
        if t.text == "{" and t.match >= idx:
            k = j - 1
            while k >= 0 and toks[k].text not in (";", "}", "{"):
                if toks[k].text == "]" and toks[k].match >= 0:
                    attr = src.text[toks[toks[k].match].start:toks[k].end]
                    if re.fullmatch(r"\[\s*(cfg\s*\(\s*test\s*\)|test|tokio::test.*|rstest.*)\s*\]", attr, re.S):
                        return True
                    k = toks[k].match - 1
                    continue
                k -= 1
    return False


def place_target(src: Source, toks, rs: int, place: str, off: int) -> str | None:
    """What to assign a rebuilt value to. A field path is assigned as is. A bare name is looked up
    at its nearest binding: a `mut` binding (`let mut x`, `mut x: T`, `|mut x|`) holds the value,
    so `x`; a binding without `mut` that is written through a field must be a `&mut` (or another
    `DerefMut`), so `*x`. None when no binding is found."""
    if not re.fullmatch(r"(?:r#)?\w+", place.strip()):
        return place
    name = place.strip()
    idx = tok_at(toks, off)
    for j in range(rs - 1, 0, -1):
        t = toks[j]
        if t.kind != "ident" or t.text != name:
            continue
        prev, nxt = toks[j - 1].text, toks[j + 1].text if j + 1 < len(toks) else ""
        if prev == "mut":
            return name
        if (prev == "let" and nxt in (":", "=")) or (prev == "|" and nxt in (":", "|", ",")) \
                or (prev in ("(", ",") and nxt == ":"):
            return f"*{name}"
    return None


STMT_EXITS = {"?", "return", "break", "continue", "yield"}


def plan_mutate(d: Diag, src: Source, s: "bsdk_api.Struct", fname: str, sname: str) -> Edit | None:
    """An expression statement mutating `place.f` (a `&mut self` method, an indexed or nested write,
    `&mut place.f`): `{ let mut f = place.f().clone(); <statement on f>; place = T::new(.., f, ..); }`."""
    toks = src.toks
    fi = tok_at(toks, d.start)
    f = s.field(fname)
    if f is None or f.getter != "get" or not is_test_code(src, d.file, d.start):
        return None
    rs = receiver_start(toks, fi - 1)
    if rs >= fi - 1 or not _simple_place(toks, rs, fi - 1):
        return None
    place = src.text[toks[rs].start:toks[fi - 1].start]
    closure_body = rs >= 1 and toks[rs - 1].text in ("|", "||")
    if closure_body:
        # `|p| p.f.op(..)`: the whole body becomes the block; a body whose value is used (not `()`)
        # then fails to compile rather than change
        lo = rs
        hi = _expr_end(toks, lo)
        if hi >= len(toks) or toks[hi].text not in (")", ",", ";", "}") or hi <= fi:
            return None
        if any(t.text in STMT_EXITS | {"|", "||"} for t in toks[lo:hi]):
            return None
        stmt = src.text[toks[lo].start:toks[hi - 1].end] + ";"
    else:
        # the statement around the write: from the token after the previous `;`/`{`/`}` to the next `;`
        lo = rs
        while lo > 0 and toks[lo - 1].text not in (";", "{", "}"):
            if toks[lo - 1].text in (")", "]") and toks[lo - 1].match >= 0:
                lo = toks[lo - 1].match
                continue
            lo -= 1
        hi = _expr_end(toks, lo)
        if hi >= len(toks) or toks[hi].text != ";" or hi <= fi:
            return None
        if toks[lo].text in ("let", "for", "while", "if", "match", "loop", "return") or toks[lo].kind == "lifetime":
            return None
        if any(t.text in STMT_EXITS for t in toks[lo:hi]):
            return None
        if any(t.text in ("|", "||", "move", "async") for t in toks[lo:rs]):
            return None  # the place may be bound by a closure inside the statement
        stmt = src.text[toks[lo].start:toks[hi].end]
    a, b = toks[rs].start - toks[lo].start, toks[fi].end - toks[lo].start
    rest = stmt[:a] + stmt[b:] + place
    gname = f.getter_name or fname  # a tuple field `.0` reads through `service()` and binds `service`
    local = next(n for n in (gname, f"{gname}_", f"new_{gname}") if not re.search(rf"\b{n}\b", rest))
    body = stmt[:a] + local + stmt[b:]
    built = rebuild_expr(s, sname, place, fname, local, allow_reset=True)
    if built is None:
        return None
    new, cloned = built
    target = place_target(src, toks, rs, place, d.start)
    if target is None:
        return None
    ls = src.text.rfind("\n", 0, toks[lo].start) + 1
    indent = re.match(r"[ \t]*", src.text[ls:]).group(0)
    store = f"{target} = {new};"
    dead = None
    if s.plain_ctor() is None and not closure_body:
        dead = reset_dead(src, toks, hi, place, s)
    if s.plain_ctor() is None and not dead:
        store = restore_text(s, place, new, target, indent + "    ", d.package_id)
        if store is None:
            return None
    text = (f"{{\n{indent}    let mut {local} = {place}.{gname}().clone();\n{indent}    {body}\n"
            f"{indent}    {store}\n{indent}}}")
    end = toks[hi - 1].end if closure_body else toks[hi].end
    e = Edit(toks[lo].start, end, text, "rebuild", f"{s.name}.{fname}")
    e.nonequiv = _rebuild_note(src, d.start, s, fname, stmt, place, [fname] + cloned, dead)
    e.nonequiv["why"] = (f"`{fname}` mutated on a clone, then {place} rebuilt through "
                         f"`{s.name}::{rebuild_ctor(s).name}`" + (f"; also clones {', '.join(cloned)}" if cloned else ""))
    if s.plain_ctor() is None:
        e.nonequiv["why"] += "; " + _reset_why(rebuild_ctor(s), dead)
    return e


def find_struct_group(src: Source, offset: int, sname: str) -> tuple[int, int, str] | None:
    """(path token idx, brace token idx, path text) of the innermost `Path {` group around offset
    whose last path segment is the struct's name."""
    toks = src.toks
    idx = tok_at(toks, offset)
    short = sname.split("::")[-1]
    innermost = None
    for j in range(idx - 1, -1, -1):
        t = toks[j]
        if t.text == "{" and t.match >= idx:
            pb = path_before(toks, j)
            if pb and pb[1].split("::")[-1] == short:
                return pb[0], j, pb[1]
            if innermost is None:
                innermost = (pb[0], j, pb[1]) if pb else False
    # a type alias (`LlmqCommitment { .. }` for `Commitment`): the group right around the field
    return innermost or None


def is_pattern(src: Source, first: int, brace: int) -> bool:
    toks = src.toks
    end = toks[brace].match
    for a, b in split_top(toks, brace + 1, end):
        if b - a == 1 and toks[a].text == "..":
            return True
    # walk outwards through enclosing ( [ groups and `|` alternatives
    lo, hi = first, end
    while True:
        prev = toks[lo - 1] if lo >= 1 else None
        nxt = toks[hi + 1] if hi + 1 < len(toks) else None
        if prev is not None and prev.text in ("let", "for"):
            return True
        if nxt is not None and nxt.text in ("=>", "in", "@", "|", ":"):
            return True
        if nxt is not None and nxt.text == "=" and prev is not None and prev.text in ("let", "if", "while"):
            return True
        if nxt is not None and nxt.text == "=":
            # `let (a, S { .. }) = ` handled by the walk; a bare `S {..} = x` is a destructuring assignment
            return True
        if nxt is not None and nxt.text in (")", "]", ",") :
            # inside a tuple/slice/args: climb to the group
            g = None
            for j in range(lo - 1, -1, -1):
                if toks[j].text in ("(", "[") and toks[j].match > hi:
                    g = j
                    break
                if toks[j].text == "{" and toks[j].match > hi:
                    break
            if g is None:
                return False
            # tuple-struct pattern `Some(S {..})`: include the path before `(`
            lo, hi = g, toks[g].match
            pb = path_before(toks, g) if g >= 1 and toks[g - 1].kind == "ident" else None
            if pb:
                lo = pb[0]
            continue
        return False


def plan_literal(src: Source, first: int, brace: int, path: str, api: bsdk_api.Api, st: CrateStats,
                 file: str, sname: str = "") -> Edit | None:
    toks = src.toks
    end = toks[brace].match
    s = api.lookup(path) or (api.lookup(sname) if sname else None)
    line = src.line(toks[first].start)
    if s is None:
        st.hand_sites.append((file, line, "ctor", path, "struct not found in base-sdk's source"))
        return None
    entries = {}
    order = []
    base = None
    for a, b in split_top(toks, brace + 1, end):
        if toks[a].text == "..":
            copy_only = all(g.public or g.getter == "get_copy" for g in s.fields)
            gettable = all(g.public or g.getter in ("get", "get_copy") for g in s.fields)
            if b <= a + 1 or not (copy_only or (gettable and is_test_code(src, file, toks[first].start))):
                st.hand_sites.append((file, line, "ctor", f"{s.name} {{ .. }}",
                                      "functional update `..base` of a type with non-Copy getters"))
                return None
            base = (src.text[toks[a + 1].start:toks[b - 1].end], _simple_place(toks, a + 1, b))
            continue
        while a < b and toks[a].text == "#":
            st.hand_sites.append((file, line, "ctor", f"{s.name} {{ .. }}", "attribute on a field initializer"))
            return None
        name = toks[a].text
        if b - a == 1:
            expr = name
        elif toks[a + 1].text == ":":
            # keep comments between fields: take the text from after `:` to the field's end
            expr = src.text[toks[a + 1].end:toks[b - 1].end].strip()
        else:
            st.hand_sites.append((file, line, "ctor", f"{s.name} {{ .. }}", "unparsed field initializer"))
            return None
        fname = api.renames.get((s.name, name), name)
        entries[fname] = expr
        order.append(fname)
    names = [f.name for f in s.fields]
    bind = None
    if base is not None:
        base_text, simple = base
        if simple:
            ref = base_text
        else:
            bind = next(n for n in ("base", "base_", "update_base") if not any(
                re.search(rf"\b{n}\b", e) for e in entries.values()))
            ref = bind
        base_cloned = []
        for g in s.fields:
            if g.name not in entries:
                if g.public:
                    entries[g.name] = f"{ref}.{g.name}"
                elif g.getter == "get":
                    entries[g.name] = f"{ref}.{g.name}().clone()"
                    base_cloned.append(g.name)
                else:
                    entries[g.name] = f"{ref}.{g.name}()"
    if set(entries) != set(names):
        st.hand_sites.append((file, line, "ctor", f"{s.name} {{ {', '.join(order)} }}",
                              f"fields differ from base-sdk's {names}"))
        return None
    ctor = s.plain_ctor()
    if ctor is None:
        st.hand_sites.append((file, line, "ctor", f"{s.name} {{ .. }}",
                              f"no plain constructor ({', '.join(c.name for c in s.ctors) or 'none'})"))
        return None
    inv = {p: f for f, p in ctor.field_map.items()}
    by_param = [inv[p] for p, _ty in ctor.params]
    moved = reordered_impure(src.text, order, by_param, entries)
    if moved:
        st.hand_sites.append((file, line, "ctor", f"{s.name} {{ {', '.join(order)} }}",
                              f"the constructor's order evaluates {', '.join(moved)} in another order "
                              "than the literal, and one of them is not a plain path, literal or field read"))
        return None
    if bind and any(not pure_expr(entries[f]) for f in order):
        st.hand_sites.append((file, line, "ctor", f"{s.name} {{ .., ..{base[0]} }}",
                              "the base would be evaluated before an initializer that is not a plain path, "
                              "literal or field read"))
        return None
    args = [entries[f] for f in by_param]
    multiline = "\n" in src.text[toks[brace].start:toks[end].end]
    if multiline:
        # indent of the line holding the path
        ls = src.text.rfind("\n", 0, toks[first].start) + 1
        indent = re.match(r"[ \t]*", src.text[ls:]).group(0)
        inner = indent + "    "
        body = "".join(f"{inner}{_reindent(a, inner)},\n" for a in args)
        new = f"{path}::{ctor.name}(\n{body}{indent})"
    else:
        new = f"{path}::{ctor.name}({', '.join(args)})"
    note = f"{s.name}::{ctor.name}"
    e = Edit(toks[first].start, toks[end].end, new, "ctor", note)
    if base is not None:
        if bind:
            # `..Default::default()` took its type from the literal; the binding needs it spelled
            ty = f": {path}" if re.fullmatch(r"(?:Default::)?default\(\)", base[0].strip()) else ""
            e.new = f"{{\n{indent if multiline else ''}    let {bind}{ty} = {base[0]};\n{indent if multiline else ''}    {new}\n{indent if multiline else ''}}}"
        e.kind = "ctor-update"
        e.nonequiv = {"kind": "ctor-update", "fn": enclosing_fn(src, toks[first].start),
                      "old": f"{s.name} {{ .., ..{base[0]} }}", "new": f"{s.name}::{ctor.name}(.., {base[0]}.f(), ..)",
                      "why": f"functional update rebuilt through `{s.name}::{ctor.name}`; "
                             + (f"clones {', '.join(base_cloned)} from the base where `..base` moved them"
                                if base_cloned else "every field reads by copy, so the fields taken from the "
                                                    "base are the same values")}
    return e


def pure_expr(expr: str) -> bool:
    """A plain path, literal or field read (`a`, `x.f.0`, `&x.f`, `*p`, `-1`, `T::C`, `x as u32`):
    evaluating it has no effect, so its place among the initializers does not matter."""
    toks = lex(expr)
    for i, t in enumerate(toks):
        if t.kind in ("ident", "lit"):
            continue
        if t.text in (".", "::", "&", "*", "-", "!") and not (t.text == "!" and i > 0 and toks[i - 1].kind == "ident"):
            continue
        return False
    return bool(toks)


def reordered_impure(text: str, order: list[str], by_param: list[str], entries: dict[str, str]) -> list[str]:
    """The initializers of the literal, in source order `order`, that the constructor's parameter
    order `by_param` would evaluate in another relative order, when at least one of a swapped
    pair is not pure: `S { b: r.next(), a: r.next() }` through `new(a, b)`."""
    pos = {f: i for i, f in enumerate(by_param)}
    explicit = [f for f in order if f in pos]
    out = []
    for i, a in enumerate(explicit):
        for b in explicit[i + 1:]:
            if pos[a] > pos[b] and not (pure_expr(entries[a]) and pure_expr(entries[b])):
                out += [f for f in (a, b) if f not in out]
    return out


def _reindent(expr: str, inner: str) -> str:
    lines = expr.split("\n")
    if len(lines) == 1:
        return expr
    # keep the relative indentation of continuation lines; rustfmt fixes the rest
    return "\n".join([lines[0]] + lines[1:])


def plan_pattern(src: Source, first: int, brace: int, path: str, api: bsdk_api.Api, st: CrateStats,
                 file: str, sname: str = "") -> Edit | None:
    """`let S { a, b: x, .. } = place;` -> `let a = place.a(); let x = place.b();`."""
    toks = src.toks
    end = toks[brace].match
    line = src.line(toks[first].start)
    s = api.lookup(path) or (api.lookup(sname) if sname else None)
    why = None
    if s is None:
        why = "struct not found"
    elif first < 1 or toks[first - 1].text != "let" or end + 1 >= len(toks) or toks[end + 1].text != "=":
        why = "struct pattern outside a plain `let`"
    if why is None:
        j = end + 2
        k = j
        while k < len(toks) and toks[k].text != ";":
            if toks[k].text in OPEN and toks[k].match > k:
                why = "initializer is not a place expression"
                break
            if not (toks[k].kind == "ident" or toks[k].text in (".", "&", "*")):
                why = "initializer is not a place expression"
                break
            k += 1
    if why is not None:
        st.hand_sites.append((file, line, "pattern", src.text[toks[first].start:toks[end].end].replace("\n", " ")[:120], why))
        return None
    place = src.text[toks[end + 2].start:toks[k - 1].end].lstrip("&").strip()
    lets = []
    for a, b in split_top(toks, brace + 1, end):
        if toks[a].text == "..":
            continue
        name = toks[a].text
        fname = api.renames.get((s.name, name), name)
        f = s.field(fname)
        if f is None or (not f.public and f.getter is None):
            st.hand_sites.append((file, line, "pattern", f"{s.name}.{name}", "no getter"))
            return None
        if b - a == 1:
            bind = name
        elif b - a == 2 and toks[a].text in ("ref", "mut"):
            bind = f"{toks[a].text} {toks[a + 1].text}"
            fname = api.renames.get((s.name, toks[a + 1].text), toks[a + 1].text)
            f = s.field(fname)
        elif toks[a + 1].text == ":" and all(t.kind == "ident" or t.text == "_" for t in toks[a + 2:b]):
            bind = src.text[toks[a + 2].start:toks[b - 1].end]
        else:
            st.hand_sites.append((file, line, "pattern", f"{s.name}.{name}", "nested sub-pattern"))
            return None
        acc = f"{place}.{fname}" if f.public else f"{place}.{fname}()"
        lets.append((bind, acc, f))
    ls = src.text.rfind("\n", 0, toks[first].start) + 1
    indent = re.match(r"[ \t]*", src.text[ls:]).group(0)
    new = f"\n{indent}".join(f"let {b} = {acc};" for b, acc, _f in lets)
    for b, acc, f in lets:
        st.nonequiv.append({"file": file, "line": line, "kind": "pattern-binding",
                            "old": f"let {s.name} {{ {b}.. }} = {place}", "new": f"let {b} = {acc}",
                            "why": f"binding mode now follows the getter ({f.getter or 'public field'}) "
                                   f"instead of the pattern's default binding"})
    return Edit(toks[first - 1].start, toks[k].end, new, "pattern", s.name)


def plan_struct(d: Diag, src: Source, api: bsdk_api.Api, st: CrateStats, done: set) -> Edit | None:
    sname = None
    for rx, grp in ((_E0451, 2), (_E0560, 1), (_E0026, 1), (_E0063, 1)):
        m = rx.search(d.message)
        if m:
            sname = m.group(grp)
            break
    if sname is None:
        return None
    g = find_struct_group(src, d.start, sname)
    if g is None:
        st.hand_sites.append((d.file, d.line, d.code, d.message, "struct expression not found"))
        return None
    first, brace, path = g
    key = src.toks[first].start
    if key in done:
        return None
    done.add(key)
    if is_pattern(src, first, brace):
        return plan_pattern(src, first, brace, path, api, st, d.file, sname)
    return plan_literal(src, first, brace, path, api, st, d.file, sname)


def _conflict(a: Edit, b: Edit) -> bool:
    """Two edits touch the same text. An insertion conflicts with a replacement that contains its
    point or ends at it (the inserted text would land after the replacement)."""
    if a.start == a.end and b.start == b.end:
        return a.start == b.start
    if a.start == a.end:
        return b.start < a.start <= b.end
    if b.start == b.end:
        return a.start < b.start <= a.end
    return a.start < b.end and b.start < a.end


def apply_edits(src: Source, edits: list[Edit]) -> list[Edit]:
    """Apply non-conflicting edits from the end of the file backwards. Of conflicting edits the
    widest wins; the others are dropped and come back as errors next round."""
    uniq = {(e.start, e.end, e.new): e for e in edits}
    chosen: list[Edit] = []
    for e in sorted(uniq.values(), key=lambda e: (-(e.end - e.start), e.start)):
        if src.text[e.start:e.end] == e.new:
            continue
        if any(_conflict(e, o) for o in chosen):
            continue
        chosen.append(e)
    for e in sorted(chosen, key=lambda e: (e.start, e.end), reverse=True):
        src.splice(e.start, e.end, e.new)
    return chosen


def ref_getter_names(api: bsdk_api.Api) -> set[str]:
    """Names of base-sdk getters that return a reference (`get`)."""
    return {f.getter_name or f.name for ss in api.by_name.values() for st in ss for f in st.fields
            if f.getter == "get"}


def _same_type(have: str, other: str) -> bool:
    """`have` is `other`, where rustc writes an unsuffixed literal's type as `{integer}` /
    `{float}` (`[{integer}; 16]` against `[u8; 16]`)."""
    pat = re.escape(other).replace(r"\{integer\}", r"(?:[iu](?:8|16|32|64|128|size))") \
        .replace(r"\{float\}", r"(?:f32|f64)")
    return re.fullmatch(pat, have) is not None


def plan_ref_clone(d: Diag, src: Source, api: bsdk_api.Api) -> list[Edit]:
    """`x.f` moved or copied a field out by value, its getter `x.f()` returns `&T`: rustc reports
    E0308 "expected `T`, found `&T`" at the call, or E0716 when `x` is a temporary the reference
    outlives. `.clone()` gives back the value the old code had (non-equivalence kind `clone`)."""
    toks = src.toks
    names = ref_getter_names(api)

    def getter_call_ending_at(k: int) -> bool:  # toks[k] is the `)` of `.g()`
        return k >= 3 and toks[k].text == ")" and toks[k].match == k - 1 and toks[k - 2].text in names \
            and toks[k - 3].text == "."

    def deref(k: int) -> list[Edit]:
        """`*` before the receiver of the `.g()` ending at toks[k]: a comparison reads through the
        reference exactly as it read the field, nothing is cloned."""
        rs = receiver_start(toks, k - 3)
        if rs >= k - 3 or (rs >= 1 and toks[rs - 1].text in ("*", "&", "!", "-")):
            return []
        return [Edit(toks[rs].start, toks[rs].start, "*", "deref", toks[k - 2].text)]

    if d.code == "E0277":
        # `x.f() == v`: "can't compare `&T` with `T`" at the operator
        m = re.search(r"can't compare `&([^`]+)` with `([^`]+)`", d.message)
        k = tok_at(toks, d.start)
        if not m or not _same_type(m.group(1), m.group(2)) or k >= len(toks) or toks[k].text not in ("==", "!=") \
                or not getter_call_ending_at(k - 1):
            return []
        return deref(k - 1)
    if d.code == "E0308":
        m = re.search(r"expected `([^`]+)`, found `&([^`]+)`", d.rendered)
        if not m or m.group(1) != m.group(2):
            return []
        k = tok_at(toks, d.end - 1)
        if toks[k].end != d.end or not getter_call_ending_at(k):
            return []
        if k + 1 < len(toks) and toks[k + 1].text in ("==", "!=") or \
                toks[tok_at(toks, d.start) - 1].text in ("==", "!="):
            return deref(k)
        # rustc offers "consider dereferencing the borrow" only for a `Copy` type: `*` copies the
        # value the old code copied, and `.clone()` would be clippy's `clone_on_copy`
        if any(repl == "*" and a == b for _m, a, b, repl, _ap in suggestion_edits(d)):
            return deref(k)
        at, g = d.end, toks[k - 2].text
    elif d.code == "E0716":
        k = tok_at(toks, d.end)
        if k + 3 >= len(toks) or toks[k].text != "." or toks[k + 1].text not in names \
                or toks[k + 2].text != "(" or toks[k + 2].match != k + 3:
            return []
        if k + 5 < len(toks) and toks[k + 4].text == "." and toks[k + 5].text == "clone":
            return []
        at, g = toks[k + 3].end, toks[k + 1].text
    else:
        return []
    e = Edit(at, at, ".clone()", "clone", g)
    e.nonequiv = {"kind": "clone", "fn": enclosing_fn(src, at),
                  "old": src.text[_line_start(src.text, at):src.text.find("\n", at)].strip()[:160],
                  "new": f"{g}().clone()",
                  "why": f"the old code took the field `{g}` by value; its getter returns a reference, cloned"
                         + (" (the receiver is a temporary)" if d.code == "E0716" else "")}
    return [e]


def plan_num_new(d: Diag, src: Source, api: bsdk_api.Api, st: CrateStats) -> list[Edit]:
    """E0423 `Num(v)` of a `make_num!` newtype, or of a tuple struct with a plain constructor:
    rustc's own `Num::new(v)` / `Type::from_bytes(v)` suggestion when that function stores its
    argument unchanged."""
    name = src.text[d.start:d.end].split("::")[-1].strip()
    plain = {"new"} if name in api.nums else set()
    s = api.lookup(name)
    if s is not None and s.tuple:
        plain |= {c.name for c in s.ctors if c.field_map is not None and len(c.params) == len(s.fields)}
    if not plain:
        st.hand_sites.append((d.file, d.line, d.code, d.message, f"`{name}`: no plain constructor"))
        return []
    out = []
    for msg, a, b, rep, _app in suggestion_edits(d):
        m = re.search(r"the `(\w+)` associated function", msg)
        if m and m.group(1) in plain and rep == f"::{m.group(1)}":
            out.append(Edit(a, b, rep, "num-new" if name in api.nums else "ctor",
                            name if name in api.nums else f"{name}::{m.group(1)}"))
    if not out:
        st.hand_sites.append((d.file, d.line, d.code, d.message, "no `new` suggestion"))
    return out


_E0599_VARIANT = re.compile(r"named `([^`]+)` found for enum `([^`]+)`")


def plan_variant_rename(d: Diag, src: Source, cfg: Config) -> list[Edit]:
    """E0599 on a variant `config.toml` `[[variant-rename]]` lists: the new variant's name, at the
    error's own span only."""
    m = _E0599_VARIANT.search(d.message)
    if not m:
        return []
    new = cfg.variant_renames.get((m.group(2), m.group(1)))
    if new is None or src.text[d.start:d.end] != m.group(1):
        return []
    return [Edit(d.start, d.end, new, "variant-rename", f"{m.group(2)}::{m.group(1)}->{new}")]


STRUCT_CODES = {"E0451", "E0560", "E0026", "E0063"}
ACCESS_CODES = {"E0616", "E0609", "E0615"}


def auto_round(cfg: Config, pkg: dict, api: bsdk_api.Api, st: CrateStats) -> tuple[int, list[Diag], list[Diag], bool]:
    errs, other, ok = cargo_json(cfg, pkg)
    by_file: dict[str, list[Diag]] = defaultdict(list)
    for d in errs:
        by_file[d.file].append(d)
    changed = 0
    st.hand_sites = []
    for file, diags in sorted(by_file.items()):
        src = Source(os.path.join(cfg.repo, file))
        edits: list[Edit] = []
        # struct literals/patterns first, from the innermost (last-starting) one; each is planned on the
        # current text, so nested literals are rewritten one level per round.
        done: set = set()
        structs = []
        for d in diags:
            if d.code in STRUCT_CODES:
                e = plan_struct(d, src, api, st, done)
                if e:
                    structs.append(e)
        # keep only the innermost of nested struct edits this round
        structs.sort(key=lambda e: e.start)
        kept = []
        for e in structs:
            if any(o.start <= e.start and e.end <= o.end for o in kept):
                kept = [o for o in kept if not (o.start <= e.start and e.end <= o.end)]
            if any(e.start <= o.start and o.end <= e.end for o in kept):
                continue
            kept.append(e)
        edits.extend(kept)
        for d in diags:
            if d.code == "E0423" and "tuple struct which contains private fields" in d.message:
                edits.extend(plan_num_new(d, src, api, st))
            if d.code in ACCESS_CODES:
                if any(e.start <= d.start < e.end for e in kept):
                    continue
                edits.extend(plan_access(d, src, api, st))
            if d.code in ("E0308", "E0716", "E0277"):
                edits.extend(plan_ref_clone(d, src, api))
            if d.code == "E0599" and cfg.variant_renames:
                edits.extend(plan_variant_rename(d, src, cfg))
        applied = apply_edits(src, edits)
        if src.save():
            st.files.add(file)
            changed += len(applied)
            for e in applied:
                if e.kind in ("getter", "machine", "borrow", "tuple-getter", "deref"):
                    st.auto[e.kind] += 1
                else:
                    st.scripted[e.kind] += 1
                _record_nonequiv(st, file, src, e, api)
    return changed, errs, other, ok


def _record_nonequiv(st: CrateStats, file: str, src: Source, e: Edit, api: bsdk_api.Api) -> None:
    line = src.line(e.start)
    if e.nonequiv:
        st.nonequiv.append({"file": file, "line": line, **e.nonequiv})
        return
    if e.kind == "ctor":
        sname, ctor = e.note.split("::")
        s = api.lookup(sname)
        c = next((c for c in s.ctors if c.name == ctor), None) if s else None
        if c is not None and c.body != "<macro>":
            st.nonequiv.append({"file": file, "line": line, "fn": enclosing_fn(src, e.start), "kind": "ctor-handwritten",
                                "old": f"{sname} {{ .. }}", "new": f"{sname}::{ctor}(..)",
                                "why": f"hand-written constructor, body `{c.body}`"})


def needless_borrow_round(cfg: Config, pkg: dict, base: str, st: CrateStats) -> int:
    """Apply clippy's needless_borrow fixes on lines this port changed."""
    warns, _other, ok = cargo_json(cfg, pkg, clippy=True)
    if not ok:
        return 0
    changed_lines = changed_line_map(cfg, base)
    by_file = defaultdict(list)
    for d in warns:
        if d.message.startswith("this expression creates a reference which is immediately dereferenced") or \
                "needless_borrow" in d.rendered or "borrowed expression implements the required traits" in d.message:
            if d.line in changed_lines.get(d.file, set()):
                by_file[d.file].append(d)
    n = 0
    for file, diags in by_file.items():
        src = Source(os.path.join(cfg.repo, file))
        edits = []
        for d in diags:
            for _msg, a, b, rep, app in suggestion_edits(d):
                if app == "MachineApplicable":
                    edits.append(Edit(a, b, rep, "borrow"))
        applied = apply_edits(src, edits)
        if src.save():
            n += len(applied)
            st.auto["needless_borrow"] += len(applied)
    return n


def changed_line_map(cfg: Config, base: str) -> dict[str, set[int]]:
    r = sh(["git", "diff", "-U0", "--no-color", base, "--", "."], cfg.repo)
    out: dict[str, set[int]] = defaultdict(set)
    cur = None
    for line in r.stdout.splitlines():
        if line.startswith("+++ "):
            cur = line[6:] if line.startswith("+++ b/") else None
        elif line.startswith("@@") and cur:
            m = re.search(r"\+(\d+)(?:,(\d+))?", line)
            a, n = int(m.group(1)), int(m.group(2) or "1")
            out[cur].update(range(a, a + max(n, 1)))
    return out


