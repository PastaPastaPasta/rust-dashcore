@dataclass
class Diag:
    code: str | None
    message: str
    file: str  # repo-relative
    start: int  # byte offsets of the primary span
    end: int
    line: int
    rendered: str
    children: list[dict]
    package_id: str


def cargo_json(cfg: Config, pkg: dict, clippy: bool = False) -> tuple[list[Diag], list[Diag], bool]:
    """Returns (errors in this package, errors elsewhere, built ok), over the crate's main check
    and its `extra` ones (`config.toml`), one cargo invocation after the other."""
    name = pkg["name"]
    main = [*cfg.skip_targets.get(name, ["--all-targets"]), *cfg.features.get(name, ["--all-features"])]
    mine, other, ok, seen = [], [], True, set()
    for args in [main, *cfg.extra.get(name, [])]:
        m, o, k = _cargo_json(cfg, pkg, args, clippy, seen)
        mine += m
        other += o
        ok = ok and k
    return mine, other, ok


def _cargo_json(cfg: Config, pkg: dict, args: list[str], clippy: bool, seen: set) -> tuple[list[Diag], list[Diag], bool]:
    name = pkg["name"]
    cmd = ["cargo", "clippy" if clippy else "check", "--manifest-path", cfg.manifest, "-p", name, *args,
           "--message-format=json"]
    if clippy:
        cmd += ["--", "-A", "clippy::all", "-W", "clippy::needless_borrow",
                "-W", "clippy::needless_borrows_for_generic_args"]
    env = dict(os.environ)
    env.setdefault("CARGO_BUILD_JOBS", "12")
    r = subprocess.run(cmd, cwd=cfg.repo, text=True, capture_output=True, env=env)
    mine, other = [], []
    for line in r.stdout.splitlines():
        try:
            m = json.loads(line)
        except json.JSONDecodeError:
            continue
        if m.get("reason") != "compiler-message":
            continue
        msg = m["message"]
        want = "warning" if clippy else "error"
        if msg["level"] != want:
            continue
        prim = [s for s in msg["spans"] if s["is_primary"]]
        if not prim:
            if not clippy:
                other.append(Diag(None, msg["message"], "", 0, 0, 0, msg.get("rendered") or "", [], m["package_id"]))
            continue
        sp = prim[0]
        while sp.get("expansion") and sp["expansion"].get("span"):
            # error inside a macro expansion: point at the invocation site
            if sp["file_name"].startswith("/") or "<" in sp["file_name"]:
                sp = sp["expansion"]["span"]
            else:
                break
        fname = sp["file_name"]
        absf = fname if os.path.isabs(fname) else os.path.join(cfg.ws_dir, fname)
        rel = os.path.relpath(absf, cfg.repo)
        d = Diag((msg.get("code") or {}).get("code"), msg["message"], rel, sp["byte_start"], sp["byte_end"],
                 sp["line_start"], msg.get("rendered") or "", msg["children"], m["package_id"])
        key = (d.code, d.file, d.start, d.end)
        if key in seen:
            continue
        seen.add(key)
        if m["package_id"] == pkg["id"] and not rel.startswith(".."):
            mine.append(d)
        else:
            other.append(d)
    ok = r.returncode == 0
    if not ok and not mine and not other:
        other.append(Diag(None, "cargo failed: " + r.stderr.strip().splitlines()[-1] if r.stderr.strip() else "cargo failed",
                          "", 0, 0, 0, r.stderr[-4000:], [], ""))
    return mine, other, ok


