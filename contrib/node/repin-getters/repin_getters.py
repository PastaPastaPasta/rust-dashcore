# Hand patches


def hand_patches(cfg: Config, crate: str) -> list[str]:
    d = hand_dir_for(cfg)
    if not os.path.isdir(d):
        return []
    pats = [f for f in os.listdir(d) if fnmatch.fnmatch(f, f"{crate}.*.patch")]
    pats.sort(key=lambda f: int(f.split(".")[-2]))
    return [os.path.join(d, f) for f in pats]


def hand_dir_for(cfg: Config) -> str:
    return os.path.join(cfg.hand_dir, cfg.manifest.replace("/", "_").removesuffix("Cargo.toml").rstrip("_") or "root")


def created_files(cfg: Config, crate: str | None = None) -> list[str]:
    """The files the hand patches create (`new file mode`), of one crate or of all, relative to
    the repository."""
    d = hand_dir_for(cfg)
    if not os.path.isdir(d):
        return []
    out = []
    for f in sorted(os.listdir(d)):
        if not f.endswith(".patch") or (crate is not None and not fnmatch.fnmatch(f, f"{crate}.*.patch")):
            continue
        cur = None
        with open(os.path.join(d, f)) as fh:
            for line in fh:
                if line.startswith("diff --git "):
                    cur = line.rstrip("\n").split(" b/", 1)[1]
                elif cur and line.startswith("new file mode"):
                    out.append(cur)
    return out


def add_created(cfg: Config, env: dict) -> None:
    """Adds the files hand patches created to the scratch index `env` names. `git add -u` sees
    tracked files only, so without this a snapshot would miss them (and a later `hand-save`
    would record them again) and `git apply --3way` would refuse a later patch to them."""
    files = [f for f in created_files(cfg) if os.path.exists(os.path.join(cfg.repo, f))]
    if files:
        subprocess.run(["git", "add", "--", *files], cwd=cfg.repo, env=env, check=True)


def remove_created(cfg: Config, crate: str) -> None:
    """`--fresh` for the files the crate's hand patches create: `git checkout HEAD` leaves an
    untracked file in place, and the patch that creates it would then fail. A file HEAD tracks
    is left to the checkout."""
    for f in created_files(cfg, crate):
        path = os.path.join(cfg.repo, f)
        tracked = subprocess.run(["git", "cat-file", "-e", f"HEAD:{f}"], cwd=cfg.repo,
                                 capture_output=True).returncode == 0
        if not tracked and os.path.exists(path):
            os.remove(path)


def apply_hand(cfg: Config, patch: str, st: CrateStats) -> str:
    """`git apply --3way` against a scratch index that matches the work tree, so the tool's
    unstaged rewrites count as the patch's base and the real index is never touched."""
    rel = os.path.relpath(patch, cfg.repo)
    os.makedirs(cfg.state_dir, exist_ok=True)
    idx = os.path.join(cfg.state_dir, "apply.index")
    env = dict(os.environ, GIT_INDEX_FILE=idx)
    subprocess.run(["git", "read-tree", "HEAD"], cwd=cfg.repo, env=env, check=True)
    subprocess.run(["git", "add", "-u", "."], cwd=cfg.repo, env=env, check=True)
    add_created(cfg, env)
    rev = subprocess.run(["git", "apply", "--reverse", "--check", patch], cwd=cfg.repo, env=env, text=True,
                         capture_output=True)
    if rev.returncode == 0:
        return "already"
    # rerere off: a resolution recorded for an earlier conflict must not silently resolve this one
    r = subprocess.run(["git", "-c", "rerere.enabled=false", "apply", "--3way", "--whitespace=nowarn", patch],
                       cwd=cfg.repo, env=env,
                       text=True, capture_output=True)
    out = (r.stdout + r.stderr).strip()
    if r.returncode == 0 and "conflict" not in out.lower():
        st.hand_applied.append(rel)
        return "applied"
    st.hand_failed.append((rel, out[-2000:]))
    return "failed"


def snapshot(cfg: Config) -> str:
    """A commit of the whole work tree (tracked files), without touching the index or HEAD."""
    idx = os.path.join(cfg.state_dir, "snap.index")
    os.makedirs(cfg.state_dir, exist_ok=True)
    env = dict(os.environ, GIT_INDEX_FILE=idx)
    subprocess.run(["git", "read-tree", "HEAD"], cwd=cfg.repo, env=env, check=True)
    subprocess.run(["git", "add", "-u", "."], cwd=cfg.repo, env=env, check=True)
    add_created(cfg, env)
    tree = subprocess.run(["git", "write-tree"], cwd=cfg.repo, env=env, check=True, text=True,
                          capture_output=True).stdout.strip()
    c = subprocess.run(["git", "commit-tree", tree, "-p", "HEAD", "-m", "repin-getters snapshot"], cwd=cfg.repo,
                       check=True, text=True, capture_output=True).stdout.strip()
    return c


