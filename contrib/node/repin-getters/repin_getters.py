def is_mut_method(name: str) -> bool:
    return name in MUT_METHODS or name.startswith("set_") or name.endswith("_mut") or "_mut_" in name


ASSIGN_OPS = {"=", "+=", "-=", "*=", "/=", "%=", "^=", "&=", "|=", "<<=", ">>="}


def sh(cmd: list[str], cwd: str, check: bool = True, **kw) -> subprocess.CompletedProcess:
    r = subprocess.run(cmd, cwd=cwd, text=True, capture_output=True, **kw)
    if check and r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit(f"command failed ({r.returncode}): {' '.join(cmd)}")
    return r


