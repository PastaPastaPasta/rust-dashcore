# Driver


def run_crate(cfg: Config, pkg: dict, api: bsdk_api.Api, base: str, max_rounds: int, state: dict) -> CrateStats:
    st = CrateStats()
    name = pkg["name"]
    patches = hand_patches(cfg, name)
    next_patch = 0
    stage = 0
    while True:
        for rnd in range(max_rounds):
            n, errs, other, ok = auto_round(cfg, pkg, api, st)
            log(f"  [{name}] stage {stage} round {rnd}: {len(errs)} errors, {n} rewrites"
                + (f", {len(other)} errors outside the crate" if other else ""))
            if n == 0:
                break
        if st.files:
            # rustfmt what the tool rewrote, so hand patches are recorded against formatted code
            sh(["rustfmt", "--edition", "2024", *sorted(st.files)], cfg.repo, check=False)
        state.setdefault("snapshots", {})[f"{name}.{stage}"] = state["last_snapshot"] = snapshot(cfg)
        if next_patch < len(patches):
            res = apply_hand(cfg, patches[next_patch], st)
            log(f"  [{name}] hand patch {os.path.basename(patches[next_patch])}: {res}")
            next_patch += 1
            stage += 1
            continue
        break
    if ok:
        nb = needless_borrow_round(cfg, pkg, base, st)
        if nb:
            log(f"  [{name}] needless borrows removed: {nb}")
            errs, other, ok = cargo_json(cfg, pkg)
    st.left = [(d.file, d.line, d.code, d.message) for d in errs]
    st.blocked = sorted({(os.path.relpath(d.file, cfg.repo) if d.file else d.package_id.split("#")[0][-60:],
                          d.message[:120]) for d in other})[:20]
    state["stage"][name] = stage
    return st


def save_stats(cfg: Config, name: str, st: CrateStats) -> None:
    os.makedirs(cfg.state_dir, exist_ok=True)
    with open(os.path.join(cfg.state_dir, f"{name}.json"), "w") as fh:
        json.dump({"auto": st.auto, "scripted": st.scripted, "hand_applied": st.hand_applied,
                   "hand_failed": st.hand_failed, "left": st.left, "blocked": st.blocked,
                   "nonequiv": st.nonequiv, "hand_sites": st.hand_sites}, fh, indent=1, default=list)


def load_state(cfg: Config) -> dict:
    p = os.path.join(cfg.state_dir, "state.json")
    if os.path.exists(p):
        with open(p) as fh:
            return json.load(fh)
    return {"stage": {}}


def write_state(cfg: Config, state: dict) -> None:
    os.makedirs(cfg.state_dir, exist_ok=True)
    with open(os.path.join(cfg.state_dir, "state.json"), "w") as fh:
        json.dump(state, fh, indent=1)


def cmd_order(cfg: Config, args) -> None:
    meta = cargo_metadata(cfg)
    for p in member_order(meta):
        print(p["name"])


def cmd_api(cfg: Config, args) -> None:
    meta = cargo_metadata(cfg)
    api = build_api(cfg, meta)
    json.dump(api.to_json(), sys.stdout, indent=1)
    print()


def cmd_run(cfg: Config, args) -> None:
    meta = cargo_metadata(cfg)
    api = build_api(cfg, meta)
    order = member_order(meta)
    names = [p["name"] for p in order]
    if args.crates:
        want = set(args.crates)
        unknown = want - set(names)
        if unknown:
            raise SystemExit(f"not a member that reaches base-sdk: {sorted(unknown)}")
        order = [p for p in order if p["name"] in want]
    elif args.start_at:
        order = order[names.index(args.start_at):]
    state = load_state(cfg)
    base = args.base or state.get("base") or sh(["git", "rev-parse", "HEAD"], cfg.repo).stdout.strip()
    state["base"] = base
    summary = []
    for pkg in order:
        log(f"== {pkg['name']}")
        if args.fresh:
            d = os.path.relpath(os.path.dirname(pkg["manifest_path"]), cfg.repo)
            sh(["git", "checkout", "HEAD", "--", d], cfg.repo)
            remove_created(cfg, pkg["name"])
        st = run_crate(cfg, pkg, api, base, args.max_rounds, state)
        save_stats(cfg, pkg["name"], st)
        write_state(cfg, state)
        status = "ok" if not st.left and not st.blocked else ("blocked" if st.blocked and not st.left else "errors")
        summary.append((pkg["name"], status, len(st.left)))
        log(f"   {pkg['name']}: {status}; auto {dict(st.auto)} scripted {dict(st.scripted)} "
            f"hand {len(st.hand_applied)} applied {len(st.hand_failed)} failed; {len(st.left)} errors left")
        for f, why in st.hand_failed:
            log(f"   HAND PATCH FAILED {f}:\n{why}")
        if st.blocked and not st.left:
            for b in st.blocked[:5]:
                log(f"   blocked: {b}")
        if args.stop_on_error and status != "ok":
            break
    if args.fmt:
        fmt_changed(cfg, base)
    log("\nsummary:")
    for n, s, k in summary:
        log(f"  {n:28} {s:8} {k}")


def fmt_changed(cfg: Config, base: str) -> None:
    files = [f for f in changed_line_map(cfg, base) if f.endswith(".rs")]
    if files:
        sh(["rustfmt", "--edition", "2024", *files], cfg.repo, check=False)


def cmd_hand_save(cfg: Config, args) -> None:
    """Save the work tree's changes since the tool's last snapshot as the crate's next hand patch.

    The tool's last snapshot holds everything it wrote, for every crate; what changed since is
    yours. Make the edits for one crate at a time, right after running it or a later crate."""
    state = load_state(cfg)
    stage = state["stage"].get(args.crate)
    if stage is None:
        raise SystemExit(f"{args.crate} has not been run yet")
    snap = state["last_snapshot"]
    d = hand_dir_for(cfg)
    os.makedirs(d, exist_ok=True)
    paths = args.paths or ["."]
    r = sh(["git", "diff", "--no-color", "--full-index", snap, "--", *paths,
            f":(exclude){os.path.relpath(HERE, cfg.repo)}"], cfg.repo)
    if not r.stdout.strip():
        raise SystemExit("no changes since the snapshot")
    existing = hand_patches(cfg, args.crate)
    n = len(existing) + 1
    if existing and stage < len(existing):
        raise SystemExit("the crate has hand patches the last run did not reach; re-run it first")
    path = os.path.join(d, f"{args.crate}.{n}.patch")
    with open(path, "w") as fh:
        fh.write(r.stdout)
    log(f"wrote {os.path.relpath(path, cfg.repo)} ({r.stdout.count(chr(10) + '@@')} hunks)")


def cmd_hand_list(cfg: Config, args) -> None:
    """Print the hand edits: every hunk of every patch, with its class from hand-edits.toml."""
    classes = {}
    p = os.path.join(HERE, "hand-edits.toml")
    if os.path.exists(p):
        with open(p, "rb") as fh:
            for e in tomllib.load(fh).get("edit", []):
                classes[(e["patch"], e["file"], e["hunk"])] = e
    d = hand_dir_for(cfg)
    rows = []
    for patch in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        for h in parse_patch(os.path.join(d, patch)):
            e = classes.get((patch, h["file"], h["hunk"]), {})
            rows.append({"patch": patch, **h, "class": e.get("class", "?"), "note": e.get("note", "")})
    if args.init:
        # One file serves every workspace: the other workspaces' entries are kept as they are,
        # the root's first.
        mine = set(os.listdir(d)) if os.path.isdir(d) else set()
        others = [e for e in classes.values() if e["patch"] not in mine]
        root = os.path.basename(d) == "root"
        entries = [*rows, *others] if root else [*others, *rows]
        out = []
        for r in entries:
            out.append(f'[[edit]]\npatch = "{r["patch"]}"\nfile = "{r["file"]}"\nhunk = {r["hunk"]}\n'
                       f'class = "{r["class"]}"\nnote = {json.dumps(r["note"])}\n')
        with open(p, "w") as fh:
            fh.write("# Hand edits: one entry per hunk of hand/**.patch. Classes: ctor setter rebuild ref/copy clone api mirror fork-api\n\n")
            fh.write("\n".join(out))
        log(f"wrote {p}")
        return
    for r in rows:
        print(f"{r['file']}:{r['line']}  [{r['class']}]  ({r['patch']} hunk {r['hunk']}) {r['note']}")
        for line in r["old"]:
            print(f"    - {line}")
        for line in r["new"]:
            print(f"    + {line}")


def parse_patch(path: str) -> list[dict]:
    out = []
    cur = None
    n = 0
    h = None
    with open(path) as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith("diff --git "):
                cur = line.split(" b/", 1)[1]
                n = 0
            elif line.startswith("@@") and cur:
                m = re.search(r"\+(\d+)", line)
                n += 1
                h = {"file": cur, "hunk": n, "line": int(m.group(1)), "old": [], "new": []}
                out.append(h)
            elif h is not None and line[:1] == "-" and not line.startswith("---"):
                h["old"].append(line[1:].strip())
            elif h is not None and line[:1] == "+" and not line.startswith("+++"):
                h["new"].append(line[1:].strip())
    return out


def cmd_report(cfg: Config, args) -> None:
    """Per-crate table and the non-equivalence list from the last run's state."""
    meta = cargo_metadata(cfg)
    rows = []
    for p in member_order(meta):
        f = os.path.join(cfg.state_dir, f"{p['name']}.json")
        if not os.path.exists(f):
            continue
        with open(f) as fh:
            s = json.load(fh)
        rows.append((p["name"], s))
    print("| crate | auto | scripted | hand patches | left |")
    print("|---|---|---|---|---|")
    for n, s in rows:
        print(f"| {n} | {sum(s['auto'].values())} {dict(s['auto'])} | {sum(s['scripted'].values())} {dict(s['scripted'])} "
              f"| {len(s['hand_applied'])} ({len(s['hand_failed'])} failed) | {len(s['left'])}"
              f"{' blocked' if s['blocked'] and not s['left'] else ''} |")
    if args.nonequiv:
        print("\nnon-equivalence (tool):")
        for n, s in rows:
            for e in s["nonequiv"]:
                print(f"- {e['file']} fn {e.get('fn', '?')} [{e['kind']}] `{e['old']}` -> `{e['new']}`: {e['why']}")
    if args.left:
        for n, s in rows:
            for e in s["left"]:
                print(f"{n}: {e[0]}:{e[1]} {e[2]} {e[3]}")
            for e in s["hand_sites"]:
                print(f"{n}: HAND {e[0]}:{e[1]} {e[2]} {e[3]} -- {e[4]}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", default=os.getcwd())
    ap.add_argument("--manifest", default="Cargo.toml", help="workspace manifest, relative to --repo")
    ap.add_argument("--state", help="state dir (default target/repin-getters)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("order", help="members that reach base-sdk, in dependency order")
    sub.add_parser("api", help="base-sdk's private-field table as JSON")
    r = sub.add_parser("run", help="auto pass + scripted rewrites + hand patches, crate by crate")
    r.add_argument("crates", nargs="*")
    r.add_argument("--start-at")
    r.add_argument("--base", help="commit the port starts from (default: HEAD at the first run)")
    r.add_argument("--max-rounds", type=int, default=12)
    r.add_argument("--stop-on-error", action="store_true")
    r.add_argument("--fmt", action="store_true", help="rustfmt the changed files at the end")
    r.add_argument("--fresh", action="store_true",
                   help="reset each crate's directory to HEAD first (discards unsaved hand edits there)")
