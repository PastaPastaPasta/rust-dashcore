@dataclass
class Config:
    repo: str
    manifest: str  # relative manifest path, "Cargo.toml" for the root workspace
    renames: dict[tuple[str, str], str]
    variant_renames: dict[tuple[str, str], str]  # (enum, old variant) -> new variant
    features: dict[str, list[str]]  # crate -> cargo feature args, when --all-features is broken
    skip_targets: dict[str, list[str]]  # crate -> target args replacing --all-targets
    extra: dict[str, list[list[str]]]  # crate -> more checks: target and feature args of each
    restore: list[dict]  # `[[restore]]`: putting back a field a reset constructor resets
    hand_dir: str
    state_dir: str

    @property
    def ws_dir(self) -> str:
        return os.path.dirname(os.path.join(self.repo, self.manifest))


def load_config(args) -> Config:
    with open(os.path.join(HERE, "config.toml"), "rb") as fh:
        conf = tomllib.load(fh)
    renames = {}
    for r in conf.get("rename", []):
        renames[(r["struct"], r["old"])] = r["new"]
    variant_renames = {(r["enum"], r["old"]): r["new"] for r in conf.get("variant-rename", [])}
    ws = conf.get("workspace", {}).get(args.manifest, {})
    state = args.state or os.path.join(args.repo, "target", "repin-getters")
    return Config(
        repo=args.repo,
        manifest=args.manifest,
        renames=renames,
        variant_renames=variant_renames,
        features={k: v for k, v in ws.get("features", {}).items()},
        skip_targets={k: v for k, v in ws.get("targets", {}).items()},
        extra={k: v for k, v in ws.get("extra", {}).items()},
        restore=conf.get("restore", []),
        hand_dir=os.path.join(HERE, "hand"),
        state_dir=os.path.join(state, args.manifest.replace("/", "_")),
    )


