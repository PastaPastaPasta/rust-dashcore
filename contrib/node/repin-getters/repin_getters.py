# cargo metadata: members, base-sdk sources, dependency order


def cargo_metadata(cfg: Config) -> dict:
    """With every feature on, as the checks build: an optional dependency orders its user too."""
    r = sh(["cargo", "metadata", "--format-version", "1", "--all-features", "--manifest-path",
            cfg.manifest], cfg.repo)
    return json.loads(r.stdout)


def member_order(meta: dict) -> list[dict]:
    """Workspace members that reach base-sdk, in dependency order (deps first)."""
    pkgs = {p["id"]: p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}

    def kinds(dep):
        return {k.get("kind") for k in dep.get("dep_kinds", [])}

    bsdk = {pid for pid, p in pkgs.items() if "base-sdk" in (p.get("source") or "")}
    reach: dict[str, bool] = {}

    def reaches(pid: str, seen=()) -> bool:
        if pid in reach:
            return reach[pid]
        if pid in bsdk:
            return True
        if pid in seen:
            return False
        out = any(reaches(d["pkg"], seen + (pid,)) for d in nodes[pid]["deps"])
        reach[pid] = out
        return out

    todo = sorted((m for m in members if reaches(m)), key=lambda m: pkgs[m]["name"])
    hard: dict[str, set[str]] = {m: set() for m in todo}
    dev: dict[str, set[str]] = {m: set() for m in todo}
    for m in todo:
        for d in nodes[m]["deps"]:
            if d["pkg"] not in hard:
                continue
            if kinds(d) - {"dev"}:
                hard[m].add(d["pkg"])
            else:
                dev[m].add(d["pkg"])

    def has_path(a: str, b: str, edges) -> bool:
        stack, seen = [a], set()
        while stack:
            x = stack.pop()
            if x == b:
                return True
            if x in seen:
                continue
            seen.add(x)
            stack.extend(edges[x])
        return False

    edges = {m: set(hard[m]) for m in todo}
    for m in todo:
        for d in sorted(dev[m]):
            if d != m and not has_path(d, m, edges):
                edges[m].add(d)
    order, done = [], set()
    while len(order) < len(todo):
        ready = [m for m in todo if m not in done and edges[m] <= done]
        if not ready:
            raise SystemExit("dependency cycle among members")
        m = ready[0]
        order.append(m)
        done.add(m)
    return [pkgs[m] for m in order]


def build_api(cfg: Config, meta: dict) -> bsdk_api.Api:
    srcs = bsdk_api.bsdk_sources(meta)
    if not srcs:
        raise SystemExit("no base-sdk packages in cargo metadata (run `cargo fetch` first?)")
    api = bsdk_api.load_api(srcs, cfg.renames)
    # a struct the workspace's base-sdk packages do not define (a nested workspace that does not
    # reach it) is skipped; one that is there must match
    for (st, old), new in cfg.renames.items():
        s = api.lookup(st)
        if s is None:
            continue
        if s.field(new) is None or s.field(old) is not None:
            raise SystemExit(f"rename {st}.{old} -> {new} does not match base-sdk's source; update config.toml")
    for (enum, old), new in cfg.variant_renames.items():
        variants = bsdk_api.enum_variants(list(srcs.values()), enum)
        if variants is None:
            continue
        if new not in variants or old in variants:
            raise SystemExit(f"variant rename {enum}::{old} -> {new} does not match base-sdk's source; "
                             f"update config.toml")
    for r in cfg.restore:
        for st in r["structs"]:
            s = api.lookup(st)
            if s is None:
                continue
            c = s.reset_ctor()
            if c is None or set(c.reset) != {r["field"]} or s.field(r["field"]).getter != "get":
                raise SystemExit(f"restore: {st}'s constructor does not reset only `{r['field']}` behind a "
                                 f"`get` getter in base-sdk's source; update config.toml")
    set_restore(cfg, meta)
    API_RENAMES.clear()
    API_RENAMES.update(cfg.renames)
    return api


API_RENAMES: dict[tuple[str, str], str] = {}


# package id -> struct name -> (field, path of the function putting it back)
RESTORE: dict[str, dict[str, tuple[str, str]]] = {}


def set_restore(cfg: Config, meta: dict) -> None:
    """Which members reach each `[[restore]]` helper: the crate defining it (through `in_crate`),
    and every member depending on it, of any kind, with its feature (through `path`)."""
    RESTORE.clear()
    for p in meta["packages"]:
        if p["id"] not in meta["workspace_members"]:
            continue
        for r in cfg.restore:
            if p["name"] == r["crate"]:
                path = r["in_crate"]
            elif any(d["name"] == r["crate"] and r["feature"] in d.get("features", [])
                     for d in p["dependencies"]):
                path = r["path"]
            else:
                continue
            for st in r["structs"]:
                RESTORE.setdefault(p["id"], {})[st] = (r["field"], path)


