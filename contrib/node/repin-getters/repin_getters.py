# Source files


class Source:
    def __init__(self, path: str):
        self.path = path
        with open(path, "rb") as fh:
            self.text = fh.read().decode("latin-1")
        self.orig = self.text
        self._toks = None

    @property
    def toks(self):
        if self._toks is None:
            self._toks = lex(self.text)
        return self._toks

    def splice(self, start: int, end: int, new: str) -> None:
        self.text = self.text[:start] + new + self.text[end:]
        self._toks = None

    def save(self) -> bool:
        if self.text == self.orig:
            return False
        with open(self.path, "wb") as fh:
            fh.write(self.text.encode("latin-1"))
        self.orig = self.text
        return True

    def line(self, offset: int) -> int:
        return self.text.count("\n", 0, offset) + 1


