#!/usr/bin/env python3
"""Writes dash-consensus/src/fp/kgw_pow.rs: KGW's pow table (CS2 design §2.4).

KGW calls pow(fl(m / 28.2), fl(-1.228)) for its mass m = 1..=4032, the call's whole input
domain (CS2-fp-release-binaries.md §4.1). The table holds the correctly rounded binary64
value of each call, from MPFR through gmpy2:
  - x = fl(m / 28.2) is computed with IEEE binary64 division, as Core does;
  - pow is evaluated at 53 bits, round to nearest even, which MPFR guarantees is the
    correctly rounded result;
  - a second evaluation at 256 bits must round to the same double.

Usage (from anywhere; needs gmpy2, e.g. `pip install gmpy2==2.3.2` in a venv):
  gen-kgw-pow.py                 rewrite the file
  gen-kgw-pow.py --check         exit 1 unless the file is what this script writes
  gen-kgw-pow.py --cr CR_TXT     also require equality with a table of `m hex(x) hex(pow)`
                                 lines (the evidence's out/pow-tables/cr.txt)
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

import gmpy2
from gmpy2 import mpfr

MASSES = 4032
OUT = Path(__file__).resolve().parents[3] / "dash-consensus" / "src" / "fp" / "kgw_pow.rs"


def bits(d: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", d))[0]


def kgw_pow(m: int, precision: int) -> float:
    ctx = gmpy2.get_context()
    ctx.precision = precision
    ctx.round = gmpy2.RoundToNearest
    # float(...) rounds the result to the nearest double
    return float(mpfr(float(m) / 28.2) ** mpfr(-1.228))


def table() -> list[int]:
    values = []
    for m in range(1, MASSES + 1):
        p53 = kgw_pow(m, 53)
        p256 = kgw_pow(m, 256)
        assert p53 == p256, f"m={m}: 53-bit {p53!r} and 256-bit {p256!r} round differently"
        values.append(bits(p53))
    return values


def render(values: list[int]) -> str:
    listing = "".join(f"{v:016x}\n" for v in values)
    digest = hashlib.sha256(listing.encode()).hexdigest()
    lines = [
        "//! KGW's `pow(fl(m / 28.2), fl(-1.228))` for every mass m = 1..=4032, correctly rounded",
        "//! (CS2 design §2.4).",
        "//!",
        "//! @generated by `contrib/node/fp/gen-kgw-pow.py`; do not edit. Regenerate (or check, with",
        "//! `--check`) with gmpy2 installed:",
        "//!",
        "//! ```text",
        "//! python3 -I contrib/node/fp/gen-kgw-pow.py",
        "//! ```",
        "//!",
        f"//! Written with MPFR {gmpy2.mpfr_version().split()[-1]} and gmpy2 {gmpy2.version()}. Each value is MPFR's 53-bit",
        "//! round-to-nearest `pow`, and a 256-bit evaluation rounds to the same double. The sha256 of",
        "//! the values, one `%016x` line each for m = 1..=4032, is that of the third column of the",
        "//! evidence's `out/pow-tables/cr.txt`:",
        f"//! `{digest}`.",
        "//!",
        "//! This is derived data, not a Dash Core fixture. That Core's decisions follow from it is",
        "//! proven by `fp`'s tests and the oracle differential (CS2-fp-release-binaries.md §4).",
        "",
        "/// `KGW_POW[m - 1]` is the bit pattern of the binary64 nearest to `pow(fl(m / 28.2),",
        "/// fl(-1.228))`.",
        f"pub(super) static KGW_POW: [u64; {MASSES}] = [",
    ]
    lines += [f"    0x{v:016x}, // m = {m}" for m, v in enumerate(values, start=1)]
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--cr", type=Path)
    args = ap.parse_args()
    values = table()
    if args.cr:
        for line in args.cr.read_text().splitlines():
            m, x, p = line.split()[:3]
            m = int(m)
            assert int(x, 16) == bits(float(m) / 28.2), f"{args.cr}: x at m={m}"
            assert int(p, 16) == values[m - 1], f"{args.cr}: pow at m={m}"
        print(f"{args.cr}: equal")
    text = render(values)
    if args.check:
        same = OUT.read_text() == text
        print(f"{OUT}: {'up to date' if same else 'DIFFERS'}")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
