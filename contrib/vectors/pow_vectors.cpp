#include <arith_uint256.h>
#include <uint256.h>

#include <cstdint>
#include <cstdio>
#include <iostream>
#include <random>
#include <set>
#include <string>
#include <vector>

static const uint64_t SEED = 0x646173682d706f77; // "dash-pow"

// Big-endian hex without leading zeros, "0" for zero.
static std::string Hex(const arith_uint256& v)
{
    const std::string full = ArithToUint256(v).GetHex();
    const size_t first = full.find_first_not_of('0');
    return first == std::string::npos ? "0" : full.substr(first);
}

static std::string Hex32(uint32_t v)
{
    char buf[9];
    snprintf(buf, sizeof buf, "%08x", v);
    return buf;
}

// Core's GetBlockProof (chain.cpp) given the SetCompact results.
static arith_uint256 BlockProof(const arith_uint256& target, bool negative, bool overflow)
{
    if (negative || overflow || target == 0) return 0;
    return (~target / (target + 1)) + 1;
}

static const char* Bool(bool b) { return b ? "true" : "false"; }

int main()
{
    std::mt19937_64 rng(SEED);

    // nBits vectors.
    std::vector<uint32_t> bits;
    std::set<uint32_t> seen;
    auto add_bits = [&](uint32_t n) {
        if (seen.insert(n).second) bits.push_back(n);
    };

    // Mantissas that exercise zero, the sign bit, and the 8 and 16 bit boundaries.
    const uint32_t edge_mantissas[] = {
        0x000000, 0x000001, 0x00007f, 0x000080, 0x0000fe, 0x0000ff, 0x000100, 0x000101,
        0x007fff, 0x008000, 0x00fffe, 0x00ffff, 0x010000, 0x010001, 0x123456, 0x7ffffe,
        0x7fffff, 0x800000, 0x800001, 0x923456, 0xfffffe, 0xffffff,
    };
    // A few mantissas for every one of the 256 exponents.
    const uint32_t every_exponent_mantissas[] = {0x000000, 0x000001, 0x00ffff, 0x7fffff, 0x800000, 0xffffff};
    for (uint32_t exponent = 0; exponent < 256; ++exponent) {
        for (uint32_t m : every_exponent_mantissas) add_bits(exponent << 24 | m);
    }
    // All edge mantissas around the small-exponent shifts and the overflow boundary.
    const uint32_t edge_exponents[] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x1b, 0x1c, 0x1d, 0x1e,
                                       0x1f, 0x20, 0x21, 0x22, 0x23, 0x24, 0xff};
    for (uint32_t exponent : edge_exponents) {
        for (uint32_t m : edge_mantissas) add_bits(exponent << 24 | m);
    }
    // Seeded random nBits, biased to realistic exponents for half of them.
    for (int i = 0; i < 100; ++i) {
        add_bits(static_cast<uint32_t>(rng()));
        add_bits((0x18u + static_cast<uint32_t>(rng() % 0x0a)) << 24 | static_cast<uint32_t>(rng() & 0xffffff));
    }

    // Targets for target -> compact.
    std::vector<arith_uint256> targets;
    std::set<std::string> seen_targets;
    auto add_target = [&](const arith_uint256& t) {
        if (seen_targets.insert(Hex(t)).second) targets.push_back(t);
    };
    add_target(arith_uint256(0));
    add_target(~arith_uint256());
    for (unsigned k = 0; k < 256; ++k) {
        arith_uint256 p = arith_uint256(1) << k;
        add_target(p);
        add_target(p - 1);
        if (k < 255) add_target(p + 1);
    }
    for (int i = 0; i < 100; ++i) {
        // Random value with a random bit length.
        arith_uint256 t;
        for (int w = 0; w < 4; ++w) t = (t << 64) | arith_uint256(rng());
        add_target(t >> static_cast<unsigned>(rng() % 256));
    }

    std::cout << "{\n";
    std::cout << "  \"comment\": \"Generated by contrib/vectors/pow_vectors.cpp from Dash Core's arith_uint256. "
                 "Hex values are big-endian without leading zeros.\",\n";
    std::cout << "  \"compact_fields\": [\"nBits\", \"SetCompact value (raw)\", \"negative\", \"overflow\", "
                 "\"GetBlockProof\", \"GetCompact(raw value)\"],\n";
    std::cout << "  \"compact\": [\n";
    for (size_t i = 0; i < bits.size(); ++i) {
        bool negative, overflow;
        arith_uint256 value;
        value.SetCompact(bits[i], &negative, &overflow);
        std::cout << "    [\"" << Hex32(bits[i]) << "\",\"" << Hex(value) << "\"," << Bool(negative) << ","
                  << Bool(overflow) << ",\"" << Hex(BlockProof(value, negative, overflow)) << "\",\""
                  << Hex32(value.GetCompact(false)) << "\"]" << (i + 1 < bits.size() ? "," : "") << "\n";
    }
    std::cout << "  ],\n";
    std::cout << "  \"target_fields\": [\"target\", \"GetCompact\", \"GetBlockProof (null for 2^256-1, "
                 "where Core divides by zero)\"],\n";
    std::cout << "  \"target\": [\n";
    for (size_t i = 0; i < targets.size(); ++i) {
        const arith_uint256& t = targets[i];
        std::cout << "    [\"" << Hex(t) << "\",\"" << Hex32(t.GetCompact(false)) << "\",";
        if (t == ~arith_uint256()) {
            std::cout << "null";
        } else {
            std::cout << "\"" << Hex(BlockProof(t, false, false)) << "\"";
        }
        std::cout << "]" << (i + 1 < targets.size() ? "," : "") << "\n";
    }
    std::cout << "  ]\n}\n";
    return 0;
}
