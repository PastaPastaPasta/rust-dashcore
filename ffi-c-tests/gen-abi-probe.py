#!/usr/bin/env python3
"""Writes abi-probe.c: a C program that prints the layout of every struct and the value of
every enum constant and integer macro in the baseline headers. It also redeclares every
baseline dash-spv-ffi function and callback typedef, so a changed signature fails to compile.

Usage: gen-abi-probe.py <baseline include dir>
"""

import re
import sys
from pathlib import Path

HEADERS = [
    "dash-network/dash-network.h",
    "key-wallet-ffi/key-wallet-ffi.h",
    "dash-spv-ffi/dash-spv-ffi.h",
]

COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
STRUCT = re.compile(r"^typedef struct(?: \w+)? \{\n(.*?)^\} (\w+);", re.S | re.M)
ENUM = re.compile(r"^typedef enum(?: \w+)? \{\n(.*?)^\} (\w+);", re.S | re.M)
MACRO = re.compile(r"^#define (\w+) (\S+)$", re.M)
CALLBACK = re.compile(r"^typedef [^;{]*\(\*\s*\w+\)\s*\(.*?\);", re.S | re.M)
EXTERN_C = re.compile(r'^extern "C" \{\n#endif[ \t]*\n(.*?)^#ifdef __cplusplus\n\}', re.S | re.M)
FIELD_NAME = re.compile(r"\(\*\s*(\w+)\)|(\w+)\s*(?:\[[^\]]*\])?\s*$")


def field_names(body):
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        m = FIELD_NAME.search(decl)
        if not m:
            sys.exit(f"cannot parse field: {decl!r}")
        yield m.group(1) or m.group(2)


def signatures(text):
    """Yields every callback typedef and function prototype of `text`, whitespace collapsed."""
    for m in CALLBACK.finditer(text):
        yield " ".join(m[0].split())
    extern_c = EXTERN_C.search(text)
    if not extern_c:
        sys.exit("cannot find the extern \"C\" block")
    for decl in extern_c[1].split(";"):
        decl = " ".join(decl.split())
        if decl:
            yield decl + ";"


def main():
    base = Path(sys.argv[1])
    lines = []
    decls = list(signatures(COMMENT.sub("", (base / HEADERS[-1]).read_text())))
    for header in HEADERS:
        text = COMMENT.sub("", (base / header).read_text())
        for m in MACRO.finditer(text):
            lines.append(f'  printf("define {m[1]} %lld\\n", (long long)({m[1]}));')
        for m in ENUM.finditer(text):
            lines.append(f'  printf("sizeof {m[2]} %zu\\n", sizeof({m[2]}));')
            for const in m[1].replace("\n", " ").split(","):
                name = const.split("=")[0].strip()
                if name:
                    lines.append(f'  printf("enum {name} %lld\\n", (long long)({name}));')
        for m in STRUCT.finditer(text):
            body, name = m[1], m[2]
            lines.append(f'  printf("sizeof {name} %zu\\n", sizeof({name}));')
            lines.append(f'  printf("alignof {name} %zu\\n", _Alignof({name}));')
            for field in field_names(body):
                lines.append(
                    f'  printf("offsetof {name}.{field} %zu\\n", offsetof({name}, {field}));'
                )
                lines.append(
                    f'  printf("sizeof {name}.{field} %zu\\n", sizeof((({name} *)0)->{field}));'
                )
    print("/* Generated by gen-abi-probe.py from ffi-c-tests/baseline. Do not edit. */")
    print("#include <stddef.h>")
    print("#include <stdio.h>")
    print('#include "dash-spv-ffi/dash-spv-ffi.h"')
    print()
    print("\n".join(decls))
    print()
    print("int main(void) {")
    print("\n".join(lines))
    print("  return 0;")
    print("}")


if __name__ == "__main__":
    main()
