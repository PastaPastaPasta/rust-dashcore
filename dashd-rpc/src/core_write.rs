const OP_PUSHDATA1: u8 = 0x4c;
const OP_PUSHDATA2: u8 = 0x4d;
const OP_PUSHDATA4: u8 = 0x4e;
const OP_16: u8 = 0x60;
const OP_RETURN: u8 = 0x6a;

/// `GetScriptOp`: the next opcode and its push data, advancing `pc`; `None` where the script
/// ends or a push runs past its end.
// Core: script/script.cpp:259-310
pub(crate) fn get_op<'a>(pc: &mut &'a [u8]) -> Option<(u8, &'a [u8])> {
    let (&opcode, rest) = pc.split_first()?;
    let (size, rest) = match opcode {
        0..OP_PUSHDATA1 => (usize::from(opcode), rest),
        OP_PUSHDATA1 => (usize::from(*rest.first()?), &rest[1..]),
        OP_PUSHDATA2 => {
            let (n, rest) = rest.split_first_chunk::<2>()?;
            (usize::from(u16::from_le_bytes(*n)), rest)
        }
        OP_PUSHDATA4 => {
            let (n, rest) = rest.split_first_chunk::<4>()?;
            (usize::try_from(u32::from_le_bytes(*n)).ok()?, rest)
        }
        _ => {
            *pc = rest;
            return Some((opcode, &[]));
        }
    };
    let data = rest.get(..size)?;
    *pc = &rest[size..];
    Some((opcode, data))
}

