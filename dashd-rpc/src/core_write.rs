/// `CScriptNum(vch, false).getint()` for a push of at most 4 bytes: little-endian, the top bit of
/// the last byte the sign; such a value always fits an `int`.
// Core: script/script.h:236-247 getint, :334-357 set_vch
fn script_num(data: &[u8]) -> i64 {
    let Some((&last, _)) = data.split_last() else {
        return 0;
    };
    let value = data.iter().rev().fold(0i64, |acc, &b| (acc << 8) | i64::from(b));
    if last & 0x80 != 0 {
        -(value & !(0x80i64 << (8 * (data.len() - 1))))
    } else {
        value
    }
}

/// `ScriptToAsmStr(script, false)`: each op space-separated; a push of at most 4 bytes as its
/// number, a longer one as hex, any other opcode by name; `[error]` where an op cannot be read.
/// The `fAttemptSighashDecode = true` mode, which scriptSigs print with, is RP1a-2c's (D38).
// Core: core_write.cpp:107-157
pub(crate) fn script_to_asm_str(script: &[u8]) -> String {
    let mut out = String::new();
    let mut pc = script;
    while !pc.is_empty() {
        if !out.is_empty() {
            out.push(' ');
        }
        let Some((opcode, data)) = get_op(&mut pc) else {
            out += "[error]";
            return out;
        };
        if opcode <= OP_PUSHDATA4 {
            if data.len() <= 4 {
                out += &script_num(data).to_string();
            } else {
                out += &hex(data);
            }
        } else {
            out += get_op_name(opcode);
        }
    }
    out
}

/// `TxoutType`, as `Solver` classifies a script.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TxoutType {
    Nonstandard,
    Pubkey,
    PubkeyHash,
    ScriptHash,
    Multisig,
    NullData,
}

impl TxoutType {
    /// `GetTxnOutputType`.
    // Core: script/standard.cpp:29-40
    pub fn name(self) -> &'static str {
        match self {
            TxoutType::Nonstandard => "nonstandard",
            TxoutType::Pubkey => "pubkey",
            TxoutType::PubkeyHash => "pubkeyhash",
            TxoutType::ScriptHash => "scripthash",
            TxoutType::Multisig => "multisig",
            TxoutType::NullData => "nulldata",
        }
    }
}

/// `Solver`'s type: P2SH first, then a data carrier (`OP_RETURN` and pushes only), P2PK, P2PKH,
/// and a multisig.
// Core: script/standard.cpp:115-159
pub fn solver(script: &[u8]) -> TxoutType {
    match script {
        [0xa9, 20, h @ .., 0x87] if h.len() == 20 => TxoutType::ScriptHash,
        [OP_RETURN, rest @ ..] if is_push_only(rest) => TxoutType::NullData,
        _ if match_pay_to_pubkey(script).is_some() => TxoutType::Pubkey,
        [0x76, 0xa9, 20, h @ .., 0x88, 0xac] if h.len() == 20 => TxoutType::PubkeyHash,
        _ if match_multisig(script).is_some() => TxoutType::Multisig,
        _ => TxoutType::Nonstandard,
    }
}

/// `CScript::IsPushOnly`: every op reads and is at most `OP_16` (`OP_RESERVED` included).
// Core: script/script.cpp:237-252
fn is_push_only(mut pc: &[u8]) -> bool {
    while !pc.is_empty() {
        match get_op(&mut pc) {
            Some((opcode, _)) if opcode <= OP_16 => {}
            _ => return false,
        }
    }
    true
}

/// `ScriptToUniv(script, out, include_hex, include_address)`: `asm`, the inferred `desc`, `hex`,
/// the `address` (not for P2PK) and the `type`.
// Core: core_write.cpp:159-178
pub fn script_to_univ(
    script: &[u8],
    include_hex: bool,
    include_address: bool,
    p: &KeyIoParams,
) -> UniValue {
    let mut out = UniValue::new_object();
    out.push_kv_end("asm", script_to_asm_str(script).into());
    if include_address {
        out.push_kv_end("desc", infer_descriptor(script, p).into());
    }
    if include_hex {
        out.push_kv_end("hex", hex(script).into());
    }
    let ty = solver(script);
    if include_address
        && ty != TxoutType::Pubkey
        && let Some(dest) = extract_destination(script)
    {
        out.push_kv_end("address", encode_destination(&dest, p).into());
    }
    out.push_kv_end("type", ty.name().into());
    out
}

