/// Core: `sha256_sse4::Transform`.
#[target_feature(enable = "ssse3")]
pub(crate) fn transform(s: &mut [u32; 8], blocks: &[[u8; 64]]) {
    // SAFETY: this function has SSSE3; `s` has 8 words and `blocks` is `blocks.len()`
    // contiguous 64-byte blocks.
    unsafe { transform_asm(s.as_mut_ptr(), blocks.as_ptr().cast(), blocks.len()) }
}

/// Core: `TransformD64Wrapper<sha256_sse4::Transform>`.
#[target_feature(enable = "ssse3")]
pub(crate) fn transform_d64(out: &mut [u8; 32], input: &[u8; 64]) {
    // SAFETY: this function has `transform`'s features.
    unsafe { portable::d64_wrapper(transform, out, input) }
}
