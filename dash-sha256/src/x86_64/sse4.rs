//! The SSE4 single-stream transform (Core: `sha256_sse4::Transform`, `crypto/sha256_sse4.cpp`).
//!
//! Core's asm statement needs 14 general-purpose registers, more than Rust's inline `asm!` can
//! allocate (it reserves `rbx` and `rbp`), so the transform is a naked function with its own
//! frame. Core's operands map to:
//!
//! | Core | Here |
//! |---|---|
//! | `s`, `chunk`, `blocks` (and `e` in its low half) | `rdi`, `rsi`, `rdx` / `edx` |
//! | `a`, `b`, `c`, `d`, `f`, `g`, `h` | `eax`, `ebx`, `ecx`, `r8d`, `r9d`, `r10d`, `r11d` |
//! | `y0`, `y1`, `y2`, `tbl` | `r12d`, `r13d`, `r14d`, `r15` |
//! | `xfer`, `inp_end`, `inp` | `0(%rsp)`, `16(%rsp)`, `24(%rsp)` |
//! | `K256`, `FLIP_MASK`, `SHUF_00BA`, `SHUF_DC00` | the statics below, RIP-relative |
//!
//! The labels `Lloop0`, `Lloop1`, `Lloop2` and `Ldone_hash` are `2`, `3`, `4` and `5`. The
//! function uses the System V ABI on every target, so the caller saves the XMM registers.
//! It has no unwind information (CFI or `.pdata`): nothing can unwind out of it, but a debugger
//! or sampling profiler that stops inside it may show a wrong caller.

