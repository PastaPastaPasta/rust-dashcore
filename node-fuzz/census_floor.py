#!/usr/bin/env python3
"""The census floor gate (O2b-4 §4.5-§4.6, D46, D56): one evaluator for run.sh and fuzzctl.

    python3 -I node-fuzz/census_floor.py gate --run R --target T --pin P --encoding E --floor-src F

run.sh runs `gate` after a certify run's replay before the window (segment 2) passed with no
finding, and launches the window only when it exits 0. It copies the floor F to
R/logs/segment-2/floor.json, checks the copy against R/floor.sha256 (written when the binary was
built), reads segment 2's phase census (R/logs/segment-2/census.json), binds it to the run
(target, phase, run id, pin, encoding, a complete exit fold, and one execution per unit the
replay's INITED line counts), evaluates it against the floor, and writes
R/logs/segment-2/floor-result.json (0600). Exit 0: the floor is met; 1: missed; 2: any error (a
missing or malformed floor or census, a failed census write, a provenance mismatch).

fuzzctl loads this file by its path (it runs as `python3 -I`, which keeps this directory off
sys.path) and re-judges a run's stored census with `judge_run`, against both the floor copy the
run recorded and the target's floor now.

A floor (`node-l1/census/<target>.floor.json`, generated by O2b-4 4e1):

    {"schema": "o2b4-census-floor/1", "floor_version": 1, "target": T, "profile": "S0", "encoding": E,
     "inventory_sha256": "<64 hex>", "overlay_sha256": "<64 hex>",
     "require": {"inventory": [...], "ops": [...], "rejects": [...], "rows": [...]},
     "bounds": {"discard_rate_max": 0.01, "unexpected_max": 0, "replay_mismatches_max": 0,
                "queue_drain_share_max": 0.05, "legb_share_min": null},
     "report_only": [...], "declared_gaps": {"inventory": [...], "ops": [...], "rejects": [...]}}

It is met when every `require` key counts at least 1 in the census's map of that name and every
bound that is not null holds; `report_only` keys are reported with their counts and never
credited. `declared_gaps` holds the profile's encoding gaps (BL-835), each keyed exactly in its
census map: one a census counts is reported as reached_while_declared with its count, never
credited and never a miss (DEC-1567). Any other key, a missing one, a wrong schema or type, or a target or encoding other than
the run's makes it malformed.
"""

import hashlib
import json
import math
import os
import re
import sys

SCHEMA = "o2b4-census-floor/1"
FLOOR_KEYS = {"schema", "floor_version", "target", "profile", "encoding", "inventory_sha256", "overlay_sha256",
              "require", "bounds", "report_only", "declared_gaps"}
REQUIRE_KEYS = ("inventory", "ops", "rejects", "rows")
GAP_KEYS = ("inventory", "ops", "rejects")
COUNT_BOUNDS = ("unexpected_max", "replay_mismatches_max")
SHARE_BOUNDS = ("discard_rate_max", "queue_drain_share_max", "legb_share_min")
PROFILES = ("S0", "S1", "S2", "S0p")
HEX64 = re.compile(r"[0-9a-f]{64}")
# The phase census's destination, beside which node-l1 leaves this marker when a write failed.
CENSUS = "census.json"
FAILED_MARKER = "census.failed"
SEGMENT = "segment-2"
PHASE = "pre-replay"
FLOOR_COPY = "floor.json"
RESULT = "floor-result.json"
FLOOR_SHA = "floor.sha256"
# An op the second system ran unserved because its queue held work (D49): `<kind>:<this>`.
QUEUE_DRAIN = "unsupported-queue-drain"
INITED = re.compile(rb"^#(\d+)\s+INITED\b", re.M)


def is_count(x, least=0):
    return isinstance(x, int) and not isinstance(x, bool) and x >= least


def is_share(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x) and 0 <= x <= 1


def read_json(path):
    """(value, problem): the problem is None when the file reads as JSON."""
    try:
        with open(path, "rb") as f:
            return json.load(f), None
    except FileNotFoundError:
        return None, "missing"
    except Exception as e:  # noqa: BLE001 (a torn or hostile file: a nesting too deep included)
        return None, f"unreadable ({type(e).__name__})"


def sha256_file(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def load_floor(path, target, encoding):
    """(floor, problems): the floor at `path` for `target` under `encoding`; None with the
    problems when it is missing or malformed."""
    floor, why = read_json(path)
    if why:
        return None, [f"the floor is {why}"]
    if not isinstance(floor, dict):
        return None, ["the floor is not an object"]
    problems = []
    # A floor copy written before floor_version 2 has no declared_gaps: it declares none.
    if "declared_gaps" not in floor and is_count(floor.get("floor_version")) and floor["floor_version"] < 2:
        floor = {**floor, "declared_gaps": {k: [] for k in GAP_KEYS}}
    unknown, absent = set(floor) - FLOOR_KEYS, FLOOR_KEYS - set(floor)
    if unknown:
        problems.append(f"the floor has unknown keys {sorted(unknown)}")
    if absent:
        problems.append(f"the floor lacks {sorted(absent)}")
    if floor.get("schema") != SCHEMA:
        problems.append(f"the floor's schema is not {SCHEMA}")
    if not is_count(floor.get("floor_version"), 1):
        problems.append("the floor's floor_version is not a whole number from 1")
    if floor.get("target") != target:
        problems.append(f"the floor is not {target}'s")
    if floor.get("encoding") != encoding:
        problems.append(f"the floor's encoding is not {encoding}")
    if floor.get("profile") not in PROFILES:
        problems.append(f"the floor's profile is not one of {list(PROFILES)}")
    for key in ("inventory_sha256", "overlay_sha256"):
        if not (isinstance(floor.get(key), str) and HEX64.fullmatch(floor[key])):
            problems.append(f"the floor's {key} is not 64 hex digits")
    names = lambda x: isinstance(x, list) and all(isinstance(k, str) and k for k in x) and len(set(x)) == len(x)
    require = floor.get("require")
    if not (isinstance(require, dict) and set(require) == set(REQUIRE_KEYS)
            and all(names(require[k]) for k in REQUIRE_KEYS)):
        problems.append(f"the floor's require is not {list(REQUIRE_KEYS)}, each a list of distinct names")
        require = {}
    elif not require["ops"]:
        problems.append("the floor requires no op")
    bounds = floor.get("bounds")
    if not (isinstance(bounds, dict) and set(bounds) == set(COUNT_BOUNDS + SHARE_BOUNDS)
            and all(bounds[k] is None or is_count(bounds[k]) for k in COUNT_BOUNDS)
            and all(bounds[k] is None or is_share(bounds[k]) for k in SHARE_BOUNDS)):
        problems.append(f"the floor's bounds are not {sorted(COUNT_BOUNDS + SHARE_BOUNDS)}, each null, "
                        "a count or a share")
    report = floor.get("report_only")
    if not names(report):
        problems.append("the floor's report_only is not a list of distinct names")
    elif any(k in report for v in require.values() for k in v):
        problems.append("the floor requires a key it reports only")
    gaps = floor.get("declared_gaps")
    if not (isinstance(gaps, dict) and set(gaps) == set(GAP_KEYS) and all(names(gaps[k]) for k in GAP_KEYS)):
        problems.append(f"the floor's declared_gaps is not {list(GAP_KEYS)}, each a list of distinct names")
    elif any(k in require.get(m, []) for m in GAP_KEYS for k in gaps[m]):
        problems.append("the floor requires one of its declared gaps")
    return (None if problems else floor), problems


def load_census(path):
    """(census, problems): the phase census at `path`; None with the problems when it is
    missing, its write failed, it is torn, or it is not the complete exit fold's."""
    if os.path.lexists(os.path.join(os.path.dirname(path), FAILED_MARKER)):
        return None, ["the census write failed"]
    census, why = read_json(path)
    if why:
        return None, [f"the census is {why}"]
    if not isinstance(census, dict):
        return None, ["the census is not an object"]
    if census.get("complete") is not True:
        return None, ["the census is not complete (no exit fold)"]
    return census, []


def inited_units(path):
    """The units the INITED line of a replay's log counts: None without exactly one."""
    try:
        with open(path, "rb") as f:
            found = INITED.findall(f.read())
    except OSError:
        return None
    return int(found[0]) if len(found) == 1 else None


def provenance(census, *, target, phase, run, pin, encoding, inited_units, profile=None):
    """Problems binding `census` to the run: its target, phase, run id, pin and encoding, its
    schedule (the floor's profile, when given), a complete exit fold, and one execution per unit
    the replay's INITED line counts."""
    problems = [f"the census's {key} is not {want!r}" for key, want in (
        ("target", target), ("phase", phase), ("run", run), ("pin", pin), ("encoding", encoding),
        *((("schedule", profile),) if profile is not None else ())) if census.get(key) != want]
    if census.get("complete") is not True:
        problems.append("the census is not complete (no exit fold)")
    executions = census.get("executions")
    if not is_count(inited_units):
        problems.append("the replay's log has no single INITED line")
    elif not is_count(executions) or executions != inited_units:
        problems.append(f"the census counts {executions!r} executions, the replay's INITED {inited_units}")
    return problems


def evaluate(census, floor):
    """{"met", "missing", "bounds", "report_only", "reached_while_declared"} of a well-formed census
    against its floor."""
    def count(m, key):
        c = (census.get(m) or {}).get(key) if isinstance(census.get(m), dict) else None
        return c if is_count(c) else 0

    missing = [f"{m}:{k}" for m in REQUIRE_KEYS for k in floor["require"][m] if count(m, k) < 1]
    ops = census.get("ops") if isinstance(census.get("ops"), dict) else {}
    # The ops that ran: an op refused before it ran (`<kind>:unsupported`) is not one.
    executed = sum(n for k, n in ops.items() if is_count(n) and not k.endswith(":unsupported"))
    drained = sum(n for k, n in ops.items() if is_count(n) and k.endswith(":" + QUEUE_DRAIN))
    measured = {
        "discard_rate_max": census.get("discard_rate"),
        "unexpected_max": sum(n for n in census.get("unexpected", {}).values() if is_count(n))
        if isinstance(census.get("unexpected"), dict) else None,
        "replay_mismatches_max": census.get("replay_mismatches"),
        "queue_drain_share_max": drained / executed if executed else 0.0,
        "legb_share_min": census.get("legb_share"),
    }
    failed = []
    for key, bound in sorted(floor["bounds"].items()):
        value = measured[key]
        if bound is None:
            continue
        number = isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)
        if not number or (value < bound if key.endswith("_min") else value > bound):
            failed.append(f"{key}: {value!r} against {bound}")
    report = {}
    for key in floor["report_only"]:
        report[key] = (sum(n for k, n in ops.items() if is_count(n) and k.rsplit(":", 1)[-1] == key)
                       + count("inventory", key) + count("rows", key) + count("rejects", key))
    reached = {f"{m}:{k}": count(m, k) for m in GAP_KEYS for k in floor["declared_gaps"][m] if count(m, k) > 0}
    return {"met": not missing and not failed, "missing": missing, "bounds": failed, "report_only": report,
            "reached_while_declared": reached}


def judge_run(run, *, target, pin, encoding, floor_path):
    """(result, report) of a certify run's segment-2 census against the floor at `floor_path`:
    result is "met", "missed" or "error"; report holds the floor's sha256 and version (None when
    unreadable), and the problems, missing keys, failed bounds, report-only counts and the declared
    gaps the census reached."""
    seg = os.path.join(run, "logs", SEGMENT)
    report = {"floor_sha256": None, "floor_version": None, "problems": [], "missing": [], "bounds": [],
              "report_only": {}, "reached_while_declared": {}}
    floor, problems = load_floor(floor_path, target, encoding)
    if os.path.isfile(floor_path):
        try:
            report["floor_sha256"] = sha256_file(floor_path)
        except OSError as e:
            problems.append(f"the floor cannot be hashed ({type(e).__name__})")
    if floor:
        report["floor_version"] = floor["floor_version"]
    census, census_problems = load_census(os.path.join(seg, CENSUS))
    problems += census_problems
    if census is not None:
        problems += provenance(census, target=target, phase=PHASE, run=os.path.basename(run), pin=pin,
                               encoding=encoding, inited_units=inited_units(os.path.join(seg, "fuzz.out")),
                               profile=floor["profile"] if floor else None)
    report["problems"] = problems
    if problems:
        return "error", report
    result = evaluate(census, floor)
    report.update(missing=result["missing"], bounds=result["bounds"], report_only=result["report_only"],
                  reached_while_declared=result["reached_while_declared"])
    return ("met" if result["met"] else "missed"), report


def write_private(path, data):
    """`data` (bytes) to `path`, mode 0600, replacing it."""
    tmp = f"{path}.tmp-{os.getpid()}"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(data)
    os.replace(tmp, path)


def gate(run, target, pin, encoding, floor_src):
    """The gate's exit status (0 met, 1 missed, 2 error), with its result written."""
    seg = os.path.join(run, "logs", SEGMENT)
    copy, problems = os.path.join(seg, FLOOR_COPY), []
    # An older result never stands for this gate's: fuzzctl reads the file as its record.
    try:
        os.unlink(os.path.join(seg, RESULT))
    except FileNotFoundError:
        pass
    data = None
    try:
        with open(floor_src, "rb") as f:
            data = f.read()
    except FileNotFoundError:
        problems.append("the target has no floor")
    except OSError as e:
        problems.append(f"the floor could not be read ({type(e).__name__})")
    if data is not None:
        try:
            write_private(copy, data)
            with open(copy, "rb") as f:
                if f.read() != data:
                    problems.append("the floor's copy is not the floor")
        except OSError as e:
            problems.append(f"the floor could not be copied ({type(e).__name__})")
    try:
        with open(os.path.join(run, FLOOR_SHA)) as f:
            built = f.read().strip()
    except OSError:
        built = None
    if not problems and built != sha256_file(copy):
        problems.append("the floor is not the one the run was built with")
    if problems:
        result, report = "error", {"floor_sha256": None, "floor_version": None, "problems": problems,
                                   "missing": [], "bounds": [], "report_only": {}, "reached_while_declared": {}}
    else:
        result, report = judge_run(run, target=target, pin=pin, encoding=encoding, floor_path=copy)
    try:
        write_private(os.path.join(seg, RESULT),
                      json.dumps({"result": result, **report}, indent=1, sort_keys=True).encode() + b"\n")
    except OSError:
        return 2
    return {"met": 0, "missed": 1}.get(result, 2)


def main(argv):
    if not argv or argv[0] != "gate":
        print("usage: census_floor.py gate --run R --target T --pin P --encoding E --floor-src F", file=sys.stderr)
        return 2
    args, rest = {}, argv[1:]
    while rest:
        if len(rest) < 2 or rest[0] not in ("--run", "--target", "--pin", "--encoding", "--floor-src"):
            print(f"census_floor.py: bad arguments {rest!r}", file=sys.stderr)
            return 2
        args[rest[0][2:]], rest = rest[1], rest[2:]
    if set(args) != {"run", "target", "pin", "encoding", "floor-src"}:
        print("census_floor.py: gate takes --run, --target, --pin, --encoding and --floor-src", file=sys.stderr)
        return 2
    try:
        return gate(args["run"], args["target"], args["pin"], args["encoding"], args["floor-src"])
    except Exception as e:  # noqa: BLE001 (any failure is the gate's error, never "missed")
        print(f"census_floor.py: the gate failed ({type(e).__name__})", file=sys.stderr)
        try:
            report = {"result": "error", "floor_sha256": None, "floor_version": None,
                      "problems": [f"the gate failed ({type(e).__name__})"], "missing": [], "bounds": [],
                      "report_only": {}, "reached_while_declared": {}}
            write_private(os.path.join(args["run"], "logs", SEGMENT, RESULT),
                          json.dumps(report, indent=1, sort_keys=True).encode() + b"\n")
        except Exception:  # noqa: BLE001
            pass
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
