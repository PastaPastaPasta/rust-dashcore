//! What a failing row must say. A row that expects a non-zero exit code passes when both
//! programs fail alike, so on its own it also passes when both fail early, on the wrong path,
//! with the same message. Each failing row names the text of the failure it is about; the stock
//! binary's own output must contain it (the premise), and the rows then compare rdash-cli with
//! that output. A failing row without an entry fails, so a new row has to say what it is about.
//!
//! The table is `(group, row name, text)`. The text is the first line the stock binary printed
//! (for an exception, its message), with the port of a local server written as `PORT` and
//! anything that depends on where the test runs cut off.

use super::Output;

/// Why `stock`'s output does not fit the row, if it does not.
pub fn check(group: &str, name: &str, expect_code: i32, stock: &Output) -> Option<String> {
    if expect_code == 0 {
        return None;
    }
    let Some(&(_, _, text)) = TABLE.iter().find(|(g, n, _)| *g == group && *n == name) else {
        return Some(
            "no failure text is recorded for this row (support/says.rs), so a failure on the \
             wrong path would pass"
                .to_string(),
        );
    };
    let seen = |bytes: &[u8]| with_port_masked(&String::from_utf8_lossy(bytes)).contains(text);
    if seen(&stock.stderr) || seen(&stock.stdout) {
        None
    } else {
        Some(format!("stock does not say {text:?}, so the row is not about the failure it names"))
    }
}

/// `127.0.0.1:<digits>` and `localhost:<digits>` with `PORT` for the digits.
fn with_port_masked(text: &str) -> String {
    let mut out = text.to_string();
    for host in ["127.0.0.1:", "localhost:"] {
        let (mut done, mut rest) = (String::with_capacity(out.len()), out.as_str());
        while let Some(at) = rest.find(host) {
            let (head, tail) = rest.split_at(at + host.len());
            done.push_str(head);
            let digits = tail.bytes().take_while(u8::is_ascii_digit).count();
            if digits > 0 {
                done.push_str("PORT");
            }
            rest = &tail[digits..];
        }
        done.push_str(rest);
        out = done;
    }
    out
}

/// How many requests a failing row's server sees.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Requests {
    /// The failure is the server's reply, so there is at least one request.
    AtLeastOne,
    /// The failure comes before any request (arguments, configuration, standard input).
    NoneSent,
    /// Depends on the machine (which address `localhost` resolves to first).
    Any,
}

/// What the row about `name` expects of its server. Rows that fail before connecting say so
/// here; everything else has to reach the server.
pub fn requests(group: &str, name: &str) -> Requests {
    if ANY_REQUESTS.contains(&(group, name)) {
        Requests::Any
    } else if NO_REQUEST.contains(&(group, name)) {
        Requests::NoneSent
    } else {
        Requests::AtLeastOne
    }
}

