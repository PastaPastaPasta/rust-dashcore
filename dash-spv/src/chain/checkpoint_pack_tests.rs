/// `DASHD`'s rows for `network`: height, hash, chain work.
fn dashd(network: Network) -> Vec<(u32, dash_primitives::BlockHash, Work)> {
    DASHD
        .lines()
        .filter_map(|line| {
            let [net, height, hash, work] = line.split(' ').collect::<Vec<_>>()[..] else {
                panic!("bad row {line:?}");
            };
            (net == network.to_string()).then(|| {
                let hash: BlockHash = hash.parse().unwrap();
                (height.parse().unwrap(), block_hash_to_base(&hash), work.parse().unwrap())
            })
        })
        .collect()
}

struct NoFail;

impl FailStop for NoFail {
    fn read_failed(&self, _what: &str) {}

    fn is_tripped(&self) -> bool {
        false
    }
}

/// Builds an anchored chain from `pack`, as SPV's candidate start does.
fn accepted(pack: &AnchorPack, network: Network) -> Result<(), dash_chain::ChainError> {
    let params = chain_setup(&ClientConfig::new(network)).unwrap();
    let svc = Services {
        clock: Arc::new(MockClock::at(2_000_000)),
        sporks: Arc::new(StaticSporks::for_network(&params, Some(false))),
        fail: Arc::new(NoFail),
    };
    let cfg = ChainConfig::spv(&params, 10_000);
    HeaderChain::<NoStore, Evicting>::new_anchored(params, cfg, svc, NoStore, pack).map(drop)
}

#[test_case(Network::Mainnet)]
#[test_case(Network::Testnet)]
fn anchor_packs_match_dashd_and_link(network: Network) {
    let expected = dashd(network);
    let checkpoints: Vec<_> = CheckpointManager::for_network(network).checkpoints().collect();
    let heights: Vec<u32> = checkpoints.iter().map(|c| c.height()).collect();
    assert_eq!(heights, expected.iter().map(|row| row.0).collect::<Vec<_>>());

    for (checkpoint, &(height, hash, chain_work)) in checkpoints.iter().zip(&expected) {
        let at = format!("{network} checkpoint {height}");
        assert_eq!(checkpoint.network, Some(network), "{at}: decoded for another network");
        let pack = checkpoint.anchor_pack().unwrap_or_else(|| panic!("{at}: no pack"));

        assert_eq!(pack.height, height, "{at}");
        assert_eq!(pack.hash, hash, "{at}: hash");
        assert_eq!(pack.chain_work, chain_work, "{at}: chain work");
        let hashes = pack.headers.map(|h| Header::new(h).hash());
        for k in 1..CHECKPOINT_HEADERS {
            assert_eq!(
                pack.headers[k].prev_hash(),
                hashes[k - 1],
                "{at}: header {k} does not link"
            );
        }
        assert_eq!(hashes[CHECKPOINT_HEADERS - 1], hash, "{at}: the last header is not the block");
        accepted(&pack, network).unwrap_or_else(|e| panic!("{at}: dash-chain refuses it: {e}"));
    }
}

#[test_case(Network::Mainnet)]
#[test_case(Network::Testnet)]
fn chain_work_grows_with_height(network: Network) {
    let works: Vec<Work> = CheckpointManager::for_network(network)
        .checkpoints()
        .map(|c| c.chain_work().expect("embedded chain work"))
        .collect();

    for pair in works.windows(2) {
        assert!(pair[0] < pair[1], "{network}: chain work {} is not above {}", pair[1], pair[0]);
    }
}
