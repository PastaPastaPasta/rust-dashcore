/// `CheckDiskSpace` failing before an allocation gives "Disk space is too low!" in `AcceptBlock`,
/// which the message table accepts. The harness never limits the disk, so this runs on a world of
/// its own.
#[test]
fn a_full_disk_gives_cores_disk_space_message() {
    use dashd_store::faulty::{FatalCause, World, WorldConfig};
    let world = World::new(WorldConfig {
        capacity: Some(0),
        ..WorldConfig::default()
    });
    let cfg = ChainConfig::default();
    let a = ChainSut::open(&world, &cfg).err().expect("genesis's write needs space");
    assert_eq!(a.message, "Disk space is too low!");
    let t = world.trace();
    assert_eq!(stopped_in(&t), [dashd_chainstate::crash::PATH_ACCEPT]);
    // A failure only V reports (`CheckDiskSpace` is no store event): no store, V's paths.
    let cause = FatalCause {
        read: false,
        store: None,
        paths: stopped_in(&t),
    };
    assert!(ChainSut::sanctioned_after(&cfg, &a.message, &cause));
    assert!(!ChainSut::sanctioned_after(&cfg, "Failed to read block", &cause));
}

