/// `sc` killed after its forward run's last event and reopened, without R12: the violations and
/// the recovered world's trace.
fn killed_after_the_run(sc: &Sc) -> (Vec<Violation>, Trace) {
    replay_trace::<ChainSut>(&killed(sc)).expect("the image replays")
}

/// `sc` killed after its forward run's last event.
fn killed(sc: &Sc) -> Repro {
    let mut r = Repro::new(sc, None);
    r.crash_at = forward(sc).events().last().map(|(id, ..)| id.index);
    r.kind = CrashKind::ProcessKill;
    r
}

/// DEC-196: the coins at block 5, the index-only write after `x3` marks it
/// failed, and a crash after that write. Block 5 strictly outworks every valid block, so V
/// refuses to start with a model message: R6 (e) requires the refusal, and R0 sanctions it. So
/// does `x4` (its parent) and `x5` (the tip itself), as DEC-196 is written.
#[test]
fn a_loaded_failed_tip_that_outworks_every_valid_block_refuses_to_start() {
    for workload in ["c5;f;x3;i", "c5;f;x4;i", "c5;f;x5;i"] {
        // From the flush's B1 on, so the image after the index-only write's append is in it.
        let mut sc: Sc = Scenario::new("x-refused", ChainConfig::default(), ops(workload));
        sc.window = CrashWindow {
            from: after(MarkKind::Durable, 0),
            to: None,
        };
        clean(&sc);
        let (v, t) = killed_after_the_run(&sc);
        assert!(v.is_empty(), "{workload}: {v:?}");
        assert_eq!(logs(&t, INVALID_TIP).len(), 1, "{workload}: V refuses to start");
    }
    // The advice works on a default node, whose `-txindex` refuses `-reindex-chainstate`, and
    // after `invalidateblock`, whose marks `-reindex` does not keep.
    assert_eq!(
        INVALID_TIP,
        "The chainstate tip is invalid and no valid block has at least its work; restart with \
         -reindex, then repeat any invalidateblock calls (or use -reindex-chainstate, which \
         keeps them, if -txindex is off)."
    );
}

