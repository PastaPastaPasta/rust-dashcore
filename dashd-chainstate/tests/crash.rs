/// The `verdict` lines of `epoch` in `t`.
fn verdicts(t: &Trace, epoch: u32) -> Vec<String> {
    t.marks_with_epoch()
        .filter_map(|(e, m)| match m {
            Mark::Log {
                line,
            } if e == epoch && line.starts_with("verdict ") => Some(line.clone()),
            _ => None,
        })
        .collect()
}

