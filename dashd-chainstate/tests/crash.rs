/// C11's connect half (CH3 §4.6 steps 1–5) through two restarts, with the harness's checks
/// after each: B, accepted (`HAVE_DATA`, `VALID_TRANSACTIONS`) and durable through an
/// index-only write before ABC connects it, is connected after the first restart by the real
/// `ConnectBlock`, which reports `mandatory-script-verify-flag-failed (…)`; V marks it
/// `FAILED_VALID` and stays on its parent. After a flush and a second restart `FAILED_VALID` is
/// durable, the tip is still B's parent, and nothing connects B again.
#[test]
fn c11_core_connect_half_two_restarts() {
    use dash_chain::Status;
    use dashd_store::faulty::{AllSurvive, World, WorldConfig};
    let Scenario {
        cfg,
        ops: workload,
        ..
    } = c11_core();
    let world = World::new(WorldConfig::default());
    let open = || ChainSut::open(&world, &cfg).expect("V opens");
    let checks = |sut: &ChainSut| {
        // The run's blocks are generated by now.
        let refm = ChainRef::checks_view(&cfg);
        let v = world.checking(|| sut.check(&world, &refm, &world.trace()));
        assert_eq!(v, Ok(()), "epoch {}", world.epoch());
    };
    let restart = |sut: ChainSut| {
        drop(sut);
        world.crash_in_place(CrashKind::ProcessKill, Box::new(AllSurvive));
    };
    // 1, 2: B accepted, then the index-only write; V never connects it.
    let mut sut = open();
    for op in &workload {
        sut.apply(op).expect("the op runs");
    }
    assert!(verdicts(&world.trace(), 0).is_empty());
    // 3, 4: the restart's activation connects B's parent, then B through the real connect.
    restart(sut);
    let mut sut = open();
    checks(&sut);
    let [(b, parent, status)] = sut.durable_at(CORE_B)[..] else {
        panic!("one durable entry at {CORE_B}: {:?}", sut.durable_at(CORE_B));
    };
    assert_eq!(status & Status::VALID_MASK, Status::VALID_TRANSACTIONS, "B: {status:#x}");
    assert_eq!(status & Status::FAILED_MASK, 0, "B durable before its connect: {status:#x}");
    let v = verdicts(&world.trace(), 1);
    assert_eq!(v.len(), 1, "{v:?}");
    assert!(
        v[0].starts_with(&format!("verdict {CORE_B} mandatory-script-verify-flag-failed (")),
        "{v:?}"
    );
    assert_eq!(sut.tip(), Some((CORE_B - 1, parent)));
    // 5: the failure flushed, then a restart: durable, and B is never connected again.
    sut.apply(&ChainOp::Flush).expect("the flush runs");
    restart(sut);
    let sut = open();
    checks(&sut);
    let [(b2, _, status)] = sut.durable_at(CORE_B)[..] else {
        panic!("one durable entry at {CORE_B}");
    };
    assert_eq!(b2, b);
    assert_ne!(status & Status::FAILED_VALID, 0, "B durable as failed: {status:#x}");
    assert_eq!(sut.tip(), Some((CORE_B - 1, parent)));
    assert!(verdicts(&world.trace(), 2).is_empty());
}

