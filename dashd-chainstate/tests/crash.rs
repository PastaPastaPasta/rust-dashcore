/// DEC-202: no durable tip is a logically empty store. Killed before a flush made the first tip
/// durable, after a block with an effect, V keeps the effect records, starts from genesis and
/// reaches the tip R6 (e) requires, as the uncrashed run would (round 5's four repros, and one
/// after a wipe); every image of each scenario is clean.
#[test]
fn killed_before_the_first_durable_tip_starts_from_genesis() {
    // Epoch 1's applied connects, R12's continuation aside: genesis alone, as no index entry
    // was durable at event 23 (block 5's effect), or genesis and the 10 blocks the wipe keeps.
    for (cfg, workload, window, at, connects) in [
        ("effects=5", "c10", None, 23, 1),
        ("effects=5", "c10;f", None, 23, 1),
        ("presumed=5:8", "c10;f", None, 23, 1),
        ("effects=5", "c10;f;W;c1;f", None, 23, 1),
        ("effects=5", "c10;f;W;c1;f", Some(1), 57, 11),
    ] {
        let mut sc: Sc = Scenario::new("no-tip", cfg.parse().expect("a config"), ops(workload));
        if let Some(n) = window {
            sc = at_flush(sc, n);
        }
        let mut r = Repro::new(&sc, None);
        (r.crash_at, r.kind) = (Some(at), CrashKind::ProcessKill);
        // `replay` runs R12's continuation, which judges the activated state once flushed.
        let v = replay::<ChainSut>(&r).expect("the image replays");
        assert!(v.is_empty(), "{cfg} {workload} at {at}: {v:?}");
        let (_, t) = replay_trace::<ChainSut>(&r).expect("the image replays");
        let now = t
            .marks_with_epoch()
            .filter(|(e, m)| {
                *e == 1
                    && matches!(
                        m,
                        Mark::Connected {
                            applied: true,
                            ..
                        }
                    )
            })
            .count();
        assert_eq!(now, connects, "{cfg} {workload} at {at}");
        if window.is_none() {
            clean(&sc);
        }
    }
}

/// DEC-202: a kept effect record from a branch the restart does not take is never what a reader
/// sees. After `W` (no durable tip) the run reorgs onto branch B (heights 4–11), whose base block
/// 5 writes the presumed record and whose block 11, the kill's, an effect; neither B's index
/// entries nor a tip are durable. The restart re-activates branch A (genesis to 10) from the
/// durable index: A's block 5 rewrites the record before A's reader at 8 folds it (R12's R3
/// compares the evo state with the reference's fold of A's own base), and V never reads the
/// independent effects, so B's `i:11` stays unread.
#[test]
fn a_kept_effect_off_the_restarted_branch_is_never_read() {
    let cfg: ChainConfig = "presumed=5:8 effects=11".parse().expect("a config");
    let sc: Sc = Scenario::new("no-tip-branch", cfg, ops("c10;f;W;r3:9"));
    // R12's continuation flushes the activated tip, so the reopen's R3 judges its evo state.
    let v = replay::<ChainSut>(&killed(&sc)).expect("the image replays");
    assert!(v.is_empty(), "{v:?}");
    let (_, t) = killed_after_the_run(&sc);
    let connected = |epoch| -> Vec<Hash> {
        t.marks_with_epoch()
            .filter_map(|(e, m)| match m {
                Mark::Connected {
                    block,
                    applied: true,
                    ..
                } if e == epoch => Some(*block),
                _ => None,
            })
            .collect()
    };
    let (before, after) = (connected(0), connected(1));
    // Epoch 1 connects A's 11 blocks, genesis included; B's 8 are the killed run's alone.
    let b = before.iter().filter(|h| !after.contains(h)).count();
    assert_eq!((after.len(), b), (11, 8), "{after:?}");
    assert_eq!(logs(&t, "effect written i:11").len(), 1, "B alone wrote i:11");
}

