// C3-real (CH3 §4.6, CH3b b4a): a reorg across a flush with the real connector, k ∈ {1, 2, 6}.

/// C3-real's shape on its forward run, then its clean exploration, for each of `ks`. F (the
/// forward run's flush from which the window starts) is frozen at A's tip with `old` at the fork,
/// or for the connect leg at the fork with `old` at A's tip; F and the closing flush each write a
/// partial sub-batch, so a marker is durable inside each. B's first block spends the two coins A's
/// first spent, both back after A's disconnect, and B's second spends an output of B's first. In
/// the activation variant, V killed between the index-only write and the closing flush
/// disconnects A's `k` blocks in activation.
fn c3_real_clean(leg: Leg, ks: &[u32]) {
    use dash_consensus::primitives::BlockHash;
    for &k in ks {
        let sc = c3_real(k, leg);
        let t = forward(&sc);
        let mut refm = ChainRef::new(&sc.cfg);
        for op in &sc.ops {
            refm.apply(op);
        }
        let height = |h: &Hash| refm.height(&BlockHash::from(*h));
        // Each flush's (old, new) heights and its partial sub-batches.
        let mut flushes = Vec::new();
        for m in t.marks() {
            match m {
                Mark::FlushBegin {
                    old,
                    new,
                    ..
                } => flushes.push(((old.as_ref().and_then(height), height(new)), 0)),
                Mark::Log {
                    line,
                } if line.contains("Writing partial batch") => {
                    flushes.last_mut().expect("inside a flush").1 += 1;
                }
                _ => {}
            }
        }
        let (fork, a_tip) = (Some(C3_FORK), Some(C3_FORK + k));
        let (f, at) = match leg {
            Leg::Disconnect | Leg::Both | Leg::Activation => (1, (fork, a_tip)),
            Leg::Connect => (2, (a_tip, fork)),
        };
        assert_eq!(flushes[f].0, at, "{}: F's (old, new) heights in {flushes:?}", sc.name);
        let split = flushes[f].1 > 0 && flushes.last().is_some_and(|(_, p)| *p > 0);
        assert!(split, "{}: F and the closing flush split: {flushes:?}", sc.name);
        let b = refm.active();
        assert_eq!(b.len() as u32, C3_FORK + k + 2, "{}: B is the active chain", sc.name);
        let (b1, b2) = (
            refm.block(&b[C3_FORK as usize + 1]).unwrap(),
            refm.block(&b[C3_FORK as usize + 2]).unwrap(),
        );
        let a1 =
            refm.blocks.map.values().find(|g| g.height == C3_FORK + 1 && g.branch == 0).unwrap();
        let keys = |coins: &[(_, Vec<u8>)]| coins.iter().map(|(k, _)| *k).collect::<Vec<_>>();
        assert_ne!(a1.hash, b1.hash, "{}: B is a new branch", sc.name);
        assert_eq!(
            keys(&b1.spends),
            keys(&a1.spends),
            "{}: B spends what A's disconnect restored",
            sc.name
        );
        let b1_adds = keys(&b1.adds);
        assert!(
            keys(&b2.spends).iter().any(|s| b1_adds.contains(s)),
            "{}: B spends its own",
            sc.name
        );
        if let Leg::Activation = leg {
            let closing = t.entries.iter().rev().find_map(|e| match e {
                TraceEntry::Mark {
                    after_events,
                    mark: Mark::FlushBegin {
                        ..
                    },
                    ..
                } => Some(*after_events),
                _ => None,
            });
            let mut r = Repro::new(&sc, None);
            r.crash_at = closing.map(|n| n - 1);
            r.kind = CrashKind::ProcessKill;
            let (v, rt) = replay_trace::<ChainSut>(&r).expect("the image replays");
            assert!(v.is_empty(), "{}: killed before the closing flush: {v:?}", sc.name);
            let disconnects = rt.marks_with_epoch().filter(|(epoch, m)| {
                *epoch == 1
                    && matches!(m, Mark::PathBegin {
                        path
                    } if *path == PATH_DISCONNECT)
            });
            assert_eq!(disconnects.count(), k as usize, "{}: activation disconnects A", sc.name);
        }
        clean(&sc);
    }
}

