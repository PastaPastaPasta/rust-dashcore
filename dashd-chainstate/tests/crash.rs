/// The Core path a fatal error stopped in: the open paths at the trace's `Abort` mark.
fn stopped_in(t: &Trace) -> Vec<&'static str> {
    let mut paths = Vec::new();
    for m in t.marks() {
        match m {
            Mark::PathBegin {
                path,
            } => paths.push(*path),
            Mark::PathEnd => {
                paths.pop();
            }
            Mark::Abort {
                ..
            } => return paths,
            _ => {}
        }
    }
    panic!("no abort")
}

/// A block-file failure on a write path gives Core's message for its step, which the message
/// table accepts there: a rollover's flush of the old block or undo file ("Flushing…", in
/// `AcceptBlock`, or in `ConnectTip` where a lagging rev file is finalized), and a failed
/// link-count read the write's own text (D-c6-6).
#[test]
fn block_file_failures_give_cores_message() {
    use dashd_chainstate::crash::{PATH_ACCEPT as ACCEPT, PATH_CONNECT as CONNECT};
    for (workload, op, n, message, path) in [
        ("c200", OpKind::Truncate, 0, "Flushing block file", ACCEPT),
        ("c200", OpKind::SyncData, 0, "Flushing block file", ACCEPT),
        ("c200", OpKind::Truncate, 1, "Flushing undo file", ACCEPT),
        ("c200", OpKind::SyncData, 1, "Flushing undo file", ACCEPT),
        ("a200;c200", OpKind::Truncate, 1, "Flushing undo file", CONNECT),
        ("a200;c200", OpKind::SyncData, 1, "Flushing undo file", CONNECT),
        ("c5", OpKind::LinkCount, 0, "Failed to write block", ACCEPT),
        ("c5", OpKind::LinkCount, 3, "Failed to write undo data", CONNECT),
    ] {
        let sc: Sc = Scenario::new("block-files", ChainConfig::default(), ops(workload));
        let fault = io(StoreSel::Fs, op, n, FaultOutcome::NotApplied);
        let (t, stopped) = faulted(&sc, fault.clone());
        let case = format!("{workload} {op:?} {n}");
        assert!(stopped.as_deref().is_some_and(|m| m.starts_with(message)), "{case}: {stopped:?}");
        assert_eq!(stopped_in(&t).last(), Some(&path), "{case}");
        let v = replay::<ChainSut>(&Repro::new(&sc, Some(fault))).expect("a repro");
        assert!(v.is_empty(), "{case}: {v:?}");
    }
}

