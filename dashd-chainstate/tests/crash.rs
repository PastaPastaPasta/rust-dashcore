/// A decimal or `0x` hex `u64` from the environment.
fn parse_u64(v: &str, name: &str) -> u64 {
    let n = match v.strip_prefix("0x") {
        Some(hex) => u64::from_str_radix(hex, 16),
        None => v.parse(),
    };
    n.unwrap_or_else(|e| panic!("{name}={v}: {e}"))
}
