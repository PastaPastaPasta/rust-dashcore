#[test]
fn cfg_predicates() {
    let rocksdb = features(&["default", "rocksdb"]);
    let cfg = |target| Cfg {
        target,
        features: &rocksdb,
        test: false,
    };
    let (linux, windows) = (cfg(&GATE), cfg(&WINDOWS));
    for (pred, on_linux, on_windows) in [
        ("unix", true, false),
        ("not(windows)", true, false),
        ("any(windows, test)", false, true),
        ("all(test, not(loom))", false, false),
        ("not(fuzzing)", true, true),
        ("feature = \"rocksdb\"", true, true),
        ("any(test, feature = \"model\")", false, false),
        ("all(feature = \"test-hooks\", not(debug_assertions), not(clippy))", false, false),
        ("not(any(target_os = \"linux\", target_os = \"android\"))", false, true),
        ("all(target_arch = \"x86_64\", target_pointer_width = \"64\")", true, true),
        ("all(target_arch = \"aarch64\", target_endian = \"little\")", false, false),
        ("all(target_arch = \"x86\", not(target_feature = \"sse2\"))", false, false),
        ("target_family = \"windows\"", false, true),
        ("all(target_os = \"linux\", target_env = \"gnu\")", true, false),
        ("target_env = \"msvc\"", false, true),
        ("not(target_has_atomic = \"32\")", false, false),
        ("all()", true, true),
        ("any()", false, false),
    ] {
        assert_eq!(linux.holds(pred), Ok(on_linux), "{pred}");
        assert_eq!(windows.holds(pred), Ok(on_windows), "{pred}");
    }
    // Unknown names and values, and malformed predicates, are errors.
    for pred in [
        "foo",
        "feature",
        "target_os",
        "unix = \"x\"",
        "target_feature = \"avx512f\"",
        "target_has_atomic = \"128\"",
        "target_os = linux",
        "all(unix",
        "all(unix windows)",
        "not(unix, windows)",
        "not()",
        "all(,)",
        "unix)",
    ] {
        assert!(linux.holds(pred).is_err(), "{pred}: {:?}", linux.holds(pred));
    }
    // The host table is this build's own.
    let host = cfg(&HOST);
    assert_eq!(host.holds("unix"), Ok(cfg!(unix)));
    assert_eq!(host.holds("windows"), Ok(cfg!(windows)));
    assert_eq!(host.holds("target_os = \"linux\""), Ok(cfg!(target_os = "linux")));
    assert_eq!(host.holds("target_os = \"macos\""), Ok(cfg!(target_os = "macos")));
    assert_eq!(host.holds("target_arch = \"x86_64\""), Ok(cfg!(target_arch = "x86_64")));
    assert_eq!(host.holds("target_feature = \"sse2\""), Ok(cfg!(target_feature = "sse2")));
    assert_eq!(host.holds("target_has_atomic = \"32\""), Ok(cfg!(target_has_atomic = "32")));
}

#[test]
fn cfg_items() {
    let src = r##"fn a() {}
#[cfg(test)]
mod tests;
fn b() {}
#[cfg(test)]
#[allow(x)]
mod t {
    fn c() {
        "x"
    }
}
#[cfg(not(test))]
fn d() {}
    #[cfg(feature = "test-hooks")]
    let e = [
        1,
    ];
fn f() {}
#[cfg(feature = "testnet")]
fn g() {}
#[cfg(all(test, not(loom)))]
pub(crate) mod h;
struct S {
    #[cfg(test)]
    probe: Vec<u8>,
    kept: u8,
}
#[cfg(any(test, feature = "rocksdb"))]
fn i() {}
#[cfg(any(test, feature = "model"))]
fn j() {}
#[cfg(test)] fn k() {
    "{";
}
fn l() {}
#[cfg(all(
    test,
    feature = "x"
))]
fn m() {}
#[cfg(any(
    unix,
))]
fn n() {}
#[cfg(windows)]
/// Doc.
fn w() {
    let s = "on windows \
             only }";
    r#"raw " }"#;
}
#[cfg(windows)]
fn q() {
    let c = ['\'', '{'];
}
#[cfg(unix)]
fn u() {}
match x {
    #[cfg(windows)]
    A => "arm",
    #[cfg(not(windows))]
    B => { 2 }
}
fn exit() {
    #[cfg(unix)]
    unsafe {
        _exit()
    }
    #[cfg(not(unix))]
    exit("tail")
}
"##;
    let rocksdb = features(&["default", "rocksdb"]);
    let on = |target| {
        production(
            src,
            &Cfg {
                target,
                features: &rocksdb,
                test: false,
            },
        )
        .unwrap()
    };
    assert_eq!(
        on(&GATE),
        r#"fn a() {}
fn b() {}
#[cfg(not(test))]
fn d() {}
fn f() {}
struct S {
    kept: u8,
}
#[cfg(any(test, feature = "rocksdb"))]
fn i() {}
fn l() {}
#[cfg(any(
    unix,
))]
fn n() {}
#[cfg(unix)]
fn u() {}
match x {
    #[cfg(not(windows))]
    B => { 2 }
}
fn exit() {
    #[cfg(unix)]
    unsafe {
        _exit()
    }
}
"#
    );
    // The same source built for Windows: its emitters count, the unix ones do not.
    let windows = on(&WINDOWS);
    let mut literals = Vec::new();
    string_literals(&windows, &mut literals);
    assert_eq!(literals, ["rocksdb", "on windows only }", "raw \" }", "arm", "tail"]);
    assert!(
        !windows.contains("fn n()") && !windows.contains("fn u()") && !windows.contains("B =>")
    );
    assert!(windows.contains("fn q()"));

    // A file whose inner `#![cfg]` fails is empty. A test build (a proof's target) sets `test`
    // and `debug_assertions`, nothing else of `OFF`.
    let linux = Cfg {
        target: &GATE,
        features: &rocksdb,
        test: false,
    };
    let test_build = Cfg {
        test: true,
        ..linux
    };
    let file = "//! A test file.\n#![cfg(test)]\nfn a() {}\n";
    assert_eq!(production(file, &linux).unwrap(), "");
    assert_eq!(production(file, &test_build).unwrap(), file);
    let unix = "#![cfg(all(unix, not(windows)))]\nfn a() {}\n";
    assert_eq!(production(unix, &linux).unwrap(), unix);
    assert_eq!(
        production(
            unix,
            &Cfg {
                target: &WINDOWS,
                ..linux
            }
        )
        .unwrap(),
        ""
    );
    let debug = "#[cfg(debug_assertions)]\nfn a() {}\n#[cfg(miri)]\nfn b() {}\n";
    assert_eq!(production(debug, &test_build).unwrap(), "#[cfg(debug_assertions)]\nfn a() {}\n");
    assert_eq!(production(debug, &linux).unwrap(), "");
    let probes = "#[cfg(doctest)]\nstruct D;\n\
                  #[cfg(any(cap_probe = \"x\", cap_probe = \"y\"))]\nfn a() {}\n";
    assert_eq!(production(probes, &test_build).unwrap(), "");
    assert_eq!(production(probes, &linux).unwrap(), "");
    // A cut item takes the attributes above it: `#[test]` does not land on the next function.
    let above =
        "fn a() {}\n/// W.\n#[test]\n#[cfg(unix)]\n#[cfg(windows)]\nfn w() {}\nfn helper() {}\n";
    assert_eq!(production(above, &linux).unwrap(), "fn a() {}\nfn helper() {}\n");

    // What the scan cannot follow, or cannot cut, is an error.
    for (src, error) in [
        ("#[path = \"x.rs\"]\nmod x;\n", "line 1: #[path = \"x.rs\"] is not followed"),
        ("#[cfg(foo)]\nfn a() {}\n", "line 1: unknown cfg \"foo\""),
        (
            "fn a() {}\nmod m {\n    #![cfg(windows)]\n}\n",
            "line 3: #![cfg(windows)] is not followed",
        ),
        (
            "fn a() {\n    #[cfg(windows)]\n    x }\n",
            "line 2: the item ran past its block at line 3",
        ),
        ("#[cfg(windows)]\nfn a() {\n", "line 1: the item does not end"),
        ("#[cfg(windows)]\n", "line 1: no item after the attribute"),
    ] {
        assert_eq!(production(src, &linux), Err(error.to_owned()), "{src}");
    }
}

#[test]
fn module_tree() {
    let dir = tempfile::tempdir().unwrap();
    let krate = dir.path();
    let write = |path: &str, text: &str| {
        let path = krate.join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    };
    write("Cargo.toml", "[package]\nname = \"x\"\n[lib]\npath = \"src/lib.rs\"\n");
    write(
        "src/lib.rs",
        "mod a; // the a module\n#[cfg(windows)]\nmod w;\npub(in crate) mod b;\n#[cfg(test)]\n\
         #[path = \"elsewhere.rs\"]\nmod checks;\nuse crate::a::my_mod;\n",
    );
    write("src/a.rs", "mod inner;\nconst A: &str = \"a\";\n");
    write("src/a/inner.rs", "\"inner\";\n");
    write("src/b/mod.rs", "\"b\";\n");
    write("src/main.rs", "mod cli;\n");
    write("src/cli.rs", "\"cli\";\n");
    write("src/bin/tool.rs", "\"tool\";\n");
    for stray in ["src/w.rs", "src/checks.rs", "src/orphan.rs", "src/inner.rs", "src/bin/x.txt"] {
        write(stray, "\"stray\";\n");
    }
    let features = features(&[]);
    let cfg = Cfg {
        target: &GATE,
        features: &features,
        test: false,
    };
    let files = |bins| {
        let mut files: Vec<String> = crate_files(krate, &cfg, bins)
            .unwrap()
            .into_iter()
            .map(|(p, _)| p.strip_prefix(krate).unwrap().display().to_string())
            .collect();
        files.sort();
        files
    };
    // A dependency: its library only.
    assert_eq!(files(false), ["src/a.rs", "src/a/inner.rs", "src/b/mod.rs", "src/lib.rs"]);
    assert_eq!(
        files(true),
        [
            "src/a.rs",
            "src/a/inner.rs",
            "src/b/mod.rs",
            "src/bin/tool.rs",
            "src/cli.rs",
            "src/lib.rs",
            "src/main.rs"
        ]
    );

    // What the walk cannot place is an error.
    let error = |lib: &str| {
        write("src/lib.rs", lib);
        crate_files(krate, &cfg, false).unwrap_err()
    };
    assert!(error("mod missing;\n").ends_with("`mod missing;` has 0 files"));
    write("src/b.rs", "");
    assert!(error("mod b;\n").ends_with("`mod b;` has 2 files"));
    assert!(
        error("mod t {\n    mod y;\n}\n").ends_with("line 2: `mod y;` inside an inline module")
    );
    assert!(
        error("#[cfg(unix)] mod z;\n")
            .ends_with("line 1: `#[cfg(unix)] mod z;` is not read as a module")
    );
    write("Cargo.toml", "[package]\nname = \"x\"\n[lib]\npath = \"lib.rs\"\n");
    assert!(error("").ends_with("[lib] path = \"lib.rs\" is not scanned"));
}

#[test]
fn proof_citations() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    let write = |path: &str, text: &str| {
        let path = root.join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    };
    write("Cargo.toml", "[workspace]\nmembers = [\"a\"]\n");
    write(
        "a/Cargo.toml",
        "[package]\nname = \"a-crate\"\n[[test]]\nname = \"hooked\"\nrequired-features = [\"x\"]\n\
         [[test]]\nname = \"custom\"\npath = \"checks/custom.rs\"\nharness = false\n",
    );
    write(
        "a/src/lib.rs",
        "mod m;\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn unit() {\n        \
         \"unit text\";\n    }\n}\n",
    );
    write(
        "a/src/m.rs",
        "#[cfg(any())]\n#[test]\nfn compiled_out() {}\n#[test]\n#[ignore]\nfn ignored() {}\n\
         fn helper() {}\n#[test]\n#[should_panic]\nfn panics() {}\n",
    );
    write("a/tests/flow.rs", "#![cfg(test)]\nmod common;\n/// Docs.\n#[test]\nfn flows() {}\n");
    write(
        "a/tests/common/mod.rs",
        "/// In `flow`'s target.\n#[test]\nfn shared() {\n    \"flow text\";\n}\n",
    );
    write("a/tests/off.rs", "#![cfg(any())]\n#[test]\nfn off() {}\n");
    write("a/tests/twice.rs", "#[test]\nfn t() {}\nmod inner {\n    #[test]\n    fn t() {}\n}\n");
    write("a/tests/hooked.rs", "#[test]\nfn hooked() {}\n");
    write("a/checks/custom.rs", "#[test]\nfn custom() {}\n");
    let none = |_: &Path| Ok(BTreeSet::new());
    let cite = |citation| proof_literals(root, citation, &none);
    assert_eq!(cite("a-crate::lib::unit").unwrap(), ["unit text"]);
    assert_eq!(cite("a-crate::flow::flows").unwrap(), Vec::<String>::new());
    assert_eq!(cite("a-crate::flow::shared").unwrap(), ["flow text"]);
    for (citation, error) in [
        ("a-crate::flow", "not <crate>::<target>::<fn>"),
        ("a crate::lib::unit", "not <crate>::<target>::<fn>"),
        ("b::lib::unit", "b is not a workspace member"),
        ("a-crate::lib::missing", "0 functions named missing"),
        ("a-crate::lib::compiled_out", "0 functions named compiled_out"),
        ("a-crate::lib::helper", "helper is not a #[test]"),
        ("a-crate::lib::ignored", "ignored is ignored or expected to panic"),
        ("a-crate::lib::panics", "panics is ignored or expected to panic"),
        ("a-crate::off::off", "0 functions named off"),
        ("a-crate::twice::t", "2 functions named t"),
        ("a-crate::nothing::x", "test target nothing has 0 root files"),
        (
            "a-crate::hooked::hooked",
            "[[test]] hooked sets required-features: the gate does not run it",
        ),
        ("a-crate::custom::custom", "[[test]] custom sets harness: the gate does not run it"),
    ] {
        assert_eq!(cite(citation), Err(error.to_owned()), "{citation}");
    }
    // Comments, single quotes and a header with `=` in it are read; a file a `[[test]]` of
    // another name takes is that target's only.
    write(
        "a/Cargo.toml",
        "[package] # p\nname = 'a-crate' # n\n# test = false\n[[test]]  # slow\n\
         name = \"renamed\"\npath = \"tests/flow.rs\"\nrequired-features = [\n    \"x\",\n]\n\
         [target.'cfg(target_os = \"linux\")'.dev-dependencies]\nharness = false\n",
    );
    assert_eq!(cite("a-crate::lib::unit").unwrap(), ["unit text"]);
    let taken = format!("{} is [[test]] renamed's root", root.join("a/tests/flow.rs").display());
    assert_eq!(cite("a-crate::flow::flows"), Err(taken));
    assert_eq!(
        cite("a-crate::renamed::flows"),
        Err("[[test]] renamed sets required-features: the gate does not run it".to_owned())
    );
    write("a/Cargo.toml", "[package]\nname = \"a-crate\"\nautotests = false\n");
    let off = "no test target flow (autotests = false)";
    assert_eq!(cite("a-crate::flow::flows"), Err(off.to_owned()));
    write("a/Cargo.toml", "[package]\nname = \"a-crate\"\n[[test]]\nname = \"flow\"\nwhat\n");
    assert_eq!(
        cite("a-crate::flow::flows"),
        Err("Cargo.toml line 5: \"what\" is not read".to_owned())
    );
}

#[test]
fn matching() {
    let row = |matcher: &str| Row {
        line: 0,
        status: "pending",
        owner: "X",
        sense: "expected",
        kind: "literal",
        source: "f.py:1",
        fragment: String::new(),
        matcher: Some(matcher.to_owned()),
        proof: None,
        until: None,
    };
    let lits = |l: &[&str]| l.iter().map(|s| s.to_string()).collect::<Vec<_>>();
    let r = row("a{}b{|}c");
    assert!(emitted(&r, &lits(&["a {} b", "c"])));
    // In order, within one literal.
    assert!(!emitted(&r, &lits(&["b a", "c"])));
    assert!(!emitted(&r, &lits(&["a", "b", "c"])));
    // Every group.
    assert!(!emitted(&r, &lits(&["ab"])));
}

/// DEC-209's `linked` status: the form it needs, and the ratchet on it.
#[test]
fn linked_rows() {
    let row = |status, sense, owner, until| Row {
        line: 0,
        status,
        owner,
        sense,
        kind: "literal",
        source: "f.py:1",
        fragment: "text".to_owned(),
        matcher: None,
        proof: None,
        until,
    };
    let linked = row("linked", "expected", "CH1-node", Some("BL-122"));
    assert_eq!(row_form(&linked), Ok(()));
    // An active literal holds it: it passes; none does: it is stale.
    assert_eq!(ratchet(&linked, true), None);
    assert!(ratchet(&linked, false).is_some_and(|e| e.contains("stale")));
    // It names its owner and a BL-<n> until, and only an expected row is linked.
    assert!(row_form(&row("linked", "expected", "", Some("BL-122"))).is_err());
    for until in [None, Some("BL-"), Some("BL-12x"), Some("N7")] {
        assert!(row_form(&row("linked", "expected", "CH1-node", until)).is_err(), "{until:?}");
    }
    assert!(row_form(&row("linked", "unexpected", "CH1-node", Some("BL-122"))).is_err());
    // DEC-280: an unexpected row is linked only as one of its seven, P3's, until its own item.
    let dec_280 = |owner, until| Row {
        source: "test/functional/p2p_filter.py:117",
        fragment: "Misbehaving".to_owned(),
        ..row("linked", "unexpected", owner, until)
    };
    assert_eq!(row_form(&dec_280("P3", Some("BL-256"))), Ok(()));
    assert!(row_form(&dec_280("P3", Some("BL-122"))).is_err());
    assert!(row_form(&dec_280("EV", Some("BL-256"))).is_err());
    assert!(row_form(&row("linked", "unexpected", "P3", Some("BL-256"))).is_err());
    let other_line = Row {
        source: "test/functional/p2p_filter.py:118",
        ..dec_280("P3", Some("BL-256"))
    };
    assert!(row_form(&other_line).is_err());
    let other_fragment = Row {
        fragment: "text".to_owned(),
        ..dec_280("P3", Some("BL-256"))
    };
    assert!(row_form(&other_fragment).is_err());
    // DEC-282: row 161 waits for DK1's BL-264, not BL-256 or P6b's BL-265.
    let row_161 = |until| Row {
        source: "test/functional/feature_llmq_dkg_intake.py:273",
        fragment: "malformed DKG message".to_owned(),
        ..row("linked", "unexpected", "P3", until)
    };
    assert_eq!(row_form(&row_161(Some("BL-264"))), Ok(()));
    assert!(row_form(&row_161(Some("BL-256"))).is_err());
    assert!(row_form(&row_161(Some("BL-265"))).is_err());
    // An until on any other row, or a proof on a linked one, is refused.
    assert!(row_form(&row("pending", "expected", "CH1-node", Some("BL-122"))).is_err());
    let proved = Row {
        proof: Some("a::lib::t"),
        ..row("linked", "expected", "CH1-node", Some("BL-122"))
    };
    assert!(row_form(&proved).is_err());
    // The other statuses keep their rules.
    let pending = row("pending", "expected", "X", None);
    assert_eq!((row_form(&pending), ratchet(&pending, false)), (Ok(()), None));
    assert!(ratchet(&pending, true).is_some());
    assert!(ratchet(&row("pending", "unexpected", "X", None), true).is_some());
}

