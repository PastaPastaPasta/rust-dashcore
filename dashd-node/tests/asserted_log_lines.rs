/// The `cfg` names only tests, debug builds and tools set (`fuzzing`: cargo-fuzz's builds;
/// `doctest`: rustdoc's; `cap_probe`, with a value: dashd-chainstate's capability probes, CH7b-1
/// F2): off in the production build.
const OFF: &[&str] =
    &["test", "debug_assertions", "clippy", "miri", "loom", "fuzzing", "doctest", "cap_probe"];

/// The `cfg` of one crate in rdashd's production (release) build: the target's values, the
/// crate's resolved features, and [`OFF`]. Any other name, or a predicate that does not parse, is
/// an error, never a guess. It applies to `#[cfg]` attributes; the branches of a `cfg!()`
/// expression both count. With `test`, it is the gate's test build instead (for a proof's
/// target): `test` and `debug_assertions` hold.
struct Cfg<'a> {
    target: &'a Target,
    features: &'a BTreeSet<String>,
    test: bool,
}

impl Cfg<'_> {
    /// Whether `pred`, the text inside `cfg(...)`, holds.
    fn holds(&self, pred: &str) -> Result<bool, String> {
        let (value, rest) = self.predicate(pred)?;
        match rest.trim() {
            "" => Ok(value),
            rest => Err(format!("cfg({pred}): {rest:?} after the predicate")),
        }
    }

    /// Parses one predicate at the start of `s`: whether it holds, and the text after it.
    fn predicate<'s>(&self, s: &'s str) -> Result<(bool, &'s str), String> {
        let s = s.trim_start();
        for op in ["all(", "any(", "not("] {
            let Some(mut rest) = s.strip_prefix(op) else {
                continue;
            };
            let mut parts = Vec::new();
            loop {
                rest = rest.trim_start();
                if let Some(after) = rest.strip_prefix(')') {
                    let value = match (op, parts.as_slice()) {
                        ("all(", _) => parts.iter().all(|&p| p),
                        ("any(", _) => parts.iter().any(|&p| p),
                        (_, [part]) => !part,
                        _ => return Err(format!("{s:?}: not() takes one predicate")),
                    };
                    return Ok((value, after));
                }
                if rest.is_empty() {
                    return Err(format!("{s:?}: unbalanced"));
                }
                let (part, after) = self.predicate(rest)?;
                parts.push(part);
                let after = after.trim_start();
                rest = match after.strip_prefix(',') {
                    Some(next) => next,
                    None if after.starts_with(')') => after,
                    None => return Err(format!("{s:?}: expected `,` or `)` at {after:?}")),
                };
            }
        }
        // `name` or `name = "value"`.
        let end = s.find([',', ')']).unwrap_or(s.len());
        let (name, value) = match s[..end].split_once('=') {
            Some((name, value)) => {
                let value = value.trim();
                let unquoted = value.strip_prefix('"').and_then(|v| v.strip_suffix('"'));
                (name.trim(), Some(unquoted.ok_or_else(|| format!("{s:?}: unquoted value"))?))
            }
            None => (s[..end].trim(), None),
        };
        let t = self.target;
        let value = match (name, value) {
            (name, _) if OFF.contains(&name) => {
                self.test && matches!(name, "test" | "debug_assertions")
            }
            ("unix", None) => t.unix,
            ("windows", None) => t.windows,
            ("feature", Some(v)) => self.features.contains(v),
            ("target_os", Some(v)) => v == t.os,
            ("target_family", Some(v)) => v == t.family,
            ("target_env", Some(v)) => v == t.env,
            ("target_arch", Some(v)) => v == t.arch,
            ("target_pointer_width", Some(v)) => v == t.pointer_width,
            ("target_endian", Some(v)) => v == t.endian,
            ("target_feature", Some(v)) => match t.target_features.iter().find(|(f, _)| *f == v) {
                Some(&(_, on)) => on,
                None => return Err(format!("target_feature = {v:?} is not in the target table")),
            },
            ("target_has_atomic", Some(v)) => match t.atomics.iter().find(|(w, _)| *w == v) {
                Some(&(_, on)) => on,
                None => {
                    return Err(format!("target_has_atomic = {v:?} is not in the target table"));
                }
            },
            _ => return Err(format!("unknown cfg {:?}", s[..end].trim())),
        };
        Ok((value, &s[end..]))
    }
}

/// `src` without the items whose `cfg` attribute does not hold. An item ends at the `;` or `}`
/// that closes it at bracket depth 0; a field, variant, match arm or expression (an item not
/// opened by a keyword) also at a `,` there, and a block's tail expression where the block does.
/// The attributes above a cut item go with it. A file whose inner `#![cfg]` (before its first
/// item) does not hold is empty; one further down, and kept `#[path]` modules, are errors: the
/// scan does not follow them.
fn production(src: &str, cfg: &Cfg) -> Result<String, String> {
    let lines: Vec<&str> = src.split_inclusive('\n').collect();
    let mut out = String::new();
    let mut i = 0;
    // Before the file's first item, where its inner attributes are.
    let mut top = true;
    while i < lines.len() {
        let at = |e: String| format!("line {}: {e}", i + 1);
        let trimmed = lines[i].trim_start();
        let inner = trimmed.starts_with("#![cfg(");
        if trimmed.starts_with("#[path") || inner && !top {
            return Err(at(format!("{} is not followed", trimmed.trim_end())));
        }
        top &=
            trimmed.trim_end().is_empty() || trimmed.starts_with("//") || trimmed.starts_with("#!");
        let opener = if inner {
            "#![cfg("
        } else {
            "#[cfg("
        };
        if !trimmed.starts_with(opener) {
            out.push_str(lines[i]);
            i += 1;
            continue;
        }
        // A `cfg` attribute may span lines (rustfmt breaks long ones): up to its `]`.
        let mut last = i;
        let mut attr = lines[i].to_owned();
        let open = |a: &str| a.matches('(').count() > a.matches(')').count();
        while open(&attr) && last + 1 < lines.len() {
            last += 1;
            attr.push_str(lines[last]);
        }
        let attr_end = lines[last].find(")]").map(|e| e + 2).ok_or_else(|| at("no `)]`".into()))?;
        let close = attr.len() - lines[last].len() + attr_end;
        let pred = attr[attr.find(opener).unwrap() + opener.len()..close - 2].replace('\n', " ");
        if cfg.holds(&pred).map_err(at)? {
            out.push_str(lines[i]);
            i += 1;
            continue;
        }
        if inner {
            return Ok(String::new());
        }
        // The attributes and doc comments kept above it are the item's.
        loop {
            let start = out.trim_end_matches('\n').rfind('\n').map_or(0, |n| n + 1);
            let last = out[start..].trim_start();
            if !(last.starts_with("#[") || last.starts_with("///")) {
                break;
            }
            out.truncate(start);
        }
        // The item: after the attribute on its line, else past further attributes and comments.
        let (mut j, mut text) = (last, lines[last][attr_end..].trim_start());
        while text.is_empty() || text.starts_with("#[") || text.starts_with("//") {
            j += 1;
            let Some(l) = lines.get(j) else {
                return Err(at("no item after the attribute".into()));
            };
            text = l.trim_start();
        }
        let decl = unqualified(text);
        let keyword = decl.split_whitespace().next().is_some_and(|w| {
            [
                "fn",
                "mod",
                "impl",
                "struct",
                "enum",
                "union",
                "const",
                "static",
                "type",
                "use",
                "trait",
                "let",
                "macro_rules!",
                "unsafe",
                "async",
                "extern",
            ]
            .contains(&w)
        });
        i = item_end(&lines, j, lines[j].len() - text.len(), keyword).map_err(at)? + 1;
    }
    Ok(out)
}

/// An item's text past its visibility (`pub`, `pub(crate)`, `pub(in path)`, ...).
fn unqualified(item: &str) -> &str {
    if let Some(rest) = item.strip_prefix("pub(") {
        return rest.split_once(')').map_or(item, |(_, after)| after.trim_start());
    }
    item.strip_prefix("pub ").unwrap_or(item)
}

/// The out-of-line modules (`mod name;`) a file's kept text declares. One declared inside an
/// inline module (an indented declaration) is an error: its file would be one level down.
fn declared_modules(kept: &str) -> Result<Vec<String>, String> {
    let mut out = Vec::new();
    for (n, line) in kept.lines().enumerate() {
        let code = line.split("//").next().unwrap().trim_end();
        let parsed =
            unqualified(code.trim_start()).strip_prefix("mod ").and_then(|d| d.strip_suffix(';'));
        let at = format!("line {}", n + 1);
        match parsed {
            Some(_) if code.starts_with(char::is_whitespace) => {
                return Err(format!("{at}: `{}` inside an inline module", code.trim()));
            }
            Some(name) => out.push(name.trim().to_owned()),
            // Anything else declaring a module (`#[attr] mod x;` on one line, say) is not read.
            None if code.ends_with(';') && has_word(code, "mod") => {
                return Err(format!("{at}: `{}` is not read as a module", code.trim()));
            }
            None => {}
        }
    }
    Ok(out)
}

/// Whether `word` appears in `text` as a whole word.
fn has_word(text: &str, word: &str) -> bool {
    let ident = |c: Option<char>| c.is_some_and(|c| c.is_alphanumeric() || c == '_');
    text.match_indices(word).any(|(at, _)| {
        !ident(text[..at].chars().next_back()) && !ident(text[at + word.len()..].chars().next())
    })
}

/// The line on which the item starting at `lines[line][col..]` ends (see [`production`]).
fn item_end(lines: &[&str], line: usize, col: usize, keyword: bool) -> Result<usize, String> {
    let b: Vec<char> = lines[line..].concat()[col..].chars().collect();
    let on = |k: usize| line + b[..k].iter().filter(|&&c| c == '\n').count();
    let mut depth = 0i32;
    let mut k = 0;
    while k < b.len() {
        match b[k] {
            '/' if b.get(k + 1) == Some(&'/') => {
                while k + 1 < b.len() && b[k + 1] != '\n' {
                    k += 1;
                }
            }
            '/' if b.get(k + 1) == Some(&'*') => {
                k += 2;
                while k + 1 < b.len() && !(b[k] == '*' && b[k + 1] == '/') {
                    k += 1;
                }
                k += 1;
            }
            'r' if matches!(b.get(k + 1), Some('"') | Some('#')) && raw_start(&b, k) => {
                let hashes = b[k + 1..].iter().take_while(|&&c| c == '#').count();
                if b.get(k + 1 + hashes) == Some(&'"') {
                    k += 2 + hashes;
                    while k < b.len()
                        && !(b[k] == '"' && (1..=hashes).all(|h| b.get(k + h) == Some(&'#')))
                    {
                        k += 1;
                    }
                    k += hashes;
                }
            }
            '"' => {
                k += 1;
                while k < b.len() && b[k] != '"' {
                    k += if b[k] == '\\' {
                        2
                    } else {
                        1
                    };
                }
            }
            // A char literal ('x', '\'', '\u{..}') or a lifetime ('a), escapes first.
            '\'' if b.get(k + 1) == Some(&'\\') => {
                k += 3;
                while k < b.len() && b[k] != '\'' {
                    k += 1;
                }
            }
            '\'' if b.get(k + 2) == Some(&'\'') => k += 2,
            '{' | '(' | '[' => depth += 1,
            '}' | ')' | ']' => {
                depth -= 1;
                if depth < 0 {
                    // A block's tail expression ends where the block does: on the line before a
                    // bracket that starts its own line.
                    let line_start = b[..k].iter().rposition(|&c| c == '\n');
                    if line_start.is_some_and(|s| b[s + 1..k].iter().all(|c| c.is_whitespace())) {
                        return Ok(on(k) - 1);
                    }
                    return Err(format!("the item ran past its block at line {}", on(k) + 1));
                }
                if depth == 0 && b[k] == '}' {
                    // The item's block closed; a trailing `;` or `,` is on the same line.
                    return Ok(on(k));
                }
            }
            ';' if depth == 0 => return Ok(on(k)),
            ',' if depth == 0 && !keyword => return Ok(on(k)),
            _ => {}
        }
        k += 1;
    }
    Err("the item does not end".into())
}

/// The string literals in Rust source, unescaped, with format strings' `{{`/`}}` undone.
fn string_literals(src: &str, out: &mut Vec<String>) {
    let b: Vec<char> = src.chars().collect();
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            '/' if b.get(i + 1) == Some(&'/') => {
                while i < b.len() && b[i] != '\n' {
                    i += 1;
                }
            }
            '/' if b.get(i + 1) == Some(&'*') => {
                i += 2;
                while i + 1 < b.len() && !(b[i] == '*' && b[i + 1] == '/') {
                    i += 1;
                }
                i += 2;
            }
            '\'' => {
                // A char literal ('x', '\n', '\u{..}') or a lifetime ('a).
                if b.get(i + 1) == Some(&'\\') {
                    // Past the backslash and the escaped char (which may be a quote).
                    i += 3;
                    while i < b.len() && b[i] != '\'' {
                        i += 1;
                    }
                    i += 1;
                } else if b.get(i + 2) == Some(&'\'') {
                    i += 3;
                } else {
                    i += 1;
                }
            }
            'r' if matches!(b.get(i + 1), Some('"') | Some('#')) && raw_start(&b, i) => {
                let mut j = i + 1;
                let mut hashes = 0;
                while b.get(j) == Some(&'#') {
                    hashes += 1;
                    j += 1;
                }
                if b.get(j) != Some(&'"') {
                    i += 1;
                    continue;
                }
                let start = j + 1;
                let mut k = start;
                loop {
                    if k >= b.len() {
                        break;
                    }
                    if b[k] == '"' && (0..hashes).all(|h| b.get(k + 1 + h) == Some(&'#')) {
                        break;
                    }
                    k += 1;
                }
                out.push(format_text(&b[start..k.min(b.len())].iter().collect::<String>()));
                i = k + 1 + hashes;
            }
            '"' => {
                let mut text = String::new();
                i += 1;
                while i < b.len() && b[i] != '"' {
                    if b[i] == '\\' {
                        i += 1;
                        match b.get(i) {
                            Some('n') => text.push('\n'),
                            Some('t') => text.push('\t'),
                            Some('r') => text.push('\r'),
                            Some('0') => text.push('\0'),
                            Some('u') => {
                                let close = (i..b.len()).find(|&k| b[k] == '}').unwrap();
                                let hex: String = b[i + 2..close].iter().collect();
                                text.extend(
                                    u32::from_str_radix(&hex, 16).ok().and_then(char::from_u32),
                                );
                                i = close;
                            }
                            Some('x') => {
                                let hex: String = b[i + 1..i + 3].iter().collect();
                                text.extend(u8::from_str_radix(&hex, 16).ok().map(char::from));
                                i += 2;
                            }
                            // A line continuation: the newline and the next line's indent go.
                            Some('\n') => {
                                while b.get(i + 1).is_some_and(|c| c.is_whitespace()) {
                                    i += 1;
                                }
                            }
                            Some(&c) => text.push(c),
                            None => {}
                        }
                    } else {
                        text.push(b[i]);
                    }
                    i += 1;
                }
                i += 1;
                out.push(format_text(&text));
            }
            _ => i += 1,
        }
    }
}

/// Whether the `r` at `i` starts a raw string (`r"`, `r#"`, `br"`), not an identifier's end.
fn raw_start(b: &[char], i: usize) -> bool {
    let ident = |c: char| c.is_alphanumeric() || c == '_';
    match i.checked_sub(1).map(|p| b[p]) {
        None => true,
        Some('b') => i < 2 || !ident(b[i - 2]),
        Some(c) => !ident(c),
    }
}

fn format_text(text: &str) -> String {
    text.replace("{{", "{").replace("}}", "}")
}

/// Files of the production build whose literals are data no code logs, left out of the tripwire
/// (`<crate dir>/<path>`): Core's verbatim RPC help text, which quotes log-like phrases ("was not
/// accepted") in command descriptions (RP0-D8).
const NOT_EMITTERS: &[&str] = &["dash-rpc-spec/src/generated.rs"];

/// Every string literal of rdashd's production build (see [`closure`] and [`production`]),
/// [`NOT_EMITTERS`] left out.
fn node_literals() -> Vec<String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().canonicalize().unwrap();
    let skipped: Vec<PathBuf> = NOT_EMITTERS.iter().map(|f| root.join(f)).collect();
    let mut out = Vec::new();
    let mut seen = Vec::new();
    for (krate, features) in closure(&root) {
        let cfg = Cfg {
            target: &HOST,
            features: &features,
            test: false,
        };
        let bins = krate == root.join("rdashd");
        for (path, kept) in crate_files(&krate, &cfg, bins).unwrap_or_else(|e| panic!("{e}")) {
            if skipped.contains(&path) {
                seen.push(path);
                continue;
            }
            string_literals(&kept, &mut out);
        }
    }
    // A stale entry would hide nothing; it must name a file the build compiles.
    for path in &skipped {
        assert!(seen.contains(path), "NOT_EMITTERS: {} is not in rdashd's build", path.display());
    }
    out
}

/// The source files a crate's production build compiles, with their kept text (see
/// [`production`]): its library (`src/lib.rs`) and, with `bins` (rdashd itself; a dependency's
/// binaries are not linked), its binaries (`src/main.rs`, `src/bin/`), then the modules their
/// kept text declares, each `name.rs` or `name/mod.rs` in the declaring module's directory (a
/// crate root's or `mod.rs`'s own, else the one named after the file). A target the manifest puts
/// elsewhere, and a declared module with no file or two, are errors.
fn crate_files(krate: &Path, cfg: &Cfg, bins: bool) -> Result<Vec<(PathBuf, String)>, String> {
    let src = krate.join("src");
    let roots: &[&str] = if bins {
        &["lib.rs", "main.rs"]
    } else {
        &["lib.rs"]
    };
    let mut todo: Vec<PathBuf> =
        roots.iter().map(|r| src.join(r)).filter(|p| p.is_file()).collect();
    if let Some(entries) = bins.then(|| std::fs::read_dir(src.join("bin")).ok()).flatten() {
        for e in entries {
            let path = e.unwrap().path();
            if path.is_dir() {
                todo.push(path.join("main.rs"));
            } else if path.extension().is_some_and(|x| x == "rs") {
                todo.push(path);
            }
        }
    }
    let manifest = std::fs::read_to_string(krate.join("Cargo.toml")).unwrap();
    let mut section = "";
    for line in manifest.lines().map(str::trim) {
        if line.starts_with('[') {
            section = line;
        } else if (section == "[lib]" || bins && section == "[[bin]]") && line.starts_with("path") {
            let target = krate.join(line.split('"').nth(1).unwrap_or_default());
            if !todo.contains(&target) {
                return Err(format!("{}: {section} {line} is not scanned", krate.display()));
            }
        }
    }
    module_files(todo, cfg)
}

/// `roots` and the modules their kept text declares, with their kept text (see [`crate_files`]).
fn module_files(roots: Vec<PathBuf>, cfg: &Cfg) -> Result<Vec<(PathBuf, String)>, String> {
    let mut todo = roots.clone();
    let mut files = Vec::new();
    while let Some(path) = todo.pop() {
        let at = |e: String| format!("{}: {e}", path.display());
        let kept = production(&std::fs::read_to_string(&path).map_err(|e| at(e.to_string()))?, cfg)
            .map_err(at)?;
        let dir = if roots.contains(&path) || path.file_stem().unwrap() == "mod" {
            path.parent().unwrap().to_path_buf()
        } else {
            path.with_extension("")
        };
        for name in declared_modules(&kept).map_err(at)? {
            let found: Vec<PathBuf> =
                [dir.join(format!("{name}.rs")), dir.join(&name).join("mod.rs")]
                    .into_iter()
                    .filter(|p| p.is_file())
                    .collect();
            match found.as_slice() {
                [file] => todo.push(file.clone()),
                _ => return Err(at(format!("`mod {name};` has {} files", found.len()))),
            }
        }
        files.push((path, kept));
    }
    Ok(files)
}

fn emitted(row: &Row, literals: &[String]) -> bool {
    held(&groups(row), literals)
}

/// Whether every group appears, in order, within one of `literals`.
fn held(groups: &[Vec<String>], literals: &[String]) -> bool {
    !groups.is_empty() && groups.iter().all(|g| literals.iter().any(|l| in_order(l, g)))
}

/// Whether `pieces` appear in `literal` one after another.
fn in_order(literal: &str, pieces: &[String]) -> bool {
    let mut rest = literal;
    pieces.iter().all(|p| match rest.find(p.as_str()) {
        Some(at) => {
            rest = &rest[at + p.len()..];
            true
        }
        None => false,
    })
}

/// A manifest table's keys and values.
type Table<'a> = BTreeMap<&'a str, &'a str>;

/// A manifest's tables in order, each header (`[lib]`, `[[test]]`; `""` before the first) with
/// its `key = value` lines: a quoted string unquoted, any other value (an array, a number) as
/// written. Comments are dropped. Enough for the keys read here, not a TOML parser: a line it
/// cannot read is an error, never skipped.
fn tables(manifest: &str) -> Result<Vec<(&str, Table<'_>)>, String> {
    let mut out = vec![("", BTreeMap::new())];
    let mut in_array = false;
    for (n, line) in manifest.lines().enumerate() {
        let line = uncommented(line).trim();
        if in_array {
            in_array = !line.ends_with(']');
        } else if line.starts_with('[') {
            out.push((line, BTreeMap::new()));
        } else if let Some((key, value)) = line.split_once('=') {
            let value = value.trim();
            let unquoted = [('"', '"'), ('\'', '\'')].into_iter().find_map(|(open, close)| {
                value.strip_prefix(open)?.strip_suffix(close).filter(|v| !v.contains(close))
            });
            in_array = value.starts_with('[') && !value.ends_with(']');
            out.last_mut().unwrap().1.insert(unquote(key.trim()), unquoted.unwrap_or(value));
        } else if !line.is_empty() {
            return Err(format!("Cargo.toml line {}: {line:?} is not read", n + 1));
        }
    }
    Ok(out)
}

/// `line` up to a `#` outside a string.
fn uncommented(line: &str) -> &str {
    let mut quote = None;
    for (i, c) in line.char_indices() {
        match (quote, c) {
            (None, '"' | '\'') => quote = Some(c),
            (Some(q), _) if c == q => quote = None,
            (None, '#') => return &line[..i],
            _ => {}
        }
    }
    line
}

fn unquote(value: &str) -> &str {
    value.trim_matches('"')
}

/// The `header` table of a manifest's `tables`.
fn table<'t>(tables: &'t [(&str, Table<'_>)], header: &str) -> Option<&'t Table<'t>> {
    tables.iter().find(|(h, _)| *h == header).map(|(_, t)| t)
}

fn manifest(dir: &Path) -> Result<String, String> {
    std::fs::read_to_string(dir.join("Cargo.toml")).map_err(|e| format!("{}: {e}", dir.display()))
}

/// The directory of the workspace member under `root` whose package is `name`.
fn workspace_member(root: &Path, name: &str) -> Result<PathBuf, String> {
    let text = manifest(root)?;
    let root_tables = tables(&text)?;
    let members = table(&root_tables, "[workspace]")
        .and_then(|t| t.get("members")?.strip_prefix('[')?.strip_suffix(']'))
        .ok_or("no one-line `members = [...]` in the workspace manifest")?;
    for member in members.split(',').map(|m| unquote(m.trim())).filter(|m| !m.is_empty()) {
        let dir = root.join(member);
        let text = manifest(&dir)?;
        if table(&tables(&text)?, "[package]").and_then(|t| t.get("name")) == Some(&name) {
            return Ok(dir);
        }
    }
    Err(format!("{name} is not a workspace member"))
}

/// The root file of `krate`'s test target `target`, if the gate's `cargo test --workspace` runs
/// its tests: the library's unit tests (`lib`), or an integration test: a `[[test]]`, else (with
/// `autotests`) `tests/<target>.rs` or `tests/<target>/main.rs` when no `[[test]]` takes that
/// file. A target with `required-features` (the workspace run does not enable them),
/// `test = false` or `harness = false` is an error.
fn test_target(krate: &Path, target: &str) -> Result<PathBuf, String> {
    let text = manifest(krate)?;
    let tables = tables(&text)?;
    let runs = |header: &str, t: &Table| {
        let refused =
            [("required-features", None), ("test", Some("false")), ("harness", Some("false"))];
        match refused
            .into_iter()
            .find(|(key, bad)| t.get(key).is_some_and(|v| bad.is_none_or(|b| *v == b)))
        {
            Some((key, _)) => {
                Err(format!("{header} {target} sets {key}: the gate does not run it"))
            }
            None => Ok(()),
        }
    };
    let inferred = |name: &str| {
        let candidates = [format!("tests/{name}.rs"), format!("tests/{name}/main.rs")];
        let found: Vec<PathBuf> =
            candidates.iter().map(|c| krate.join(c)).filter(|p| p.is_file()).collect();
        match <[PathBuf; 1]>::try_from(found) {
            Ok([path]) => Ok(path),
            Err(found) => Err(format!("test target {name} has {} root files", found.len())),
        }
    };
    if target == "lib" {
        let lib = table(&tables, "[lib]");
        if let Some(t) = lib {
            runs("[lib]", t)?;
        }
        let path = krate.join(lib.and_then(|t| t.get("path")).unwrap_or(&"src/lib.rs"));
        return if path.is_file() {
            Ok(path)
        } else {
            Err("no library".into())
        };
    }
    let mut declared = Vec::new();
    for (_, t) in tables.iter().filter(|(h, _)| *h == "[[test]]") {
        let name = *t.get("name").ok_or("a [[test]] without a name")?;
        let path = match t.get("path") {
            Some(path) => krate.join(path),
            None => inferred(name)?,
        };
        declared.push((name, path, t));
    }
    if let Some((_, path, t)) = declared.iter().find(|(name, ..)| *name == target) {
        runs("[[test]]", t)?;
        return Ok(path.clone());
    }
    if table(&tables, "[package]").and_then(|t| t.get("autotests")) == Some(&"false") {
        return Err(format!("no test target {target} (autotests = false)"));
    }
    let path = inferred(target)?;
    match declared.iter().find(|(_, p, _)| *p == path) {
        Some((name, ..)) => Err(format!("{} is [[test]] {name}'s root", path.display())),
        None => Ok(path),
    }
}

/// The kept text of the file holding `fn name` among `files`: exactly one function of that
/// name, a `#[test]`, neither `#[ignore]`d nor `#[should_panic]`.
fn test_fn<'f>(files: &'f [(PathBuf, String)], name: &str) -> Result<&'f str, String> {
    let mut found = Vec::new();
    for (_, kept) in files {
        let mut attrs = Vec::new();
        for line in kept.lines().map(str::trim) {
            let decl = unqualified(line);
            let decl = decl.strip_prefix("async ").unwrap_or(decl);
            if let Some(rest) = decl.strip_prefix("fn ") {
                if rest.strip_prefix(name).is_some_and(|r| r.starts_with(['(', '<'])) {
                    found.push((kept.as_str(), attrs.clone()));
                }
                attrs.clear();
            } else if line.starts_with("#[") {
                attrs.push(line);
            } else if !line.starts_with("//") {
                attrs.clear();
            }
        }
    }
    let [(kept, attrs)] = found.as_slice() else {
        return Err(format!("{} functions named {name}", found.len()));
    };
    if !attrs.iter().any(|a| *a == "#[test]" || a.starts_with("#[tokio::test")) {
        return Err(format!("{name} is not a #[test]"));
    }
    if attrs.iter().any(|a| a.contains("ignore") || a.contains("should_panic")) {
        return Err(format!("{name} is ignored or expected to panic"));
    }
    Ok(kept)
}

/// The string literals of the file holding the test a proof cites (`<crate>::<target>::<fn>`,
/// see [`test_target`] and [`test_fn`]), its target's files read as the gate's test build of
/// that crate: for [`GATE`], whatever the host, with the crate's `features` there.
fn proof_literals(
    root: &Path,
    citation: &str,
    features: &dyn Fn(&Path) -> Result<BTreeSet<String>, String>,
) -> Result<Vec<String>, String> {
    let parts: Vec<&str> = citation.split("::").collect();
    let word =
        |w: &str| !w.is_empty() && w.chars().all(|c| c.is_ascii_alphanumeric() || "_-".contains(c));
    let (krate, target, name) = match parts[..] {
        [krate, target, name] if parts.iter().all(|p| word(p)) => (krate, target, name),
        _ => return Err("not <crate>::<target>::<fn>".into()),
    };
    let dir = workspace_member(root, krate)?;
    let features = features(&dir)?;
    let cfg = Cfg {
        target: &GATE,
        features: &features,
        test: true,
    };
    let files = module_files(vec![test_target(&dir, target)?], &cfg)?;
    let mut literals = Vec::new();
    string_literals(test_fn(&files, name)?, &mut literals);
    Ok(literals)
}

