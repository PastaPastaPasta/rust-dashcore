/// One row's form: its columns' values, a proof exactly on an `implemented` row, and a `linked`
/// row's owner and `until` (DEC-209).
fn row_form(r: &Row) -> Result<(), String> {
    if !matches!(r.status, "implemented" | "pending" | "linked") {
        return Err(format!("status {}", r.status));
    }
    if !matches!(r.sense, "expected" | "unexpected") {
        return Err(format!("sense {}", r.sense));
    }
    if !matches!(r.kind, "literal" | "fstring") {
        return Err(format!("kind {}", r.kind));
    }
    if r.owner.is_empty() || r.owner.contains(' ') {
        return Err(format!("owner {:?}", r.owner));
    }
    if !r.source.contains(':') {
        return Err(format!("source {:?}", r.source));
    }
    if groups(r).is_empty() {
        return Err("no text to look for".to_owned());
    }
    if (r.status == "implemented") != r.proof.is_some() {
        return Err("an implemented row, and only one, cites a proof".to_owned());
    }
    let backlog = |u: &str| {
        u.strip_prefix("BL-")
            .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
    };
    match (r.status, r.until) {
        ("linked", Some(u)) if backlog(u) => {}
        ("linked", until) => {
            return Err(format!("a linked row names a BL-<n> until, not {until:?}"));
        }
        (_, Some(u)) => return Err(format!("only a linked row has an until ({u:?})")),
        (_, None) => {}
    }
    // DEC-209: an unexpected line in rdashd's build needs its owner's runtime proof. DEC-280's one
    // exception: the negative rows P3's network composition brought in, linked until the item
    // DEC-280 or DEC-282 names (P3 proves their silence before S6a or S6b rides a train).
    let dec_280 = r.owner == "P3"
        && DEC_280_ROWS.iter().any(|&(source, fragment, until)| {
            (source, fragment, Some(until)) == (r.source, r.fragment.as_str(), r.until)
        });
    if r.status == "linked" && r.sense != "expected" && !dec_280 {
        return Err("only an expected row, or a DEC-280 one, can be linked".to_owned());
    }
    Ok(())
}

