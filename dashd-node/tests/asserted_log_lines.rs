//! The ratchet over `asserted_log_lines.txt` (DEC-201 Q15, DEC-204), the debug-log fragments Dash
//! Core's functional tests assert. The list is a tracking ledger with cited runtime proof: every
//! asserted fragment has a row, and an `implemented` row cites the test that shows it in
//! rdashd's real output (the process's debug log, or the node's log sink): the line appears
//! (`expected`), or stays out where Core asserts so (`unexpected`). The list does not inventory
//! rdashd's log lines.
//! - every `implemented` row, and no `pending` one, cites `<crate>::<target>::<fn>`: a `#[test]`
//!   in a target the gate's `cargo test --workspace` runs, whose file names the row's text (see
//!   [`proof_literals`]). The citation is checked, not what the test asserts: a reviewer judges
//!   that when a status changes;
//! - a tripwire, no evidence on its own: the string literals of rdashd's production build (the
//!   in-repo crates `cargo tree -p rdashd -e normal` lists, with the `cfg` of that build
//!   evaluated, see [`Cfg`]). An `implemented` row whose text (or match) no active literal holds
//!   fails: its emitter is gone. A `pending` row one holds fails: an `expected` row is flipped,
//!   with its proof, once its owner emits it; an `unexpected` row once its owner has shown the line
//!   stays silent where the test asserts so. Only literal text is seen: a line an emitter composes
//!   at runtime is seen through a row's `match` naming that emitter's literals;
//! - a `linked` row (DEC-209) is an `expected` line whose emitter is in rdashd's build but which
//!   rdashd cannot reach yet: it names its owner and the backlog item that flips it (`until`),
//!   cites no proof, and fails once no active literal holds it (stale). DEC-280 also lets the seven
//!   `unexpected` rows P3's network composition brought in be linked (owner P3, until the item
//!   `DEC_280_ROWS` names: BL-256, or DEC-282's BL-264 and BL-265), and no others; P3 proves their
//!   silence before S6a or S6b rides a train.
//!
//! The list is generated by `contrib/node/asserted-logs.py`, which also checks it is in sync with
//! the pinned Core tree (that needs the tree, so it is a gate and CI step, not this test).

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::Command;

const LIST: &str = include_str!("asserted_log_lines.txt");

struct Row<'a> {
    line: usize,
    status: &'a str,
    owner: &'a str,
    sense: &'a str,
    kind: &'a str,
    source: &'a str,
    fragment: String,
    matcher: Option<String>,
    /// The test an `implemented` row cites (DEC-204): `<crate>::<target>::<fn>`.
    proof: Option<&'a str>,
    /// The backlog item a `linked` row waits for (DEC-209): `BL-<n>`.
    until: Option<&'a str>,
}

fn unescape(text: &str) -> String {
    let mut out = String::new();
    let mut chars = text.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('\\') => out.push('\\'),
            other => panic!("bad escape \\{other:?} in {text:?}"),
        }
    }
    out
}

fn rows() -> Vec<Row<'static>> {
    let mut out = Vec::new();
    for (i, line) in LIST.lines().enumerate() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let cells: Vec<&str> = line.split('\t').collect();
        assert!(matches!(cells.len(), 6..=9), "line {}: {} columns", i + 1, cells.len());
        out.push(Row {
            line: i + 1,
            status: cells[0],
            owner: cells[1],
            sense: cells[2],
            kind: cells[3],
            source: cells[4],
            fragment: unescape(cells[5]),
            matcher: cells.get(6).filter(|m| !m.is_empty()).map(|m| unescape(m)),
            proof: cells.get(7).copied().filter(|p| !p.is_empty()),
            until: cells.get(8).copied().filter(|u| !u.is_empty()),
        });
    }
    out
}

/// What a row's text must show in Rust: its `match`, or its fragment, as groups of literal
/// pieces. A group is the text between `{|}` marks (where the line is composed from several Rust
/// literals); its pieces are cut at the placeholders that stand for runtime values (`{expr}` in
/// Core's f-strings, `{}` in a match), and must appear in order within one literal.
fn groups(row: &Row) -> Vec<Vec<String>> {
    text_groups(row.matcher.as_deref().unwrap_or(&row.fragment))
}

fn text_groups(text: &str) -> Vec<Vec<String>> {
    text.split("{|}").map(pieces).filter(|g| !g.is_empty()).collect()
}

fn pieces(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(open) = rest.find('{') {
        out.push(rest[..open].to_owned());
        let close = rest[open..].find('}').map_or(rest.len(), |c| open + c + 1);
        rest = &rest[close..];
    }
    out.push(rest.to_owned());
    out.retain(|p| !p.is_empty());
    out
}

/// The in-repo crates of rdashd's production build, each with its resolved features, as
/// `cargo tree -p rdashd -e normal` reports them (its normal dependencies, transitively; no dev-
/// or build-dependencies). `cargo tree` resolves for the host, so the test's own target (see
/// [`HOST`]) matches it in a native run only.
fn closure(root: &Path) -> Vec<(PathBuf, BTreeSet<String>)> {
    let crates = cargo_tree(root, &["-p", "rdashd", "-e", "normal"]);
    assert!(crates.iter().any(|(dir, _)| dir.ends_with("rdashd")), "{crates:?}");
    crates
}

/// `cargo tree` under `root` for `selection` (packages and edges; see [`tree_packages`]).
fn cargo_tree(root: &Path, selection: &[&str]) -> Vec<(PathBuf, BTreeSet<String>)> {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let out = Command::new(cargo)
        .current_dir(root)
        .arg("tree")
        .args(selection)
        .args(["--prefix", "none", "--format", "{p}|{f}", "--offline", "--locked"])
        .output()
        .unwrap();
    let text = String::from_utf8(out.stdout).unwrap();
    assert!(out.status.success(), "cargo tree: {}", String::from_utf8_lossy(&out.stderr));
    tree_packages(&text, root)
}

/// The packages under `root` in `cargo tree --format '{p}|{f}'` output: their directories and
/// features. A package listed twice must have the same features both times.
fn tree_packages(text: &str, root: &Path) -> Vec<(PathBuf, BTreeSet<String>)> {
    let mut out = BTreeMap::new();
    for line in text.lines().map(|l| l.trim_end_matches(" (*)")).filter(|l| !l.is_empty()) {
        let (package, features) = line.rsplit_once('|').unwrap();
        // `name vX.Y.Z (/path)`; registry and git packages have no path, or one elsewhere.
        let Some(dir) = package
            .rsplit_once(" (")
            .and_then(|(_, p)| p.strip_suffix(')'))
            .map(PathBuf::from)
            .filter(|p| p.starts_with(root))
        else {
            continue;
        };
        let features: BTreeSet<String> =
            features.split(',').filter(|f| !f.is_empty()).map(str::to_owned).collect();
        let old = out.insert(dir, features.clone());
        assert!(old.is_none_or(|old| old == features), "{line}");
    }
    out.into_iter().collect()
}

