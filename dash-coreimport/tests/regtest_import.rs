const KEY: [u8; 8] = [0x5c, 0x9b, 0x2f, 0x71, 0xf0, 0x03, 0x66, 0xe3];

fn write_chainstate(dir: &Path, wal: &[u8]) {
    fs::create_dir_all(dir).unwrap();
    fs::write(dir.join("CURRENT"), CURRENT).unwrap();
    fs::write(dir.join("MANIFEST-000004"), MANIFEST).unwrap();
    fs::write(dir.join("000005.ldb"), TABLE).unwrap();
    fs::write(dir.join("000006.log"), wal).unwrap();
    fs::write(dir.join("LOCK"), b"").unwrap();
}

fn holds_key(bytes: &[u8]) -> bool {
    bytes.windows(OBFUSCATE_KEY_KEY.len()).any(|w| w == OBFUSCATE_KEY_KEY)
}

#[test]
fn the_cache_chainstate_key_is_in_its_table_only() {
    let digest: String =
        sha256::Hash::hash(WAL).to_byte_array().iter().map(|b| format!("{b:02x}")).collect();
    assert_eq!(digest, WAL_SHA256);
    assert!(holds_key(&TABLE));
    assert!(!holds_key(WAL));
    let temp = tempfile::tempdir().unwrap();
    write_chainstate(temp.path(), WAL);
    assert_eq!(obfuscate_key(temp.path()).unwrap(), ObfuscateKey::Present(KEY));
    let mut value = vec![8];
    value.extend(KEY);
    assert_eq!(
        LevelDbReader::open(temp.path()).unwrap().get(OBFUSCATE_KEY_KEY).unwrap(),
        Some(value)
    );
}

#[test]
fn prefixes_of_the_cache_wal_keep_the_key() {
    let temp = tempfile::tempdir().unwrap();
    write_chainstate(temp.path(), WAL);
    let ends = (0..64).chain((64..WAL.len() - 64).step_by(61)).chain(WAL.len() - 64..WAL.len());
    for len in ends {
        fs::write(temp.path().join("000006.log"), &WAL[..len]).unwrap();
        assert_eq!(obfuscate_key(temp.path()).unwrap(), ObfuscateKey::Present(KEY), "len {len}");
    }
}

#[test]
fn the_cache_chainstate_moves_aside_unchanged() {
    let temp = tempfile::tempdir().unwrap();
    let net = temp.path().join("regtest");
    write_chainstate(&net.join("chainstate"), WAL);
    fs::create_dir_all(net.join("blocks/index")).unwrap();
    fs::write(net.join("blocks/blk00000.dat"), b"blk").unwrap();
    let fs = OsImportFs::new();
    let backup = begin(&fs, &net).unwrap().complete(&fs).unwrap();
    assert_eq!(obfuscate_key(&backup.join("chainstate")).unwrap(), ObfuscateKey::Present(KEY));
    assert_eq!(fs::read(backup.join("chainstate/000006.log")).unwrap(), WAL);
    assert!(backup.join(JOURNAL).is_file());
    assert!(!net.join("chainstate").exists() && !net.join("blocks/index").exists());
    assert!(net.join("blocks/blk00000.dat").is_file());
    assert_eq!(recover(&fs, &net).unwrap(), Recovered::Clean);
}
